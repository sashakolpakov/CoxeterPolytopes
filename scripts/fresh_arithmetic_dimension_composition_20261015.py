#!/usr/bin/env python3
"""Compose complete field-specific certificates with published field bounds.

This is a dependency and logical-coverage binder. It does not independently
reprove the imported mathematical theorems or the field-specific calculations.
"""
import argparse
import json
from hashlib import sha256
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TAG = 'fresh_arithmetic_dimension_composition_20261015'


def run(bound):
    assert bound in (23, 24, 25, 26, 27)
    q5tag = f'fresh_sqrt5_dimension{bound}_coverage_20261015'
    tags = [q5tag, 'fresh_sqrt2_quad_exhaustion_20261015_review',
            'fresh_sqrt2_weight_bound_20261015_review',
            'fresh_compact_global_bound_20261015_review']
    paths = {f'scripts/{TAG}.py',
             'results/arithmetic_dimension_bounds_and_effective_high_dimension_search.md'}
    data = {}
    for tag in tags:
        path = f'results/{tag}.json'
        paths.add(path)
        data[tag] = json.loads((ROOT/path).read_text())
        assert data[tag]['status'].startswith('PASS'), (tag, data[tag]['status'])
    q5 = data[q5tag]
    assert q5['arithmetic_ground_field'] == 'Q(sqrt5)'
    assert q5['compact_dimension_upper_bound'] == bound
    assert q5['complete_coverage'] is True
    assert q5['excluded_dimensions'] == list(range(bound + 1, 30))
    assert data[tags[1]]['status'] == (
        'PASS_INDEPENDENT_UNION_FIELD_PROFILE_REPLAY_AND_ALL_SIZE_CLOSURE_PROOF_REVIEW')
    assert data[tags[3]]['status'] == (
        'PASS_INDEPENDENT_FRACTION_AND_EXHAUSTIVE_QUAD_SCOPE_REVIEW_CUBIC_SEVEN_BOUND20')
    checked, references = set(), []
    def check(path):
        if path in checked or not path.endswith('.json'):
            return
        checked.add(path)
        doc = json.loads((ROOT/path).read_text())
        for field in ('sources', 'source_hashes'):
            for source, expected in doc.get(field, {}).items():
                assert isinstance(expected, str), (path, source)
                actual = sha256((ROOT/source).read_bytes()).hexdigest()
                assert actual == expected, (path, source)
                references.append([path, source, expected])
                check(source)
    for path in sorted(paths):
        check(path)
    branches = []
    for n in range(bound + 1, 30):
        assert n >= 22
        for field, upper in [('Q(sqrt2)', 20), ('Q(sqrt5)', bound),
                             ('Q(cos(2pi/7))', 20)]:
            assert n > upper
            branches.append(dict(dimension=n, field=field, excluded_by_upper_bound=upper))
    return dict(status='PASS_ARITHMETIC_REFLECTION_DIMENSION_COMPOSITION',
        sources={p: sha256((ROOT/p).read_bytes()).hexdigest() for p in sorted(paths)},
        compact_arithmetic_dimension_upper_bound=bound,
        finite_volume_arithmetic_reflection_dimension_upper_bound=bound,
        compact_high_dimension_field_branches=branches,
        noncompact_arithmetic=dict(upper_bound=21, excluded_dimension=20,
                                  dimension21_attained=True),
        recursive_manifest_count=len(checked), source_reference_count=len(references),
        published_inputs=[
            dict(result='Compact Coxeter dimension at most29; compact arithmetic '
                        'ground fields at dimension>=22 lie in the three-field list.',
                 source='Vinberg1984, Theorems1and2',
                 url='https://www.mathnet.ru/php/getFT.phtml?jrnid=mmo&option_lang=rus&paperid=444&what=fullt'),
            dict(result='Noncompact arithmetic reflection dimension at most21, '
                        'dimension20 excluded; dimension21 attained.',
                 source='Esselmann1996; Borcherds1987; scope restated in Belolipetsky2015, Section1',
                 url='https://doi.org/10.1006/jnth.1996.0141'),
            dict(result='Every arithmetic hyperbolic lattice generated by reflections '
                        'is of simplest type.',
                 source='Vinberg1967 Lemma7, restated in Belolipetsky2015 Lemma2.1',
                 url='https://arxiv.org/pdf/1506.03111')],
        proof='Above29 the published compact theorem applies. At each dimension '
              f'{bound+1} through29, Vinberg restricts compact arithmetic ground '
              'fields to the three listed fields, each excluded by a complete '
              'field-specific certificate. Noncompact arithmetic reflection '
              'groups already satisfy the published upper bound21. The scope '
              'is all arithmetic finite-volume reflection groups, which are '
              'automatically of simplest type.',
        scope='Computer-assisted research proof composition with explicit published '
              'inputs and internally reviewed field certificates. No external '
              'validation, formal proof-assistant verification, priority, '
              'unconditional nonarithmetic bound, or new example is claimed.')


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--bound', type=int, required=True, choices=(23, 24, 25, 26, 27))
    ap.add_argument('--verify', action='store_true')
    args = ap.parse_args()
    result = run(args.bound)
    out = ROOT/f'results/{TAG}_bound{args.bound}.json'
    if args.verify:
        assert result == json.loads(out.read_text())
    else:
        out.write_text(json.dumps(result, indent=2) + '\n')
    print(result['status'], args.bound, result['recursive_manifest_count'])
