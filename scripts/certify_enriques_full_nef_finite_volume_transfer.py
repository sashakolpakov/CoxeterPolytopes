#!/usr/bin/env python3
"""Freeze the exact data behind the full-nef Enriques volume classification.

The script does not attempt to prove Torelli, arithmetic finite covolume, or
the Cox-ring theorem computationally.  It pins their primary-source inputs,
checks the theorem anchors in Martin's source, replays the already independent
seven-chamber archives, and verifies that the stated implication graph is an
equivalence rather than a one-way slogan.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MARTIN = ROOT / "data/external/martin_enriques_2019/source/EnriquesFiniteAut.tex"
KONDO = ROOT / "data/external/kondo_enriques_1986/ko1821.pdf"
PRODUCTION = ROOT / "data/known_examples/enriques_finite_automorphism_nef_chambers.json"
HOSTILE = ROOT / "data/enumerations/enriques_finite_aut_nef_chambers_hostile_audit.json"
OUTPUT = ROOT / "data/enumerations/enriques_full_nef_finite_volume_transfer.json"

EXPECTED_HASHES = {
    "martin_source": "b1a576fd503ebd78ad62343fef2b46e7a890af6f8364eb67fa6e5fd8e80fc1cd",
    "kondo_pdf": "57be54fdd5e95324fe870f0fb69fc406022c4a13459e4a94de290a8d2fac6204",
    "production_archive": "245715b7352219a7ed1bfc34a43b5b37921e289d39829df51015c347b97072bc",
    "hostile_archive": "224ded8c22c223cf379461f54650d2f7fd560292e1de79bbefe62e5d51d55b1b",
}


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def transitive_closure(nodes: list[str], edges: list[tuple[str, str]]) -> dict[str, list[str]]:
    adjacency = {node: set() for node in nodes}
    for source, target in edges:
        adjacency[source].add(target)
    for pivot in nodes:
        for source in nodes:
            if pivot in adjacency[source]:
                adjacency[source].update(adjacency[pivot])
    return {node: sorted(adjacency[node]) for node in nodes}


def analyze() -> dict:
    paths = {
        "martin_source": MARTIN,
        "kondo_pdf": KONDO,
        "production_archive": PRODUCTION,
        "hostile_archive": HOSTILE,
    }
    hashes = {name: sha256(path) for name, path in paths.items()}
    if hashes != EXPECTED_HASHES:
        raise AssertionError({"expected": EXPECTED_HASHES, "actual": hashes})

    martin = MARTIN.read_text(encoding="utf-8")
    anchors = {
        "reflection_index_iff_finite_aut": (
            "generated by reflections along classes of $(-2)$-curves has finite index "
            "if and only if $\\Aut(X)$ is finite"
        ),
        "seven_complete_graphs_iff_finite_aut": (
            "$X$ has finite automorphism group if and only if the dual graph of all "
            "$(-2)$-curves on $X$ is one of the seven dual graphs"
        ),
    }
    anchor_checks = {name: text in martin for name, text in anchors.items()}
    if not all(anchor_checks.values()):
        raise AssertionError(anchor_checks)

    production = json.loads(PRODUCTION.read_text(encoding="utf-8"))
    hostile = json.loads(HOSTILE.read_text(encoding="utf-8"))
    checks = production["global_checks"]
    required_checks = {
        "all_seven_complete_nef_chambers": True,
        "all_seven_exact_cdd_cones_have_no_hyperideal_ray": True,
        "all_seven_finite_volume": True,
        "all_seven_literal_Vinberg_audits_pass": True,
        "all_seven_noncompact": True,
        "facet_count_multiset": [12, 12, 20, 20, 20, 20, 20],
        "no_full_nef_finite_Aut_Enriques_H9_14_member": True,
    }
    for key, expected in required_checks.items():
        if checks.get(key) != expected:
            raise AssertionError((key, checks.get(key), expected))

    hostile_types = hostile["types"]
    if len(hostile_types) != 7:
        raise AssertionError(len(hostile_types))
    finite = sum(record["exact_cone"]["finite_vertex_count"] for record in hostile_types)
    ideal = sum(record["exact_cone"]["ideal_vertex_count"] for record in hostile_types)
    hyperideal = sum(record["exact_cone"]["hyperideal_ray_count"] for record in hostile_types)
    elliptic_edges = sum(
        record["literal_vinberg"]["elliptic_rank_8_edge_count"]
        for record in hostile_types
    )
    affine_audits = sum(
        record["literal_vinberg"]["affine_zero_neighborhood_audit_count"]
        for record in hostile_types
    )
    if (finite, ideal, hyperideal, elliptic_edges, affine_audits) != (
        2214,
        294,
        0,
        13182,
        584,
    ):
        raise AssertionError((finite, ideal, hyperideal, elliptic_edges, affine_audits))

    nodes = [
        "finite_hyperbolic_volume_of_full_nef_chamber",
        "nodal_reflection_group_has_finite_index",
        "finite_automorphism_group",
        "kondo_martin_type_I_through_VII",
        "rational_polyhedral_effective_and_nef_cones",
        "finitely_generated_cox_ring",
        "one_of_seven_normalized_gram_images",
    ]
    undirected_bridges = [
        (nodes[0], nodes[1], "fundamental chamber plus arithmetic covolume/index"),
        (nodes[1], nodes[2], "Enriques Torelli finite-kernel/cokernel bridge"),
        (nodes[2], nodes[3], "Nikulin--Kondo--Martin classification"),
        (nodes[3], nodes[4], "finite complete nodal lists and cone duality"),
        (nodes[4], nodes[5], "Artebani--Hausen--Laface Theorem 2.10"),
        (nodes[3], nodes[6], "Shimada exact vectors and seven-image audit"),
    ]
    directed_edges = []
    for left, right, _ in undirected_bridges:
        directed_edges.extend([(left, right), (right, left)])
    closure = transitive_closure(nodes, directed_edges)
    for node in nodes:
        if set(closure[node]) != set(nodes):
            raise AssertionError((node, closure[node]))

    return {
        "schema": "enriques_full_nef_finite_volume_transfer_v1",
        "scope": {
            "field": "complex numbers",
            "surface": "smooth projective Enriques surface",
            "cone": "the complete nef cone cut by all smooth rational curves",
            "hyperbolic_dimension": 9,
            "excludes": [
                "proper nef sections",
                "weak Picard-lattice carriers",
                "arbitrary abstract H9 Coxeter polytopes",
                "positive-characteristic Torelli implications",
            ],
        },
        "pinned_primary_sources": {
            "sha256": hashes,
            "martin_anchor_checks": anchor_checks,
            "kondo_internal_locators": {
                "fundamental_chamber": "section 1.3, internal page 9",
                "finite_kernel_cokernel_torelli_bridge": "Theorem 1.5, internal page 10",
            },
            "cox_ring_locator": "Artebani--Hausen--Laface, Theorem 2.10, arXiv:0901.0369",
        },
        "equivalence": {
            "nodes": nodes,
            "bidirectional_bridges": [
                {"left": left, "right": right, "reason": reason}
                for left, right, reason in undirected_bridges
            ],
            "transitive_closure": closure,
            "all_nodes_mutually_equivalent_in_scope": True,
        },
        "exact_seven_image_consequence": {
            "image_cardinality": 7,
            "facet_count_multiset": [12, 12, 20, 20, 20, 20, 20],
            "finite_vertices": finite,
            "ideal_vertices": ideal,
            "hyperideal_rays": hyperideal,
            "elliptic_rank_8_edges": elliptic_edges,
            "full_affine_neighborhood_audits": affine_audits,
            "all_finite_volume": True,
            "all_noncompact": True,
            "no_compact_full_nef_enriques_member": True,
            "no_fourteen_facet_full_nef_enriques_member": True,
        },
        "proof_boundary": (
            "The source pins and exact chamber replays certify the inputs.  The "
            "fundamental-domain, arithmetic-covering-volume, Torelli, classification, "
            "and Cox-ring implications are mathematical arguments recorded in the report, "
            "not consequences of JSON hashing."
        ),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check-archive", action="store_true")
    args = parser.parse_args()
    rendered = json.dumps(analyze(), indent=2, sort_keys=True) + "\n"
    if args.check_archive:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != rendered:
            raise SystemExit(f"archived certificate differs: {args.output}")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(rendered, encoding="utf-8")
    print(hashlib.sha256(rendered.encode("utf-8")).hexdigest())


if __name__ == "__main__":
    main()
