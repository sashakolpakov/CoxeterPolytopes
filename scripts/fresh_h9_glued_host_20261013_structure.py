def det_rational(matrix):
    a=[list(map(Q,row))for row in matrix];out=Q(1)
    for i in range(len(a)):
        j=next(j for j in range(i,len(a))if a[j][i])
        if i!=j:a[i],a[j]=a[j],a[i];out=-out
        q=a[i][i];out*=q
        for j in range(i+1,len(a)):
            factor=a[j][i]/q
            for k in range(i,len(a)):a[j][k]-=factor*a[i][k]
    return out

def norm(x):
    cols=[mul(x,tuple(Q(i==j)for i in range(4)))for j in range(4)]
    return det_rational([[cols[j][i]for j in range(4)]for i in range(4)])

def remainder_mod3(poly,divisor):
    p=list(poly)
    for j in range(len(p)-1,len(divisor)-2,-1):
        q=p[j]%3
        for i,a in enumerate(divisor):p[j-len(divisor)+1+i]=(p[j-len(divisor)+1+i]-q*a)%3
    return p[:len(divisor)-1]

