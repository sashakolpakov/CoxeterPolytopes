"""Complete63 cone after the exact missing-S6 escape cutter."""
import argparse
import json
from collections import Counter
from fractions import Fraction as F
from hashlib import sha256
from pathlib import Path

import fresh_nonarithmetic_pi8_quad_cone_20261017 as Q
import fresh_nonarithmetic_escape62_20261017_cap as B

P,U,I=Q.P,Q.U,Q.I
ROOT=Path(__file__).resolve().parents[1]
TAG='fresh_nonarithmetic_escape62_20261017_cone'
CAP=B.TAG
PRIOR='fresh_nonarithmetic_pi9_prism_cone_20261017'


def run():
    old,cap=Q.read(PRIOR),Q.read(CAP)
    assert old['status']=='PASS_COMPLETE_62_WALL_CONE_AND_STRICT_ESCAPE'
    assert cap['status']=='PASS_EXACT_63_WALL_CAP_CUTTING_RETAINED60_ESCAPE'
    z=B.geometry();q,normals=z['exact_gram'],z['normals'];assert len(normals)==63
    assert old['computational_root_basis']==cap['computational_root_basis']==z['basis_ids']
    assert old['computational_gram']==cap['computational_gram']==[P.enc(row)for row in q]
    h=Q.vector(cap['common_center']);assert P.enc(h)==old['computational_common_center']
    cov=[U.imv(q,n)for n in normals];hc=U.imv(q,h)
    assert U.idot(h,hc).h<0 and all(U.idot(h,c).h<0 for c in cov)
    # These are already in this exact root basis. No physical conversion or
    # initial re-solving is used or needed.
    rays=[dict(active=r['active'],mask=sum(1<<j for j in r['active']),kind=r['kind'],
               v=Q.vector(r['normalized_computational_coordinate_bounds']))for r in old['final_rays']]
    assert len(rays)==2958 and Counter(r['kind']for r in rays)==Counter(old['counts'])
    wall=62;products=[U.idot(r['v'],cov[wall])for r in rays]
    signs=[Q.sign(x)for x in products]
    negative=[i for i,s in enumerate(signs)if s<0];positive=[i for i,s in enumerate(signs)if s>0]
    assert all(rays[i]['kind']=='hyperideal_rays'for i in positive)
    assert positive
    print('COMPLETE63_PARTITION',len(negative),len(positive),flush=True)
    out={rays[i]['mask']:dict(rays[i])for i in negative};crossings=[];nonedges=[]
    for ni in negative:
        a=rays[ni]
        for pi in positive:
            b=rays[pi];common=a['mask']&b['mask']
            if common.bit_count()<8:continue
            # On the inherited complete pointed cone, the common-zero face
            # is generated by precisely the rays containing this mask.
            # More than two rays therefore certify a nonedge.
            face=[k for k,r in enumerate(rays)if r['mask']&common==common]
            assert ni in face and pi in face
            if len(face)>2:
                nonedges.append(dict(negative=ni,positive=pi,common_support=Q.ids(common),
                                     face_ray_indices=face))
                continue
            assert len(face)==2
            minor=Q.rank8([cov[k]for k in Q.ids(common)])
            ga,gb=products[ni],products[pi]
            ca,cb=U.rnd(gb/(gb-ga)),U.rnd(-ga/(gb-ga));assert ca.l>0 and cb.l>0
            v=[U.rnd(ca*x+cb*y)for x,y in zip(a['v'],b['v'])]
            mask=common|(1<<wall)
            v,reconstruction=Q.tighten(v,Q.ids(mask),cov)
            norm=U.idot(v,U.imv(q,v));assert Q.sign(norm)>0
            assert mask not in out,('duplicate crossing',Q.ids(mask))
            out[mask]=dict(active=Q.ids(mask),mask=mask,kind='hyperideal_rays',v=v)
            crossings.append(dict(negative_support=a['active'],positive_support=b['active'],
                new_support=Q.ids(mask),rank8_minor=minor,positive_coefficients=P.enc([ca,cb]),
                norm=norm.enc(),direct_ray_reconstruction=reconstruction))
            if len(crossings)%100==0:print('COMPLETE63_CROSSINGS',len(crossings),flush=True)
    rays=sorted(out.values(),key=lambda r:r['active'])
    stage=dict(wall=wall,negative=len(negative),positive=len(positive),
               removed_ray_supports=[old['final_rays'][i]['active']for i in positive],crossings=crossings,
               nonedge_rejections=nonedges,counts=dict(Counter(r['kind']for r in rays)))
    print('COMPLETE63_CLIP',len(negative),len(positive),len(crossings),len(nonedges),stage['counts'],flush=True)
    final=[];counts=Counter()
    for number,ray in enumerate(rays,1):
        v=ray['v'];norm,time=U.idot(v,U.imv(q,v)),U.idot(v,hc)
        kind='finite_vertices'if Q.sign(norm)<0 else'hyperideal_rays'
        assert kind==ray['kind']
        if kind=='finite_vertices':assert time.h<0
        for i,c in enumerate(cov):
            value=U.idot(v,c)
            if (ray['mask']>>i)&1:assert value.l<=0<=value.h
            else:assert value.h<0,(ray['active'],i,value.enc())
        final.append(dict(active=ray['active'],kind=kind,norm=norm.enc(),center_product=time.enc(),
                          normalized_computational_coordinate_bounds=P.enc(v)))
        counts[kind]+=1
        if number%500==0:print('COMPLETE63_FINAL_GATES',number,flush=True)
    oldfinite={tuple(r['active'])for r in old['final_rays']if r['kind']=='finite_vertices'}
    newfinite={tuple(r['active'])for r in final if r['kind']=='finite_vertices'}
    assert oldfinite==newfinite and len(newfinite)==193
    faces=[]
    for row in old['faces']+[dict(name='new_missing_S6_facet',support=[62])]:
        support=row['support'];rr=[r for r in final if set(support)<=set(r['active'])]
        faces.append(dict(name=row['name'],support=support,counts=dict(Counter(r['kind']for r in rr)),
                          ray_supports=[r['active']for r in rr]))
    for name,count in [('compact_H4_I2_8_tetrahedron',4),('r8_quadrilateral',4),('new_H4_I2_9_prism',6)]:
        assert next(r for r in faces if r['name']==name)['counts']=={'finite_vertices':count}
    assert faces[-1]['counts'].get('finite_vertices',0)==0
    inherited=Q.vector(old['strict_escape']['computational_point'])
    inherited_product=U.idot(inherited,cov[62])
    escape=None
    exterior=next((r for r in rays if r['kind']=='hyperideal_rays'and U.idot(r['v'],hc).h<0),None)
    if exterior is not None:
        for power in range(128):
            point=[U.rnd(x+I(F(1,2**power))*y)for x,y in zip(exterior['v'],h)]
            norm,future=U.idot(point,U.imv(q,point)),U.idot(point,hc)
            if norm.l>0 and future.h<0:
                ps=[U.idot(point,c)for c in cov]
                if all(x.h<0 for x in ps):
                    escape=dict(ray_support=exterior['active'],center_coefficient_power=power,
                        computational_point=P.enc(point),physical_point=P.enc(P.combine(point,z['basis'])),
                        norm=norm.enc(),future=future.enc(),all63_products=P.enc(ps));break
        assert escape is not None
    else:assert counts['hyperideal_rays']==0
    paths=[f'scripts/{TAG}.py',f'scripts/{CAP}.py',f'results/{CAP}.json',
           f'scripts/{PRIOR}.py',f'results/{PRIOR}.json',f'scripts/{Q.TAG}.py']
    return dict(status='PASS_COMPLETE_63_WALL_CONE_AND_STRICT_ESCAPE'if escape else'PASS_COMPLETE_63_WALL_COMPACT_CONE',
        sources={p:sha256((ROOT/p).read_bytes()).hexdigest()for p in paths},
        initial_counts=old['counts'],counts=dict(counts),clipping_stages=[stage],
        coordinate_system='Inherited computational root basis; identical basis ids and interval Gram checked before clipping.',
        computational_root_basis=z['basis_ids'],computational_gram=[P.enc(row)for row in q],computational_common_center=P.enc(h),
        final_rays=final,new_finite_supports=[],final_inequality_checks=63*len(final),faces=faces,
        inherited62_escape_new_product=inherited_product.enc(),strict_escape=escape,
        proof='Start from the frozen complete62 cone in the identical computational root basis. Strict new-wall signs partition every old ray. An opposite-sign pair is adjacent exactly when its common-zero face contains only those two inherited extreme rays; all accepted pairs also have an explicit rank8 minor. Positive combinations give every new ray. Nine active equations reconstruct each new projective ray after positive normalization. All63 final inequalities and causal signs are checked. All193 finite rays persist and every new ray is exterior, as independently predicted by the six finite neighbors of the new cap. Entire retained compact faces are checked from the complete active-ray sets.',
        scope='Complete primary63-wall cone, inheriting the62-wall completeness and frozen arithmetic helpers. Not an independent arithmetic review. A saved strict spacelike future escape proves infinite volume despite removal of the preceding escape witness.')


if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--verify',action='store_true');a=ap.parse_args()
