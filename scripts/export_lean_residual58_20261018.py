#!/usr/bin/env python3
"""Export one frozen actual residual certificate to kernel-checkable Lean.

This is the all-residual branch only, not the complete dimension58 proof.
The Lean checker verifies the table inequalities; it never calls Python.
"""
import argparse
from hashlib import sha256
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
SOURCE='results/fresh_d16_a1_long_leaf_d17_zero_ambient58_frontier_20261018.json'
PIN='a79c930ed02c61f0ac5f3d1ca0d946c12b0ef3ff34ca941cb394f554ce7c304b'
OUT='formal/CoxeterProofs/Generated/Residual58.lean'
META='formal/certificates/residual58_source.json'

def generate():
    raw=(ROOT/SOURCE).read_bytes();assert sha256(raw).hexdigest()==PIN
    data=json.loads(raw)
    for name,h in data['sources'].items():assert sha256((ROOT/name).read_bytes()).hexdigest()==h,name
    tab=data['finite']['residual_table'];types=tab['types'];weights=tab['weights'];values=tab['values']
    assert len(types)==len(weights)==149 and len(values)==59 and values[0]==0 and values[58]==24192
    assert all(isinstance(w,int)and w>=0 for w in weights+values)
    assert all(isinstance(n,int)and 1<=n<=58 for _,n in types)
    item_lines=',\n'.join(f'  ⟨{n}, {w}⟩'for (_,n),w in zip(types,weights,strict=True))
    text=f'''-- Generated by scripts/export_lean_residual58_20261018.py.
-- Frozen source SHA-256: {PIN}
-- Scope: one all-residual rank58 domain, not all finite forests.
import CoxeterProofs.CertificateBounds

set_option maxRecDepth 100000
set_option maxHeartbeats 0

namespace CoxeterProofs.Generated.Residual58

def items : List ChargedItem := [
{item_lines}]

def values : List Nat := {json.dumps(values)}

theorem all_last_item_inequalities : checkLastItems 58 items values = true := by
  decide

theorem zero_entry : tableValue values 0 = 0 := by decide
theorem terminal_entry : tableValue values 58 = 24192 := by decide

theorem every_allowed_forest_upper
    (xs : List ChargedItem)
    (membership : ∀ a ∈ xs, a ∈ items)
    (capacity : totalRank xs ≤ 58) :
    totalCharge xs ≤ tableValue values (totalRank xs) := by
  exact additive_upper_of_last_item 58 items (tableValue values) zero_entry
    (last_item_steps_of_check 58 items values all_last_item_inequalities)
    xs membership capacity

theorem rank58_upper
    (xs : List ChargedItem)
    (membership : ∀ a ∈ xs, a ∈ items)
    (rank : totalRank xs = 58) : totalCharge xs ≤ 24192 := by
  have upper := every_allowed_forest_upper xs membership (by omega)
  rw [rank, terminal_entry] at upper
  exact upper

def witness : List ChargedItem := [⟨17, 7296⟩, ⟨17, 7296⟩, ⟨24, 9600⟩]
theorem witness_rank : totalRank witness = 58 := by decide
theorem witness_charge : totalCharge witness = 24192 := by decide
theorem witness_membership : ∀ a ∈ witness, a ∈ items := by decide

end CoxeterProofs.Generated.Residual58
'''
    meta=dict(status='EXPORTED_ONE_RESIDUAL_CERTIFICATE_NOT_FULL_DIMENSION_PROOF',source=SOURCE,sha256=PIN,
        producer='scripts/export_lean_residual58_20261018.py',lean=OUT,scale=64,cap=58,terminal_charge=24192,
        formal_upper='378',types=types,weights=weights,values=values,
        scope='149 actual residual types; no fixed components, cross interactions or witness contexts. Geometry, other finite branches, ideal profiles and dimension theorem are not formalized by this certificate.')
    return text,json.dumps(meta,indent=2)+'\n'

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--write',action='store_true');args=parser.parse_args()
    lean,meta=generate()
    for name,body in((OUT,lean),(META,meta)):
        path=ROOT/name
        if args.write:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(body)
        else:assert path.read_text()==body,name
    print('PASS',('export'if args.write else'exact export replay'),149,'actual residual items, rank58 upper378; full theorem pending')
