G = tuple(tuple(-ALPHA if i == j == 0 else O if i == j else Z for j in range(10))for i in range(10))


def emul(u,v):
    return u[0]*v[0]+ALPHA*u[1]*v[1], u[0]*v[1]+u[1]*v[0]


def lattice(r):
    return all(z.is_integral for z in r) and (sum(r[1:],Z)/2).is_integral


def simple_d9():
    roots=[]
    for i in range(8):
        r=[Z]*10;r[i+1]=O;r[i+2]=-O;roots.append(tuple(r))
    r=[Z]*10;r[8]=r[9]=O;roots.append(tuple(r))
    return roots


DBASIS = [(O,*(Z for _ in range(9))),*simple_d9()]
INITIAL = [tuple(-z for z in r)for r in simple_d9()[:8]]+[(Z,*(Z for _ in range(8)),-2*O)]


def root_reason(r,q):
    assert pair(r,G,r)==q
    if not lattice(r):return 'NONINTEGRAL'
    if lattice(tuple(z/T for z in r)):return 'IMPRIMITIVE'
    if not all((2*pair(r,G,b)/q).is_integral for b in DBASIS):return 'NONREFLECTIVE'
    return None


def compatible(r,s):
    p=pair(r,G,s)
    if p>0:return False
    ratio=4*p*p/(pair(r,G,r)*pair(s,G,s))
    return ratio>=4 or ratio in ALLOWED


def read_interface():
    raw=RAW.read_text()
    for text in ('ABSOLUTE x^8 + 4*x^6 + 2*x^4 - 4*x^2 - 1\n',
                 'CERTIFY 1\n','BASE_CERTIFY 1\n','CLASS 1\n','SIGNATURE [2, 3]\n'):
        assert text in raw
    base=[];units=[];normrows=[];reps={};counts={}
    for line in raw.splitlines():
        if line.startswith('BASE_UNIT '):base.append(K.from_json(json.loads(line.split(' ',2)[2])))
        elif line.startswith('UNIT '):units.append(tuple(map(K.from_json,json.loads(line.split(' ',2)[2]))))
        elif line.startswith('UNIT_NORM '):
            _,i,s=line.split(' ',2);n,exponents=s.split('] ',1)
            normrows.append((K.from_json(json.loads(n+']')),json.loads(exponents)))
        elif line.startswith('NORM '):
            _,n,c=line.split();reps[int(n)]=[];counts[int(n)]=int(c)
        elif line.startswith('SOLUTION '):
            _,n,s=line.split(' ',2);reps[int(n)].append(tuple(map(K.from_json,json.loads(s))))
    assert len(base)==3 and len(units)==4
    assert [e for n,e in normrows]==[[0,-1,0,0],[2,-1,0,0],[0,0,2,0],[0,0,0,0]]
    for (z,x),(n,e) in zip(units,normrows):
        assert z*z-ALPHA*x*x==n
        check=K((-1)**e[3])
        for b,k in zip(base,e):check*=b**k
        assert check==n and abs(n.norm())==1
    # The first three columns of the norm map have nonzero determinant 4;
    # its exact integral kernel is therefore generated by the fourth unit.
    epsilon=units[3]
    assert epsilon==(K(-1,0,2,1),K(0,0,2,1))
    assert epsilon[0]>1 and epsilon[1]>0 and epsilon[0]**2-ALPHA*epsilon[1]**2==1
    assert set(reps)=={2**j for j in range(13)}
    assert all(len(reps[n])==counts[n]==1 for n in reps)
    for n,rs in reps.items():
        for z,x in rs:assert (z*z-ALPHA*x*x).norm()==n
    return base,units,normrows,reps,counts,epsilon


