def canonical_digest(value: object) -> str:
    return hashlib.sha256(
        json.dumps(value, sort_keys=True, separators=(",", ":")).encode()
    ).hexdigest()


def surface_pair(left: Sequence[int], right: Sequence[int]) -> int:
    """Intersection pairing diag(+1,-1^n), with n inferred from vectors."""

    if len(left) != len(right):
        raise ValueError("intersection vectors have different lengths")
    return left[0] * right[0] - sum(
        a * b for a, b in zip(left[1:], right[1:])
    )


def vector_add(left: Sequence[int], right: Sequence[int], scale: int = 1) -> Vector:
    return tuple(a + scale * b for a, b in zip(left, right))


def vector_sum(vectors: Iterable[Sequence[int]], length: int) -> Vector:
    vectors = tuple(vectors)
    if not vectors:
        return (0,) * length
    return tuple(sum(entries) for entries in zip(*vectors))


def primitive(vector: Sequence[int]) -> Vector:
    divisor = reduce(gcd, (abs(entry) for entry in vector if entry), 0)
    if divisor == 0:
        raise ValueError("zero vector has no primitive normalization")
    return tuple(entry // divisor for entry in vector)


def normalize_state(curves: Iterable[Sequence[int]]) -> CurveState:
    return tuple(sorted(set(tuple(curve) for curve in curves if any(curve))))


def contract_state(state: CurveState, exceptional: Vector) -> CurveState:
    """Pull current image classes back to ``exceptional^perp`` after blowdown."""

    if surface_pair(exceptional, exceptional) != -1:
        raise ValueError("only square-minus-one contractions are allowed")
    images = []
    for curve in state:
        if curve == exceptional:
            continue
        images.append(
            vector_add(curve, exceptional, surface_pair(curve, exceptional))
        )
    result = normalize_state(images)
    if any(surface_pair(curve, exceptional) for curve in result):
        raise AssertionError("a pushforward pullback is not orthogonal to e")
    return result


def enumerate_contraction_levels(
    roots: Sequence[Vector], n: int
) -> tuple[dict[int, dict[CurveState, set[ExceptionalBasis]]], list[dict[str, int]]]:
    """Enumerate every facet-image contraction state down to rank one."""

    levels: dict[int, dict[CurveState, set[ExceptionalBasis]]] = {
        n + 1: {normalize_state(roots): {()}},
    }
    census: list[dict[str, int]] = []
    for rank in range(n + 1, 1, -1):
        current = levels[rank]
        following: dict[CurveState, set[ExceptionalBasis]] = defaultdict(set)
        branch_count = 0
        dead_state_count = 0
        for state, bases in current.items():
            exceptionals = [
                curve for curve in state if surface_pair(curve, curve) == -1
            ]
            branch_count += len(exceptionals)
            if not exceptionals:
                dead_state_count += 1
            for exceptional in exceptionals:
                image_state = contract_state(state, exceptional)
                for basis in bases:
                    if any(surface_pair(exceptional, old) for old in basis):
                        raise AssertionError(
                            "exceptional total transforms are not orthogonal"
                        )
                    new_basis = tuple(sorted((*basis, exceptional)))
                    following[image_state].add(new_basis)
        census.append(
            {
                "rank": rank,
                "state_count": len(current),
                "exceptional_basis_count": sum(len(value) for value in current.values()),
                "square_minus_one_branch_count": branch_count,
                "states_without_square_minus_one_image_count": dead_state_count,
                "next_state_count": len(following),
                "next_exceptional_basis_count": sum(
                    len(value) for value in following.values()
                ),
            }
        )
        levels[rank - 1] = dict(following)
    return levels, census


def adjunction_profile(canonical: Vector, roots: Sequence[Vector]) -> tuple[int, ...]:
    return tuple(surface_pair(canonical, root) for root in roots)


def validate_canonical(
    canonical: Vector,
    roots: Sequence[Vector],
    exceptional_basis: ExceptionalBasis,
    n: int,
) -> None:
    if surface_pair(canonical, canonical) != 9 - n:
        raise AssertionError("canonical square is incompatible with rational rank")
    if any(entry % 2 == 0 for entry in canonical):
        raise AssertionError("canonical vector is not characteristic in I_(1,n)")
    if any(surface_pair(canonical, exceptional) != -1 for exceptional in exceptional_basis):
        raise AssertionError("a contracted curve fails rational (-1)-adjunction")
    for root in roots:
        numerator = surface_pair(root, root) + surface_pair(canonical, root)
        if numerator % 2:
            raise AssertionError("facet adjunction parity failure")
        if 1 + numerator // 2 < 0:
            raise AssertionError("a facet curve would have negative arithmetic genus")


def validate_rank_one_state(state: CurveState, line: Vector) -> None:
    if surface_pair(line, line) != 1:
        raise AssertionError("rank-one primitive generator is not a P2 line")
    for curve in state:
        coefficient = surface_pair(line, curve)
        if coefficient < 0 or curve != tuple(coefficient * entry for entry in line):
            raise AssertionError("rank-one image cone is not the P2 effective ray")


def p2_canonical_classes(
    rank_one_states: dict[CurveState, set[ExceptionalBasis]],
    roots: Sequence[Vector],
    n: int,
) -> set[Vector]:
    result: set[Vector] = set()
    for state, bases in rank_one_states.items():
        positive = [curve for curve in state if surface_pair(curve, curve) > 0]
        if not positive:
            raise AssertionError("rank-one image cone has no positive class")
        line = primitive(positive[0])
        if any(surface_pair(line, curve) < 0 for curve in state):
            line = tuple(-entry for entry in line)
        validate_rank_one_state(state, line)
        for basis in bases:
            if len(basis) != n:
                raise AssertionError("P2 endpoint contracts exactly n curves")
            canonical = vector_add(vector_sum(basis, n + 1), line, -3)
            validate_canonical(canonical, roots, basis, n)
            result.add(canonical)
    return result


def validate_hirzebruch_state(state: CurveState, section: Vector, fiber: Vector) -> int:
    section_square = surface_pair(section, section)
    if section_square >= 0 or surface_pair(fiber, fiber) != 0:
        raise AssertionError("invalid ruled-surface section/fiber squares")
    if surface_pair(section, fiber) != 1:
        raise AssertionError("ruled-surface section and fiber do not meet once")
    hirzebruch_index = -section_square
    if primitive(section) != section or primitive(fiber) != fiber:
        raise AssertionError("ruled-surface extremal generators are not primitive")
    for curve in state:
        section_coefficient = surface_pair(curve, fiber)
        fiber_coefficient = (
            surface_pair(curve, section) + hirzebruch_index * section_coefficient
        )
        reconstruction = vector_add(
            tuple(section_coefficient * entry for entry in section),
            fiber,
            fiber_coefficient,
        )
        if section_coefficient < 0 or fiber_coefficient < 0 or curve != reconstruction:
            raise AssertionError("rank-two image is outside the ruled effective cone")
    return hirzebruch_index


def f2_canonical_classes(
    rank_two_states: dict[CurveState, set[ExceptionalBasis]],
    roots: Sequence[Vector],
    n: int,
) -> tuple[set[Vector], dict[str, int]]:
    result: set[Vector] = set()
    endpoint_types: Counter[str] = Counter()
    for state, bases in rank_two_states.items():
        negative = [curve for curve in state if surface_pair(curve, curve) < 0]
        isotropic = [curve for curve in state if surface_pair(curve, curve) == 0]
        if len(negative) != 1 or len(isotropic) != 1:
            raise AssertionError("unexpected rank-two image cone")
        section = negative[0]
        fiber = isotropic[0]
        hirzebruch_index = validate_hirzebruch_state(state, section, fiber)
        endpoint_types[f"F{hirzebruch_index}"] += len(bases)
        if hirzebruch_index == 1:
            # F1 is nonminimal and the section contraction occurs in levels[1].
            continue
        if hirzebruch_index != 2:
            raise AssertionError("a minimal ruled endpoint other than F2 appeared")
        for basis in bases:
            if len(basis) != n - 1:
                raise AssertionError("rank-two endpoint contracts n-1 curves")
            # K_F2=-2*section-4*fiber.
            canonical = vector_add(
                vector_add(vector_sum(basis, n + 1), section, -2),
                fiber,
                -4,
            )
            validate_canonical(canonical, roots, basis, n)
            result.add(canonical)
    return result, dict(sorted(endpoint_types.items()))


def weighted_diagram_automorphisms(roots: Sequence[Vector]) -> list[tuple[int, ...]]:
    graph = nx.Graph()
    for index, root in enumerate(roots):
        graph.add_node(index, square=surface_pair(root, root))
    for i, root in enumerate(roots):
        for j, other in enumerate(roots[:i]):
            intersection = surface_pair(root, other)
            if intersection:
                graph.add_edge(i, j, intersection=intersection)
    matcher = nx.algorithms.isomorphism.GraphMatcher(
        graph,
        graph,
        node_match=lambda left, right: left["square"] == right["square"],
        edge_match=lambda left, right: (
            left["intersection"] == right["intersection"]
        ),
    )
    return sorted(
        tuple(mapping[index] for index in range(len(roots)))
        for mapping in matcher.isomorphisms_iter()
    )


def integral_lifts(
    roots: Sequence[Vector], automorphisms: Sequence[tuple[int, ...]], n: int
) -> list[Matrix]:
    # The n height-zero roots followed by L form a unimodular row basis.
    basis_indices = (*range(n), n)
    basis = Matrix([roots[index] for index in basis_indices])
    if abs(int(basis.det())) != 1:
        raise AssertionError("chosen facet-root basis is not unimodular")
    inverse = basis.inv()
    all_roots = Matrix(roots)
    form = diag(1, *((-1,) * n))
    lifts = []
    for permutation in automorphisms:
        image_basis = Matrix([roots[permutation[index]] for index in basis_indices])
        transformation = inverse * image_basis
        if any(entry.q != 1 for entry in transformation):
            raise AssertionError("diagram automorphism does not lift integrally")
        if abs(int(transformation.det())) != 1:
            raise AssertionError("diagram lift is not unimodular")
        if transformation * form * transformation.T != form:
            raise AssertionError("diagram lift does not preserve the surface form")
        if all_roots * transformation != Matrix(
            [roots[permutation[index]] for index in range(len(roots))]
        ):
            raise AssertionError("integral lift misses a facet root")
        lifts.append(transformation)
    return lifts


def standard_canonical_orbit(lifts: Sequence[Matrix], n: int) -> set[Vector]:
    standard = Matrix([[ -3, *((1,) * n)]])
    return {
        tuple(int(entry) for entry in (standard * lift).row(0))
        for lift in lifts
    }


def named_abel_facets(roots: Sequence[Vector], n: int) -> dict[str, int]:
    def plane_class(degree: int, multiplicities: Sequence[int]) -> Vector:
        values = tuple(multiplicities)
        return (
            degree,
            *(-entry for entry in values),
            *((0,) * (n - len(values))),
        )

    expected = {
        "L": plane_class(1, (1, 1, 1)),
        "C": plane_class(3, (1,) * 11),
        "Q": plane_class(4, (2, *((1,) * 14))),
        "A": plane_class(4, (1,) * 18),
    }
    lookup = {root: index for index, root in enumerate(roots, start=1)}
    if any(vector not in lookup for vector in expected.values()):
        raise AssertionError("an Abel-obstruction facet is missing")
    labels = {name: lookup[vector] for name, vector in expected.items()}
    L, C, Q, A = (expected[name] for name in ("L", "C", "Q", "A"))
    if {
        "L.C": surface_pair(L, C),
        "C.Q": surface_pair(C, Q),
        "Q.A": surface_pair(Q, A),
        "C.A": surface_pair(C, A),
    } != {"L.C": 0, "C.Q": 0, "Q.A": 0, "C.A": 1}:
        raise AssertionError("the Abel-obstruction intersection pattern changed")
    return labels


def first_contraction_census(
    roots: Sequence[Vector], rank_one_states: dict[CurveState, set[ExceptionalBasis]]
) -> tuple[list[int], dict[int, int]]:
    labels = {root: index for index, root in enumerate(roots, start=1)}
    initial = [root for root in roots if surface_pair(root, root) == -1]
    endpoint_counts: Counter[int] = Counter()
    for bases in rank_one_states.values():
        for basis in bases:
            hits = [labels[root] for root in initial if root in basis]
            if len(hits) != 1:
                raise AssertionError("endpoint path has an ambiguous first contraction")
            endpoint_counts[hits[0]] += 1
    return [labels[root] for root in initial], dict(sorted(endpoint_counts.items()))


def dimension_certificate(n: int) -> dict[str, object]:
    expected = EXPECTED[n]
    roots = tuple(tuple(root) for root in enumerate_simple_roots(n))
    if len(roots) != expected["facet_count"]:
        raise AssertionError("unexpected facet count")
    if canonical_digest(roots) != expected["ordered_root_sha256"]:
        raise AssertionError("ordered Vinberg root list changed")
    if any(
        surface_pair(left, right) < 0
        for index, left in enumerate(roots)
        for right in roots[:index]
    ):
        raise AssertionError("distinct effective facet classes intersect negatively")

    levels, level_census = enumerate_contraction_levels(roots, n)
    state_counts = [entry["state_count"] for entry in level_census]
    state_counts.append(len(levels[1]))
    if state_counts != expected["state_counts_by_descending_rank"]:
        raise AssertionError((n, state_counts))

    p2_classes = p2_canonical_classes(levels[1], roots, n)
    f2_classes, endpoint_types = f2_canonical_classes(levels[2], roots, n)
    endpoint_count = expected["endpoint_count"]
    if endpoint_types != {"F1": endpoint_count, "F2": endpoint_count}:
        raise AssertionError(endpoint_types)
    if len(levels[1]) != endpoint_count or len(p2_classes) != endpoint_count:
        raise AssertionError("unexpected P2 endpoint count")
    if f2_classes != p2_classes:
        raise AssertionError("P2 and F2 canonical reconstructions disagree")

    automorphisms = weighted_diagram_automorphisms(roots)
    if len(automorphisms) != expected["automorphism_order"]:
        raise AssertionError("unexpected weighted-diagram automorphism order")
    lifts = integral_lifts(roots, automorphisms, n)
    standard_orbit = standard_canonical_orbit(lifts, n)
    if p2_classes != standard_orbit:
        raise AssertionError("MMP canonical classes are not the standard orbit")
    endpoint_profiles = {
        adjunction_profile(canonical, roots) for canonical in p2_classes
    }
    standard_profiles = {
        adjunction_profile(canonical, roots) for canonical in standard_orbit
    }
    if endpoint_profiles != standard_profiles:
        raise AssertionError("canonical facet-pairing profiles disagree")

    initial_labels, surviving_first = first_contraction_census(roots, levels[1])
    if initial_labels != expected["initial_square_minus_one_labels"]:
        raise AssertionError("initial numerical (-1)-facet labels changed")
    if surviving_first != expected["surviving_first_contraction_counts"]:
        raise AssertionError("first-contraction survival census changed")

    standard = (-3, *((1,) * n))
    standard_genera = []
    for root in roots:
        numerator = surface_pair(root, root) + surface_pair(standard, root)
        standard_genera.append(1 + numerator // 2)
    b_chain_genera = standard_genera[:n]
    if b_chain_genera != [0] * n:
        raise AssertionError("the standard B_n facet chain is not rational")

    checks = {
        "all_distinct_facet_intersections_are_nonnegative": True,
        "all_contraction_bases_are_pairwise_orthogonal_minus_one_classes": True,
        "rank_two_endpoints_are_exactly_F1_or_F2": True,
        "F1_endpoints_continue_to_P2": True,
        "P2_and_F2_canonical_reconstructions_agree": True,
        "all_canonical_classes_are_characteristic_with_square_9_minus_n": True,
        "all_facet_arithmetic_genera_are_nonnegative": True,
        "all_diagram_automorphisms_lift_integrally_and_unimodularly": True,
        "canonical_classes_equal_standard_diagram_isometry_orbit": True,
        "standard_Bn_chain_has_arithmetic_genus_zero": True,
        "abel_facets_have_intersections_LC_CQ_QA_CA_0_0_0_1": True,
    }

    return {
        "lattice": f"I_(1,{n})",
        "hyperbolic_dimension": n,
        "facet_count": len(roots),
        "ordered_root_sha256": canonical_digest(roots),
        "surface_rank": n + 1,
        "surface_canonical_square": 9 - n,
        "initial_square_minus_one_facet_count": len(initial_labels),
        "initial_square_minus_one_facet_labels_one_based": initial_labels,
        "first_contraction_endpoint_survival_counts": {
            str(label): count for label, count in surviving_first.items()
        },
        "contraction_level_census": level_census,
        "state_counts_by_descending_rank": state_counts,
        "rank_two_endpoint_types": endpoint_types,
        "rank_one_P2_endpoint_count": len(levels[1]),
        "canonical_class_count": len(p2_classes),
        "canonical_classes": [list(vector) for vector in sorted(p2_classes)],
        "canonical_facet_pairing_profiles": [
            list(profile) for profile in sorted(endpoint_profiles)
        ],
        "standard_marking_facet_arithmetic_genus_histogram": {
            str(genus): count
            for genus, count in sorted(Counter(standard_genera).items())
        },
        "standard_marking_Bn_arithmetic_genera": b_chain_genera,
        "weighted_diagram_automorphism_order": len(automorphisms),
        "weighted_diagram_automorphisms_zero_based": [
            list(permutation) for permutation in automorphisms
        ],
        "all_diagram_automorphisms_lift_to_integral_unimodular_isometries": True,
        "p2_and_f2_reconstructions_agree": True,
        "canonical_classes_equal_standard_diagram_orbit": True,
        "abel_obstruction_facet_labels_one_based": named_abel_facets(roots, n),
        "checks": checks,
        "geometric_conclusion": (
            f"No smooth projective rational surface in characteristic zero has "
            f"complete Mori cone generated by irreducible curve classes with the "
            f"P{n} facet intersection matrix.  Every possible surface-MMP "
            f"canonical marking lies in the full diagram orbit of "
            f"K=(-3,1^{n}); after conjugation the B_{n} chain is smooth rational, "
            f"contracts to P2, and the flex-cubic Abel obstruction applies."
        ),
        "abstract_polytope_caveat": (
            f"This is only a rational-surface carrier nonexistence theorem.  The "
            f"classical finite-volume Vinberg--Kaplinskaja hyperbolic P{n} exists."
        ),
    }


def build_certificate() -> dict[str, object]:
    certificate: dict[str, object] = {
        "schema": "rational_p18_p19_mmp_v1",
        "method": (
            "exact exhaustive contraction of every current square-minus-one facet "
            "image, followed by P2/F2 canonical reconstruction and integral "
            "weighted-diagram orbit comparison"
        ),
        "dimensions": {
            str(n): dimension_certificate(n) for n in sorted(EXPECTED)
        },
        "theorem_scope": (
            "unconditional nonexistence of a complete P18 or P19 Mori/nef carrier "
            "on a smooth projective rational surface in characteristic zero"
        ),
        "not_claimed": [
            "nonexistence of the abstract P18 or P19 hyperbolic Coxeter polytope",
            "nonexistence of carriers on nonrational varieties",
            "a new abstract hyperbolic Coxeter polytope",
        ],
    }
    certificate["certificate_payload_sha256"] = canonical_digest(certificate)
    return certificate


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    rendered = json.dumps(build_certificate(), indent=2, sort_keys=True) + "\n"
    if args.output is None:
        print(rendered, end="")
    else:
        args.output.write_text(rendered)


if __name__ == "__main__":
    main()
