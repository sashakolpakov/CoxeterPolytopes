"""Exact marking-independent rational-surface MMP for P18 and P19.

For each classical odd-unimodular Vinberg--Kaplinskaja chamber ``P_n``,
``n=18,19``, start from its complete list of facet curve classes in
``I_(1,n)``.  Push the generated curve cone through every numerically
possible smooth ``(-1)``-curve contraction.  A contraction sends a curve
class ``D`` to the pullback of its image

    D |-> D + (D.e)e.

The enumeration is complete for a putative smooth rational-surface
carrier: a K-negative extremal ray is generated by a smooth rational
``(-1)``-curve, and completeness of the facet cone forces that curve to
be one of the current nonzero facet images.

The terminal P2 and F2 reconstructions give respectively 24 canonical
classes for P18 and 120 for P19.  In both dimensions the two minimal-model
reconstructions agree, and the resulting classes are exactly the orbit of
the standard plane-blowup canonical class under the full weighted Coxeter
diagram automorphism group.  This is the marking-classification input for
the unconditional rational-surface carrier obstruction; it says nothing
against existence of the classical abstract hyperbolic polytopes.
"""

