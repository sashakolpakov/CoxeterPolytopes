def emul(u,v,D):return(u[0]*v[0]+D*u[1]*v[1],u[0]*v[1]+u[1]*v[0])
def interface(kind,pd):
    rawpath=ROOT/'results/fresh_h9_a9_outer_20261013_axis_raw.txt';gppath=ROOT/'scripts/fresh_h9_a9_outer_20261013_axis.gp';raw=rawpath.read_text()
    assert 'BASE_CERTIFY 1\n'in raw and'CERTIFY 1\n'in raw and'CLASS 2\n'in raw and'SIGNATURE [2, 3]\n'in raw
    D=10*ALPHA;units=[];base=[];maps=[];absolute={};counts={}
    for line in raw.splitlines():
        if line.startswith('BASE_UNIT '):base.append(K.from_json(json.loads(line.split(' ',2)[2])))
        elif line.startswith('UNIT '):
            left,right=line.split(' MAP ');units.append(tuple(map(K.from_json,json.loads(left.split(' ',2)[2]))));maps.append(json.loads(right))
        elif line.startswith('NORM '):
            _,n,c=line.split();counts[int(n)]=int(c);absolute[int(n)]=[]
        elif line.startswith('SOLUTION '):
            _,n,s=line.split(' ',2);absolute[int(n)].append(tuple(map(K.from_json,json.loads(s))))
    assert len(base)==3 and len(units)==4 and all(abs(v.norm())==1 for v in base)
    for (u,v),row in zip(units,maps,strict=True):
        expected=K((-1)**row[3])
        for t,k in zip(base,row[:3],strict=True):expected*=t**k
        assert u*u-D*v*v==expected
    m=tuple(tuple(maps[j][i]for j in range(3))for i in range(3));det=m[0][0]*(m[1][1]*m[2][2]-m[1][2]*m[2][1])-m[0][1]*(m[1][0]*m[2][2]-m[1][2]*m[2][0])+m[0][2]*(m[1][0]*m[2][1]-m[1][1]*m[2][0])
    assert det and all(v==0 for u,v in units[:3])and units[0]==(ALPHA,Z)
    assert units[3][0]**2-D*units[3][1]**2==-ALPHA
    epsilon=tuple(v/ALPHA for v in emul(units[3],units[3],D))
    if epsilon[0]<0:epsilon=tuple(-x for x in epsilon)
    if epsilon[1]<0:epsilon=(epsilon[0],-epsilon[1])
    assert epsilon[0]>1 and epsilon[1]>0 and epsilon[0]**2-D*epsilon[1]**2==1
    targets=sorted({K.from_json(row['relative_target'])for case in pd['cases']if case['kind']==kind for row in case['profiles']})
    assert set(absolute)=={int(v.norm())for v in targets}and all(len(absolute[n])==counts[n]for n in absolute)
    records={};reps={}
    for N in targets:
        nn=int(N.norm());valid=[];skipped=[]
        for u,v in absolute[nn]:
            assert(u*u-D*v*v).norm()==nn
            delta=(u*u-D*v*v)/N
            if not delta.is_integral or not delta.inverse().is_integral:
                skipped.append({'absolute_representative':enc((u,v)),'ratio':delta.to_json()});continue
            assert all(delta.sign(e)>0 for e in range(4));s=square_root(delta)
            assert s is not None and s.is_integral and s.inverse().is_integral
            u/=s;v/=s
            if u<0:u=-u;v=-v
            assert u>0 and u*u-D*v*v==N
            valid.append({'relative_representative':enc((u,v)),'correction_unit':s.to_json(),'ratio':delta.to_json()})
        reps[N]=[tuple(map(K.from_json,r['relative_representative']))for r in valid]
        records[str(N)]={'target':N.to_json(),'absolute_norm':nn,'relative_orbits':valid,'excluded_nonunit_ratios':skipped}
    return {'D':D,'epsilon':epsilon,'reps':reps,'record':{'sources':{str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest()for p in(rawpath,gppath)},
      'base_units':enc(base),'fundamental_units':[enc(u)for u in units],'relative_norm_maps':maps,'map_minor_determinant':det,
      'relative_unit':enc(epsilon),'absolute_norm_counts':counts,'targets':records,
      'unit_kernel_proof':'The first three full extension fundamental units lie in K, the first is alpha, and the fourth has relative norm -alpha. Its exponent in a norm-one unit must be even by the primary sign. The base factor is then exactly plus or minus alpha to the negative half-exponent, so the full kernel is generated by the sign and epsilon=u4²/alpha.'}}

def first_positive(rep,epsilon,D):
    u=rep;power=0;back=(epsilon[0],-epsilon[1])
    while u[1]<=0:u=emul(u,epsilon,D);power+=1;assert abs(power)<100
    while emul(u,back,D)[1]>0:u=emul(u,back,D);power-=1;assert abs(power)<100
    assert emul(u,back,D)[1]<=0 and u[1]>0
    return u,power,emul(u,back,D)

def reconstruct(case,profile,u):
    Zc,Xc=u;r0=tuple(map(K.from_json,profile['fixed_component']));b=tuple(map(K.from_json,case['released_residual']));V=tuple(map(K.from_json,case['timelike_vector']));den=case['timelike_denominator']
    r=tuple(a-Zc*bv/10+Xc*v/den for a,bv,v in zip(r0,b,V));q=K.from_json(profile['norm']);assert pair(r,G,r)==q
    s=10*ALPHA*Xc/Zc
    p=tuple(v-s*bv for v,bv in zip(V,b));p=tuple(v/p[0]for v in p)
    assert pair(p,G,p)<0 and pair(p,G,r)==0
    return r,q,s,p

def reason(r,q,walls):
    if not all(v.is_integral for v in r):return'NONINTEGRAL'
    if all((v/T).is_integral for v in r)or all((v/5).is_integral for v in r):return'IMPRIMITIVE'
    if not all((2*v/q).is_integral for v in mv(G,r)):return'NONREFLECTIVE'
    if not compatible(r,q,walls,G):return'NOT_PREFIX_COMPATIBLE'
    return None

def run(scout_powers=8):
    started=time.monotonic();pd=json.loads(PROFILE.read_text());sd=json.loads(SOURCE.read_text());walls=[tuple(map(K.from_json,r))for r in sd['all_walls']];inside=tuple(map(K.from_json,sd['strict_interior']))
