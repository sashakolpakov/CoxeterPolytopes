        partial={'status':'RUNNING','sources':{str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest()for p in(PROFILE,SOURCE)},'interfaces':{k:v['record']for k,v in tables.items()},'cases':cases}
