def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check-archive", action="store_true")
    parser.add_argument("--cdd", default=None)
    args = parser.parse_args()
    payload, artifacts = build(args.cdd)
    rendered = (json.dumps(payload, indent=2, sort_keys=True) + "\n").encode()
    if args.check_archive:
        if OUTPUT.read_bytes() != rendered:
            raise ArithmeticError("product-family JSON archive changed")
        for path, content in artifacts.items():
            if path.read_bytes() != content:
                raise ArithmeticError(f"product-family artifact changed: {path}")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_bytes(rendered)
        for path, content in artifacts.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    print(json.dumps(payload["theorem"], sort_keys=True))
    print(OUTPUT)


if __name__ == "__main__":
    main()
