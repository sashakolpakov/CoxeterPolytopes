#!/usr/bin/env python3
"""Exact surface-MMP certificate for the rational P17 obstruction.

Starting from the 22 facet classes of Vinberg's odd-unimodular P17
chamber, push the complete curve cone through every numerically possible
(-1)-curve contraction.  The calculation is deliberately finite: a
K-negative extremal ray on a nonminimal smooth rational surface must be a
smooth rational (-1)-curve, and the pushforward cone is generated by the
images of the original facet curves.

The terminal minimal models are eight copies of the P2 marking and eight
copies of the F2 marking.  Both reconstruct the same eight canonical
classes, exactly the orbit of the standard canonical class under the full
weighted-diagram automorphism group.  This is the marking-classification
input for the unconditional rational-surface P17 no-go theorem.
"""

from __future__ import annotations

import argparse
from collections import Counter, defaultdict
from functools import reduce
import hashlib
import json
from math import gcd
from pathlib import Path
from typing import Iterable, Sequence

import networkx as nx
from sympy import Matrix

try:
    from scripts.certify_rational_i1n_inverse_design import enumerate_simple_roots
except ModuleNotFoundError:  # direct ``python scripts/...`` replay
    from certify_rational_i1n_inverse_design import enumerate_simple_roots


Vector = tuple[int, ...]
CurveState = tuple[Vector, ...]
ExceptionalBasis = tuple[Vector, ...]


def surface_pair(x: Sequence[int], y: Sequence[int]) -> int:
    """Intersection form diag(+1,-1^17)."""

    return x[0] * y[0] - sum(a * b for a, b in zip(x[1:], y[1:]))


def vector_add(x: Sequence[int], y: Sequence[int], scale: int = 1) -> Vector:
    return tuple(a + scale * b for a, b in zip(x, y))


def vector_sum(vectors: Iterable[Sequence[int]]) -> Vector:
    vectors = tuple(vectors)
    if not vectors:
        return (0,) * 18
    return tuple(sum(entries) for entries in zip(*vectors))


def primitive(vector: Sequence[int]) -> Vector:
    divisor = reduce(gcd, (abs(entry) for entry in vector if entry), 0)
    if divisor == 0:
        raise ValueError("zero vector has no primitive normalization")
    return tuple(entry // divisor for entry in vector)


def normalize_state(curves: Iterable[Sequence[int]]) -> CurveState:
    return tuple(sorted(set(tuple(curve) for curve in curves if any(curve))))


def contract_state(state: CurveState, exceptional: Vector) -> CurveState:
    """Pull back the image classes to exceptional^perp after blowdown."""

    if surface_pair(exceptional, exceptional) != -1:
        raise ValueError("only square-minus-one contractions are allowed")
    images = []
    for curve in state:
        if curve == exceptional:
            continue
        # If f contracts e, then f^* f_*D = D + (D.e)e.
        images.append(vector_add(curve, exceptional, surface_pair(curve, exceptional)))
    result = normalize_state(images)
    if any(surface_pair(curve, exceptional) for curve in result):
        raise AssertionError("pushforward pullbacks are not orthogonal to exceptional")
    return result


def enumerate_contraction_levels(
    roots: Sequence[Vector],
) -> tuple[dict[int, dict[CurveState, set[ExceptionalBasis]]], list[dict[str, int]]]:
    """Enumerate all states obtained by contracting current square -1 images."""

    levels: dict[int, dict[CurveState, set[ExceptionalBasis]]] = {
        18: {normalize_state(roots): {()}},
    }
    census: list[dict[str, int]] = []
    for rank in range(18, 1, -1):
        current = levels[rank]
        following: dict[CurveState, set[ExceptionalBasis]] = defaultdict(set)
        branch_count = 0
        for state, bases in current.items():
            exceptionals = [curve for curve in state if surface_pair(curve, curve) == -1]
            branch_count += len(exceptionals)
            for exceptional in exceptionals:
                image_state = contract_state(state, exceptional)
                for basis in bases:
                    if any(surface_pair(exceptional, old) for old in basis):
                        raise AssertionError("exceptional total transforms are not orthogonal")
                    new_basis = tuple(sorted((*basis, exceptional)))
                    following[image_state].add(new_basis)
        census.append(
            {
                "rank": rank,
                "state_count": len(current),
                "exceptional_basis_count": sum(len(value) for value in current.values()),
                "square_minus_one_branch_count": branch_count,
                "next_state_count": len(following),
                "next_exceptional_basis_count": sum(len(value) for value in following.values()),
            }
        )
        levels[rank - 1] = dict(following)
    return levels, census


def adjunction_profile(canonical: Vector, roots: Sequence[Vector]) -> tuple[int, ...]:
    return tuple(surface_pair(canonical, root) for root in roots)


def validate_canonical(canonical: Vector, roots: Sequence[Vector]) -> None:
    if surface_pair(canonical, canonical) != -8:
        raise AssertionError("rational rank-18 canonical square must be -8")
    if any(entry % 2 == 0 for entry in canonical):
        raise AssertionError("canonical vector is not characteristic in I_(1,17)")
    for root in roots:
        square = surface_pair(root, root)
        pairing = surface_pair(canonical, root)
        numerator = square + pairing
        if numerator % 2:
            raise AssertionError("adjunction parity failure")
        arithmetic_genus = 1 + numerator // 2
        if arithmetic_genus < 0:
            raise AssertionError("negative arithmetic genus for a facet curve")


def p2_canonical_classes(
    rank_one_states: dict[CurveState, set[ExceptionalBasis]],
    roots: Sequence[Vector],
) -> set[Vector]:
    result: set[Vector] = set()
    for state, bases in rank_one_states.items():
        positive = [curve for curve in state if surface_pair(curve, curve) > 0]
        if not positive:
            raise AssertionError("rank-one image cone has no positive class")
        line = primitive(positive[0])
        if surface_pair(line, line) != 1:
            raise AssertionError("rank-one primitive class is not a P2 line")
        if any(surface_pair(line, curve) < 0 for curve in state):
            line = tuple(-entry for entry in line)
        if any(surface_pair(line, curve) < 0 for curve in state):
            raise AssertionError("could not orient the P2 line toward the curve cone")
        for basis in bases:
            if len(basis) != 17:
                raise AssertionError("P2 endpoint must contract 17 curves")
            canonical = vector_add(vector_sum(basis), line, -3)
            validate_canonical(canonical, roots)
            if any(surface_pair(canonical, exceptional) != -1 for exceptional in basis):
                raise AssertionError("a contracted curve is not adjunction-rational")
            result.add(canonical)
    return result


def f2_canonical_classes(
    rank_two_states: dict[CurveState, set[ExceptionalBasis]],
    roots: Sequence[Vector],
) -> tuple[set[Vector], dict[str, int]]:
    result: set[Vector] = set()
    endpoint_types: Counter[str] = Counter()
    for state, bases in rank_two_states.items():
        negative = [curve for curve in state if surface_pair(curve, curve) < 0]
        isotropic = [curve for curve in state if surface_pair(curve, curve) == 0]
        if len(negative) != 1 or len(isotropic) != 1:
            raise AssertionError("unexpected rank-two image cone")
        section = negative[0]
        fiber = isotropic[0]
        if surface_pair(section, fiber) != 1:
            raise AssertionError("rank-two generators do not meet once")
        section_square = surface_pair(section, section)
        if section_square == -1:
            endpoint_types["F1_nonminimal"] += len(bases)
            continue
        if section_square != -2:
            raise AssertionError("a minimal ruled endpoint other than F2 appeared")
        endpoint_types["F2_minimal"] += len(bases)
        for basis in bases:
            if len(basis) != 16:
                raise AssertionError("F2 endpoint must contract 16 curves")
            # K_F2 = -2*section - 4*fiber.
            canonical = vector_add(
                vector_add(vector_sum(basis), section, -2),
                fiber,
                -4,
            )
            validate_canonical(canonical, roots)
            if any(surface_pair(canonical, exceptional) != -1 for exceptional in basis):
                raise AssertionError("a contracted curve is not adjunction-rational")
            result.add(canonical)
    return result, dict(sorted(endpoint_types.items()))


def weighted_diagram_automorphisms(roots: Sequence[Vector]) -> list[tuple[int, ...]]:
    graph = nx.Graph()
    for index, root in enumerate(roots):
        graph.add_node(index, square=surface_pair(root, root))
    for i in range(len(roots)):
        for j in range(i):
            intersection = surface_pair(roots[i], roots[j])
            if intersection:
                graph.add_edge(i, j, intersection=intersection)
    matcher = nx.algorithms.isomorphism.GraphMatcher(
        graph,
        graph,
        node_match=lambda left, right: left["square"] == right["square"],
        edge_match=lambda left, right: left["intersection"] == right["intersection"],
    )
    return sorted(tuple(mapping[i] for i in range(len(roots))) for mapping in matcher.isomorphisms_iter())


def validate_integral_lifts(
    roots: Sequence[Vector], automorphisms: Sequence[tuple[int, ...]]
) -> None:
    # R_1,...,R_17,L form a unimodular basis of I_(1,17).
    basis_indices = tuple(range(17)) + (17,)
    basis = Matrix([roots[index] for index in basis_indices])
    if abs(int(basis.det())) != 1:
        raise AssertionError("chosen root basis is not unimodular")
    inverse = basis.inv()
    all_roots = Matrix(roots)
    for permutation in automorphisms:
        image_basis = Matrix([roots[permutation[index]] for index in basis_indices])
        transformation = inverse * image_basis
        if any(entry.q != 1 for entry in transformation):
            raise AssertionError("diagram automorphism does not lift integrally")
        if abs(int(transformation.det())) != 1:
            raise AssertionError("diagram lift is not unimodular")
        if all_roots * transformation != Matrix([roots[permutation[i]] for i in range(len(roots))]):
            raise AssertionError("lift does not realize the full root permutation")


def automorphism_orbit_profiles(
    roots: Sequence[Vector], automorphisms: Sequence[tuple[int, ...]]
) -> set[tuple[int, ...]]:
    standard = (-3,) + (1,) * 17
    standard_profile = adjunction_profile(standard, roots)
    orbit = set()
    for permutation in automorphisms:
        profile = [0] * len(roots)
        for source, target in enumerate(permutation):
            profile[target] = standard_profile[source]
        orbit.add(tuple(profile))
    return orbit


def build_certificate() -> dict[str, object]:
    roots = [tuple(root) for root in enumerate_simple_roots(17)]
    if len(roots) != 22:
        raise AssertionError("P17 must have 22 facets")
    if any(surface_pair(left, right) < 0 for i, left in enumerate(roots) for right in roots[:i]):
        raise AssertionError("distinct effective facet classes intersect negatively")

    levels, level_census = enumerate_contraction_levels(roots)
    p2_classes = p2_canonical_classes(levels[1], roots)
    f2_classes, endpoint_types = f2_canonical_classes(levels[2], roots)
    if endpoint_types != {"F1_nonminimal": 8, "F2_minimal": 8}:
        raise AssertionError(endpoint_types)
    if len(levels[1]) != 8 or len(p2_classes) != 8:
        raise AssertionError("expected eight P2 endpoint markings")
    if len(f2_classes) != 8 or f2_classes != p2_classes:
        raise AssertionError("P2 and F2 endpoint canonical classes disagree")

    automorphisms = weighted_diagram_automorphisms(roots)
    if len(automorphisms) != 8:
        raise AssertionError("unexpected weighted-diagram automorphism order")
    validate_integral_lifts(roots, automorphisms)
    orbit_profiles = automorphism_orbit_profiles(roots, automorphisms)
    endpoint_profiles = {adjunction_profile(canonical, roots) for canonical in p2_classes}
    if endpoint_profiles != orbit_profiles:
        raise AssertionError("MMP canonical classes are not exactly the diagram orbit")

    certificate: dict[str, object] = {
        "schema": "rational_p17_mmp_v1",
        "lattice": "I_(1,17)",
        "hyperbolic_dimension": 17,
        "facet_count": 22,
        "surface_rank": 18,
        "surface_canonical_square": -8,
        "contraction_level_census": level_census,
        "rank_two_endpoint_types": endpoint_types,
        "rank_one_P2_endpoint_count": len(levels[1]),
        "canonical_class_count": len(p2_classes),
        "canonical_classes": [list(vector) for vector in sorted(p2_classes)],
        "canonical_facet_pairing_profiles": [list(profile) for profile in sorted(endpoint_profiles)],
        "weighted_diagram_automorphism_order": len(automorphisms),
        "weighted_diagram_automorphisms_zero_based": [list(permutation) for permutation in automorphisms],
        "all_diagram_automorphisms_lift_to_integral_unimodular_isometries": True,
        "p2_and_f2_reconstructions_agree": True,
        "canonical_classes_equal_standard_diagram_orbit": True,
        "geometric_conclusion": (
            "Any smooth rational surface whose complete Mori cone is generated by the "
            "P17 facet curves has canonical class in the order-eight diagram orbit of "
            "the standard plane-blowup canonical class.  After conjugating the marking, "
            "the B17 chain is a rational exceptional chain and the flex-cubic Abel "
            "obstruction applies."
        ),
    }
    canonical_payload = json.dumps(certificate, sort_keys=True, separators=(",", ":")).encode()
    certificate["certificate_payload_sha256"] = hashlib.sha256(canonical_payload).hexdigest()
    return certificate


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    rendered = json.dumps(build_certificate(), indent=2, sort_keys=True) + "\n"
    if args.output is None:
        print(rendered, end="")
    else:
        args.output.write_text(rendered)


if __name__ == "__main__":
    main()
