#!/usr/bin/env python3
"""Finish the nonzero spacelike-face classification without a field cutoff.

Four of the six directions left by the contact-sum theorem have a strict
single-contact bound below1. The remaining two saturate a contact bound1,
forcing projection norm2 and zero passive part: the original unique poles.
"""
import argparse,json
from hashlib import sha256
import fresh_raw23_four_face_contact_preflight_20261018 as F

ROOT=F.ROOT;P=F.P;H=F.H;Q=F.Q
SUM='fresh_raw23_spacelike_contact_sum_20261018'
TAG='fresh_raw23_spacelike_pole_classification_20261018'

def run():
    old=H.read(P.TAG);summed=H.read(SUM);H.bind(old);H.bind(summed)
    assert summed['all_nonzero_spacelike_ray_combinations_reduced_to_six_ray_directions']and not summed['zero_projection_excluded']
    cases=[];strict=forced=0
    for c,o in zip(summed['cases'],old['cases'],strict=True):
        assert c['kinds']==o['kinds']and c['remaining_projected_ray_directions']==[6,31]
        by={r['index']:r for r in o['initial_cone']['rays']};metric=H.mat(o['metric']);sc=F.vec(o['original_squared_scales']);records=[]
        for ray in c['remaining_projected_ray_directions']:
            r=by[ray];x=F.vec(r['coordinates']);p=[-z for z in F.vec(r['products'])];norm=P.inner(x,metric,x)
            assert norm.sign()>0 and all(z.sign()>=0 for z in p)
            bounds=[2*z*z/norm/s for z,s in zip(p,sc)]
            below=[j for j,z in enumerate(p)if z!=0 and(bounds[j]-1).sign()<0]
            rec=dict(ray=ray,coordinates=x,squared_norm=norm,contact_magnitudes=p,
                physical_contact_square_upper=bounds,strict_excluding_walls=below)
            if below:
                strict+=1;rec.update(status='strict_contact_exclusion',forced_pole=None)
            else:
                forced+=1;anchors=[j for j,z in enumerate(p)if z!=0 and bounds[j]==1 and sc[j]==1]
                assert anchors;anchor=anchors[0];scale=Q(1)/p[anchor];pole=[scale*z for z in x]
                assert P.inner(pole,metric,pole)==2
                squares=[scale*scale*z*z/s for z,s in zip(p,sc)]
                phi2=Q('3/2','1/2');labels=[]
                for z,q in zip(p,squares):
                    if z==0:assert q==0;labels.append(2)
                    elif q==1:labels.append(3)
                    else:assert q==phi2;labels.append(5)
                assert sum(m==3 for m in labels)==2 and sum(m==5 for m in labels)==1
                frozen=next(v for v in o['initial_polar_tests']['candidates']if v['ray']==ray)
                assert frozen['passes_necessary_polar_gates']and F.vec(frozen['physical_squared_contacts'])==squares
                rec.update(status='unique_pure_pole',anchor_wall=anchor,anchor_physical_upper='1',
                    forced_projection_squared_norm='2',forced_passive_squared_norm='0',
                    forced_pole=dict(scale=scale,coordinates=pole,physical_contact_squares=squares,labels=labels))
            records.append(rec)
        expected=[]if o['kinds']==[1,6]else[31]if o['kinds']==[1,1]else[6]
        assert [r['ray']for r in records if r['status']=='unique_pure_pole']==expected==o['initial_polar_tests']['passing_rays']
        cases.append(dict(kinds=o['kinds'],ray_tests=records,compatible_poles_in_nonzero_spacelike_face=expected))
    assert strict==4 and forced==2
    paths={f'scripts/{TAG}.py',f'scripts/{F.TAG}.py',f'results/{F.TAG}.json',f'results/{F.TAG}.md',
        f'scripts/{P.TAG}.py',f'results/{P.TAG}.json',f'results/{P.TAG}.md',
        f'scripts/{SUM}.py',f'results/{SUM}.json',f'results/{SUM}.md'}
    return P.enc(dict(status='PASS_RAW23_NONZERO_SPACELIKE_FACE_POLE_CLASSIFICATION',
        sources={p:sha256((ROOT/p).read_bytes()).hexdigest()for p in sorted(paths)},cases=cases,
        nonzero_spacelike_generated_domain_complete=True,additional_strict_ray_exclusions=4,
        forced_original_poles=2,forced_passive_part_zero=True,extension_field_restricted=False,
        zero_projection_excluded=False,timelike_generator_directions_excluded=False,
        arbitrary_completion_excluded=False,model_or_capacity_changed=False,new_dimension_bound=None,
        scope='For nonzero projections in each original cone generated by all32spacelike rays, the complete contact-sum theorem leaves six rays. Four are universally impossible, and two saturate a bound1, forcing the original pure poles with no passive part. No field or finite-angle cutoff. Zero projections, timelike-generator directions and arbitrary completions remain open.'))

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--verify',action='store_true');a=ap.parse_args()
    path=ROOT/f'results/{TAG}.json';assert a.verify or not path.exists();out=run()
    if a.verify:assert out==json.loads(path.read_text())
    else:path.write_text(json.dumps(out,indent=2)+'\n')
    print(out['status'],out['additional_strict_ray_exclusions'],out['forced_original_poles'],flush=True)
