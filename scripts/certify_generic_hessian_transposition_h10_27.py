    if args.check_inputs:
        expected = {STOCK: STOCK_SHA256, KNOWN: KNOWN_SHA256, CPP_SOURCE: CPP_SHA256}
        for path, digest in expected.items():
            if _sha256(path) != digest:
                raise ArithmeticError(f"pinned input changed: {path}")
    payload = build_payload()
    encoded = json.dumps(payload, indent=2, sort_keys=True) + "\n"
    if args.check_archive:
        if not OUTPUT.exists() or OUTPUT.read_text() != encoded:
            raise ArithmeticError(f"archive mismatch: {OUTPUT}")
        print(f"archive matches: {OUTPUT}")
        return
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(encoded)
    print(json.dumps({
        "output": str(OUTPUT),
        "id": payload["id"],
        "facets": payload["restricted_chamber"]["negative_genuine_facet_count"],
        "finite_vertices": payload["literal_vinberg"]["finite_vertex_count"],
        "cusps": payload["literal_vinberg"]["ideal_vertex_count"],
        "known_abstract_polytope": payload["lineage"]["known_id"],
        "all_checks_pass": payload["all_checks_pass"],
    }, indent=2))


