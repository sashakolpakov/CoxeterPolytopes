def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _canonical_sha256(value: Any) -> str:
    return hashlib.sha256(
        json.dumps(value, sort_keys=True, separators=(",", ":")).encode()
    ).hexdigest()


def _cycles(action: Sequence[int]) -> list[list[int]]:
    seen: set[int] = set()
    result = []
    for start in range(len(action)):
        if start in seen:
            continue
        cycle = []
        current = start
        while current not in seen:
            seen.add(current)
            cycle.append(current)
            current = action[current]
        result.append(cycle)
    return result


def _matrix_payload(matrix: sp.Matrix) -> list[list[str]]:
    return [[_text(matrix[i, j]) for j in range(matrix.cols)] for i in range(matrix.rows)]


def _integer_payload(matrix: sp.Matrix) -> list[list[int]]:
    if any(value.is_Integer is not True for value in matrix):
        raise ArithmeticError("expected an integral matrix")
    return [[int(matrix[i, j]) for j in range(matrix.cols)] for i in range(matrix.rows)]


def _picard_model() -> dict[str, Any]:
    pivots, quotient_gram, quotient_gram_inverse = _basis_data()
    curve_coordinates = sp.Matrix.hstack(
        *(
            _basis_coordinates(_unit(label), pivots, quotient_gram_inverse)
            for label in FORMAL_LABELS
        )
    )
    denominator = int(sp.ilcm(*[sp.Rational(value).q for value in curve_coordinates]))
    picard_basis = hermite_normal_form(
        (denominator * curve_coordinates).applyfunc(int)
    ) / denominator
    picard_gram = picard_basis.T * quotient_gram * picard_basis
    if not (
        picard_basis.det() == sp.Rational(1, 2)
        and picard_gram.det() == -48
        and exact_inertia(picard_gram) == (1, 15, 0)
    ):
        raise ArithmeticError("the Picard lattice reconstructed from twenty curves changed")

    transposition = (2, 1, 3, 4, 5)
    quotient_action = _divisor_action_matrix(
        transposition, 0, pivots, quotient_gram_inverse
    )
    picard_action = sp.simplify(picard_basis.inv() * quotient_action * picard_basis)
    if not (
        all(value.is_Integer for value in picard_action)
        and picard_action**2 == sp.eye(16)
        and picard_action.T * picard_gram * picard_action == picard_gram
    ):
        raise ArithmeticError("the transposition is not an integral Picard isometry")

    # The helper applies Smith decomposition to the equation matrix.  Passing
    # A^T asks for the saturated column kernel of A-I.
    fixed_rows, kernel_audit = _saturated_fixed_basis((picard_action.T,), 16)
    fixed_basis = fixed_rows.T
    if picard_action * fixed_basis != fixed_basis:
        raise ArithmeticError("fixed Picard basis failed replay")
    fixed_gram = fixed_basis.T * picard_gram * fixed_basis
    fixed_smith = [
        abs(int(value))
        for value in smith_normal_form(fixed_gram, domain=sp.ZZ).diagonal()
    ]
    if not (
        fixed_basis.cols == 11
        and fixed_gram.det() == 256
        and exact_inertia(fixed_gram) == (1, 10, 0)
        and fixed_smith == [1, 1, 1, 1, 2, 2, 2, 2, 2, 2, 4]
    ):
        raise ArithmeticError("fixed Picard lattice invariants changed")
    return {
        "pivots": pivots,
        "quotient_gram": quotient_gram,
        "quotient_gram_inverse": quotient_gram_inverse,
        "picard_basis": picard_basis,
        "picard_gram": picard_gram,
        "picard_action": picard_action,
        "fixed_basis": fixed_basis,
        "fixed_gram": fixed_gram,
        "fixed_smith": fixed_smith,
        "kernel_audit": kernel_audit,
    }


def _fold_data(picard: dict[str, Any]) -> dict[str, Any]:
    walls, source_types = wall_stock()
    action = _wall_action(walls, (2, 1, 3, 4, 5), 0)
    cycles = _cycles(action)
    if Counter(map(len, cycles)) != {1: 12, 2: 36}:
        raise ArithmeticError("transposition wall orbit census changed")

    roots = [_add(*(walls[index] for index in cycle)) for cycle in cycles]
    orbit_gram = sp.Matrix([[_pair(left, right) for right in roots] for left in roots])
    negative = [index for index in range(len(roots)) if orbit_gram[index, index] < 0]
    isotropic = [index for index in range(len(roots)) if orbit_gram[index, index] == 0]
    if not (
        orbit_gram.rank() == 11
        and exact_inertia(orbit_gram) == (1, 10, 37)
        and len(negative) == 27
        and len(isotropic) == 21
        and Counter(orbit_gram[index, index] for index in negative)
        == {-2: 8, -4: 13, -36: 6}
    ):
        raise ArithmeticError("restricted-wall signature/count changed")

    # omega' = sum N + sum T is the projected Conway Weyl vector and is an
    # interior ample class (Dolgachev--Keum, Lemma 7.3 and Section 8).
    ample = _vector((kind, label, 1) for kind, label in FORMAL_LABELS)
    if _pair(ample, ample) != 20:
        raise ArithmeticError("projected Weyl-vector square changed")
    witness_records = []
    for index in negative:
        root = roots[index]
        norm = _pair(root, root)
        pairing = _pair(ample, root)
        witness = _add(ample, _scale(-pairing / norm, root))
        pairings = [_pair(witness, other) for other in roots]
        square = _pair(witness, witness)
        passes = bool(
            square > 0
            and pairings[index] == 0
            and all(value > 0 for position, value in enumerate(pairings) if position != index)
        )
        witness_records.append(
            {
                "restricted_orbit_zero_based": index,
                "source_walls_one_based": [value + 1 for value in cycles[index]],
                "root_norm": _text(norm),
                "witness_square": _text(square),
                "target_pairing": _text(pairings[index]),
                "minimum_other_pairing_including_isotropic_restrictions": _text(
                    min(value for position, value in enumerate(pairings) if position != index)
                ),
                "strict_timelike_facet_witness": passes,
            }
        )
    if not all(row["strict_timelike_facet_witness"] for row in witness_records):
        raise ArithmeticError("a retained negative restriction is not a genuine facet")

    facet_gram = orbit_gram.extract(negative, negative)
    relations = _relation_matrix(
        [[str(-facet_gram[i, j]) for j in range(facet_gram.cols)] for i in range(facet_gram.rows)]
    )
    relation_histogram = Counter(
        relations[left][right]
        for right in range(27)
        for left in range(right)
    )
    if relation_histogram != {"2": 235, "3": 15, "4": 14, "0": 48, "1": 39}:
        raise ArithmeticError(f"Coxeter relation histogram changed: {relation_histogram}")

    # Place the primitive mirrors inside the saturated fixed Picard lattice.
    fixed_records = []
    fixed_gram = picard["fixed_gram"]
    for facet_position, orbit_index in enumerate(negative):
        quotient_coordinates = _basis_coordinates(
            roots[orbit_index], picard["pivots"], picard["quotient_gram_inverse"]
        )
        picard_coordinates = picard["picard_basis"].inv() * quotient_coordinates
        fixed_coordinates = picard["fixed_basis"].gauss_jordan_solve(picard_coordinates)[0]
        if any(value.is_Integer is not True for value in fixed_coordinates):
            raise ArithmeticError("orbit root is not integral in the fixed Picard lattice")
        content = math.gcd(*(abs(int(value)) for value in fixed_coordinates if value))
        primitive = fixed_coordinates / content
        square = int((primitive.T * fixed_gram * primitive)[0])
        divisibility = math.gcd(*(abs(int(value)) for value in fixed_gram * primitive))
        reflection = sp.eye(11) - sp.Rational(2, square) * primitive * (primitive.T * fixed_gram)
        integral = all(value.is_Integer for value in reflection)
        if not integral:
            raise ArithmeticError("a folded facet reflection is nonintegral")
        fixed_records.append(
            {
                "facet_one_based": facet_position + 1,
                "source_orbit_zero_based": orbit_index,
                "orbit_sum_content_in_fixed_lattice": content,
                "primitive_square": square,
                "primitive_divisibility": divisibility,
                "reflection_integral": integral,
            }
        )
    reflection_types = Counter(
        (row["primitive_square"], row["primitive_divisibility"])
        for row in fixed_records
    )
    if reflection_types != {(-2, 1): 8, (-4, 2): 10, (-4, 4): 9}:
        raise ArithmeticError(f"fixed mirror types changed: {reflection_types}")

    return {
        "walls": walls,
        "source_types": source_types,
        "action": action,
        "cycles": cycles,
        "roots": roots,
        "orbit_gram": orbit_gram,
        "negative": negative,
        "isotropic": isotropic,
        "facet_gram": facet_gram,
        "relations": relations,
        "relation_histogram": relation_histogram,
        "witness_records": witness_records,
        "fixed_records": fixed_records,
        "reflection_types": reflection_types,
    }


