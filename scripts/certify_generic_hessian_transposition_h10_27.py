def _graph(matrix: Sequence[Sequence[str]]) -> nx.Graph:
    graph = nx.Graph()
    graph.add_nodes_from(range(len(matrix)))
    for right in range(len(matrix)):
        for left in range(right):
            graph.add_edge(left, right, relation=matrix[left][right])
    return graph


def _lineage(relations: list[list[str]]) -> dict[str, Any]:
    known = json.loads(KNOWN.read_text())
    target = known["bounded_weighted_diagram_audit"]["candidate_relation_matrix"]
    matcher = nx.algorithms.isomorphism.GraphMatcher(
        _graph(relations),
        _graph(target),
        edge_match=nx.algorithms.isomorphism.categorical_edge_match("relation", None),
    )
    if not matcher.is_isomorphic():
        raise ArithmeticError("new H10/27 diagram is not the known D16-D4-C7 diagram")
    mapping = [matcher.mapping[index] + 1 for index in range(27)]
    if mapping != EXPECTED_LINEAGE_PERMUTATION:
        raise ArithmeticError(f"lineage permutation changed: {mapping}")
    if not all(
        relations[i][j] == target[mapping[i] - 1][mapping[j] - 1]
        for i in range(27)
        for j in range(27)
    ):
        raise ArithmeticError("explicit lineage permutation failed entrywise replay")
    return {
        "known_id": known["candidate"]["id"],
        "exact_new_to_known_facet_permutation_one_based": mapping,
        "normalized_relation_matrices_match_entrywise": True,
        "known_full_reflection_chamber_facets": known["known_full_reflection_chamber"]["facet_count"],
        "known_reflection_subgroup_index": known["solomon_index"]["index"],
        "new_abstract_polytope": False,
        "new_arithmetic_class": False,
        "new_maximal_reflection_group": False,
        "new_algebraic_divisor_stock_realization_candidate": True,
        "worldwide_priority_claimed": False,
    }


