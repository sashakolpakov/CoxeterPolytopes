"""Exact K3-wall completion for Bugaenko's compact chamber.

The trace lattice attached to Bugaenko's rank-nine ``Z[phi]``-lattice is an
even K3 lattice.  A trace-lattice ``(-2)`` vector whose hyperplane meets the
identity eigenspace has one of five totally-positive field norms.  Evenness of
the field form leaves only norms ``2`` and ``4-2*phi``; multiplication by the
unit ``phi`` identifies the latter hyperplane with a norm-two mirror.

Consequently the exact Vinberg completion of the norm-two reflection chamber
also completes the restricted K3 wall arrangement.  This module additionally
enumerates every such mirror that meets the *closed* compact chamber.  A
mirror meeting a Coxeter chamber but not its interior contains a face, hence a
vertex.  At each of the 41 vertices the mirrors through it are precisely the
finite root system generated by the eight incident facets.  Reflection
closure of those finite parabolics is therefore a proved finite enumeration,
not a metric cutoff.
"""

