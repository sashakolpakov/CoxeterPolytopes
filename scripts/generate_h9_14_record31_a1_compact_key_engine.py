#!/usr/bin/env python3
"""Generate a memory-compact but semantically identical Record-31 a=1 engine.

The production quotient engine generated by
``generate_h9_14_record31_a1_addition_engine.py`` stores the complete dense
canonical adjacency matrix returned by nauty as each quotient key.  At depth
six this is a 25-by-25 graph, hence a 200-byte string for every state.  There
can be more than one hundred million such states.

Every graph passed to nauty is, by construction, a colored bipartite
incidence graph: the first color cell contains the fourteen ground vertices,
and every remaining vertex is a row node adjacent only to that first cell.
The color partition fixes those cell boundaries in the canonical graph.
Consequently the ordered canonical row-to-ground incidence bits reconstruct
the full canonical graph injectively.  This generator replaces only the key
serialization, packing those bits into at most 22 bytes.  Nauty, the search
tree, pruning predicates, and target canonicalization are otherwise unchanged.

When compiled with ``-DRECORD31_VERIFY_COMPACT_KEY``, every generated key is
decoded logically and compared with every entry of the dense canonical graph.
This expensive assertion is intended for bounded equivalence replays only.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from scripts.generate_h9_14_record31_a1_addition_engine import (
    generate as generate_dense,
    replace_exact,
)


DENSE_RETURN = """  return std::string(reinterpret_cast<const char*>(canonical.data()),
                     canonical.size() * sizeof(graph));
"""

COMPACT_RETURN = r"""  // The canonical graph is colored bipartite.  Cell order is fixed by
  // the supplied nauty partition: ground vertices first, followed by the
  // graph-edge, A4, and A5 row cells.  Its ordered row incidences therefore
  // determine the entire dense canonical graph injectively.
  const int row_count = node_count - kN;
  const int incidence_bits = row_count * kN;
  std::string code(1 + (incidence_bits + 7) / 8, '\0');
  code[0] = static_cast<char>(row_count);
  for (int row = 0; row < row_count; ++row) {
    const set* adjacency = GRAPHROW(canonical.data(), kN + row, words);
    for (int vertex = 0; vertex < kN; ++vertex) {
      if (!ISELEMENT(adjacency, vertex)) continue;
      const int bit = row * kN + vertex;
      code[1 + bit / 8] = static_cast<char>(
          static_cast<unsigned char>(code[1 + bit / 8]) |
          static_cast<unsigned char>(1u << (bit % 8)));
    }
  }

#ifdef RECORD31_VERIFY_COMPACT_KEY
  // Exact bounded-run assertion: the packed key must recover every dense
  // adjacency bit, including the assertion that no hidden same-cell edge
  // was discarded.  Thus equality of compact keys is equivalent to equality
  // of the original dense canonical keys.
  for (int left = 0; left < node_count; ++left) {
    const set* adjacency = GRAPHROW(canonical.data(), left, words);
    for (int right = 0; right < node_count; ++right) {
      const bool dense = ISELEMENT(adjacency, right);
      bool recovered = false;
      int row = -1;
      int vertex = -1;
      if (left < kN && right >= kN) {
        vertex = left;
        row = right - kN;
      } else if (right < kN && left >= kN) {
        vertex = right;
        row = left - kN;
      }
      if (row >= 0) {
        const int bit = row * kN + vertex;
        recovered =
            (static_cast<unsigned char>(code[1 + bit / 8]) >> (bit % 8)) & 1u;
      }
      if (dense != recovered) {
        throw std::runtime_error(
            "compact canonical key failed dense-graph round trip");
      }
    }
  }
#endif
  return code;
"""


def generate_compact() -> str:
    """Return the exact a=1 engine with compact canonical serialization."""

    return replace_exact(generate_dense(), DENSE_RETURN, COMPACT_RETURN)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    arguments = parser.parse_args()
    arguments.output.write_text(generate_compact(), encoding="utf-8")


if __name__ == "__main__":
    main()
