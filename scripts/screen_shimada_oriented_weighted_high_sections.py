def _matrix(payload: list[list[str]]) -> sp.Matrix:
    return sp.Matrix([[sp.Rational(value) for value in row] for row in payload])


def _saturated_fixed_divisor_lattice(
    primal_actions: tuple[sp.Matrix, ...],
    ambient_gram: sp.Matrix,
    expected_rank: int,
) -> dict[str, Any]:
    """Compute ``Z^20 intersect Fix_Q(H)`` from a reduced exact row space."""

    full_constraints = sp.Matrix.vstack(
        *(matrix.T - sp.eye(AMBIENT_RANK) for matrix in primal_actions)
    )
    _, independent_rows = full_constraints.T.rref()
    constraints = full_constraints[list(independent_rows), :]
    if constraints.rank() != AMBIENT_RANK - expected_rank:
        raise ArithmeticError("the rational fixed rank disagrees with inventory")
    denominator = int(sp.ilcm(*(sp.Rational(value).q for value in constraints)))
    integral_constraints = denominator * constraints
    if any(not value.is_Integer for value in integral_constraints):
        raise ArithmeticError("fixed constraints did not clear integrally")
    diagonal, _, right = _smith_decomposition(integral_constraints)
    zero_columns = tuple(
        column
        for column in range(AMBIENT_RANK)
        if all(diagonal[row, column] == 0 for row in range(diagonal.rows))
    )
    if len(zero_columns) != expected_rank:
        raise ArithmeticError("Smith kernel rank disagrees with inventory")
    smith_basis = right[:, list(zero_columns)].T
    basis = smith_basis.lll(delta=sp.Rational(3, 4))
    _, pivot_columns = smith_basis.rref()
    change = basis[:, list(pivot_columns)] * smith_basis[:, list(pivot_columns)].inv()
    if not (
        basis.rank() == expected_rank
        and basis * full_constraints.T
        == sp.zeros(expected_rank, full_constraints.rows)
        and all(basis * action == basis for action in primal_actions)
        and change * smith_basis == basis
        and abs(int(change.det())) == 1
    ):
        raise ArithmeticError("saturated divisor fixed lattice failed exact replay")
    gram = basis * ambient_gram * basis.T
    if exact_inertia(gram) != (1, expected_rank - 1, 0):
        raise ArithmeticError("fixed divisor lattice is not Lorentzian")
    smith = smith_normal_form(gram, domain=ZZ)
    return {
        "full_constraint_row_count": full_constraints.rows,
        "independent_constraint_row_indices": list(independent_rows),
        "rational_constraint_rank": constraints.rows,
        "clearing_denominator": denominator,
        "smith_constraint_diagonal": [
            int(diagonal[index, index])
            for index in range(min(diagonal.rows, diagonal.cols))
        ],
        "basis": basis,
        "gram": gram,
        "determinant": int(gram.det()),
        "smith_diagonal_absolute": [
            abs(int(smith[index, index])) for index in range(expected_rank)
        ],
    }


def _action_lookup(chamber: dict[str, Any]) -> dict[Permutation, dict[str, Any]]:
    records = {}
    group = chamber["oriented_weighted_wall_group"]
    for record in group["all_actions"]:
        permutation = tuple(map(int, record["permutation"]))
        if permutation in records:
            raise ArithmeticError("duplicate weighted-wall permutation")
        records[permutation] = record
    if len(records) != group["order"]:
        raise ArithmeticError("weighted-wall action list is incomplete")
    return records


def screen_case(
    atlas: ShimadaDisc11Atlas,
    discriminant: int,
    source_hash: str,
    inventory_path: Path,
    inventory_hash: str,
    chamber_record: dict[str, Any],
    class_record: dict[str, Any],
) -> dict[str, Any]:
    chamber_index = int(chamber_record["chamber_index"])
    class_index = int(class_record["class_index"])
    if not (
        class_record["order"] > 1
        and class_record["fixed_rank"] >= MIN_FIXED_RANK
    ):
        raise ArithmeticError("selected class is not a proper high fixed section")
    chamber = atlas.chamber(chamber_index)
    ambient_gram = sp.Matrix(atlas.gram)
    dual_gram = ambient_gram.inv()
    walls_tuple, orientation = _oriented_walls(atlas, chamber_index, dual_gram)
    if not (
        walls_tuple
        and len(walls_tuple) == chamber_record["wall_count"]
        and orientation == chamber_record["orientation"]
    ):
        raise ArithmeticError("oriented wall stock differs from inventory")
    wall_matrix = sp.Matrix(walls_tuple)
    walls = tuple(sp.Matrix(1, AMBIENT_RANK, wall) for wall in walls_tuple)

    published_ample_dual = sp.Matrix(
        1,
        AMBIENT_RANK,
        _row_product(chamber.weyl, atlas.projection_to_s_dual),
    )
    oriented_pairings = tuple(
        sp.Rational(value)
        for value in published_ample_dual * dual_gram * wall_matrix.T
    )
    if any(value < 0 for value in oriented_pairings):
        raise ArithmeticError("an oriented wall excludes the published Weyl vector")
    zero_positions = tuple(
        index for index, value in enumerate(oriented_pairings) if value == 0
    )
    source_interior_dual, source_interior_record = _strict_interior_from_oriented_walls(
        published_ample_dual, ambient_gram, wall_matrix, zero_positions
    )

    lookup = _action_lookup(chamber_record)
    subgroup: Subgroup = frozenset(
        tuple(map(int, permutation)) for permutation in class_record["elements"]
    )
    if not (len(subgroup) == class_record["order"] and subgroup.issubset(lookup)):
        raise ArithmeticError("subgroup wall permutations are incomplete")
    dual_actions = tuple(_matrix(lookup[element]["dual_row_action"]) for element in subgroup)
    archived_primals = tuple(_matrix(lookup[element]["primal_row_action"]) for element in subgroup)
    primal_actions = tuple(ambient_gram * action * dual_gram for action in dual_actions)
    action_denominators = []
    for permutation, dual, primal, archived_primal in zip(
        subgroup, dual_actions, primal_actions, archived_primals, strict=True
    ):
        expected = wall_matrix[[permutation[index] for index in range(len(walls))], :]
        denominator = int(sp.ilcm(*(sp.Rational(value).q for value in primal)))
        if not (
            wall_matrix * dual == expected
            and dual * dual_gram * dual.T == dual_gram
            and primal == archived_primal
            and primal * ambient_gram * primal.T == ambient_gram
            and denominator == lookup[permutation]["primal_action_denominator_lcm"]
        ):
            raise ArithmeticError("a weighted-wall Lorentz lift failed exact replay")
        action_denominators.append(denominator)

    fixed = _saturated_fixed_divisor_lattice(
        primal_actions, ambient_gram, int(class_record["fixed_rank"])
    )
    fixed_basis: sp.Matrix = fixed["basis"]
    fixed_gram: sp.Matrix = fixed["gram"]
    fixed_rank = fixed_basis.rows

    averaged_interior_dual = sum(
        (source_interior_dual * action for action in dual_actions),
        sp.zeros(1, AMBIENT_RANK),
    ) / len(dual_actions)
    if any(averaged_interior_dual * action != averaged_interior_dual for action in dual_actions):
        raise ArithmeticError("averaged interior is not fixed")
    ample = _fixed_coordinates_of_ample(
        averaged_interior_dual, ambient_gram, fixed_basis
    )
    if (ample.T * fixed_gram * ample)[0] <= 0:
        raise ArithmeticError("averaged fixed interior is not timelike")

    wall_orbits = _orbits(subgroup, len(walls))
    orbit_normals = tuple(
        sum((walls[index] for index in orbit), sp.zeros(1, AMBIENT_RANK))
        for orbit in wall_orbits
    )
    if any(
        normal * action != normal
        for normal in orbit_normals
        for action in dual_actions
    ):
        raise ArithmeticError("folded wall sum is not fixed")
    pairing_matrix = sp.Matrix.hstack(
        *(fixed_basis * normal.T for normal in orbit_normals)
    )
    if pairing_matrix.rank() != fixed_rank:
        raise ArithmeticError("folded walls do not span the fixed dual space")
    inverse_fixed_gram = fixed_gram.inv()
    orbit_gram = pairing_matrix.T * inverse_fixed_gram * pairing_matrix
    ambient_orbit_gram = (
        sp.Matrix.vstack(*orbit_normals)
        * dual_gram
        * sp.Matrix.vstack(*orbit_normals).T
    )
    if not (
        orbit_gram == ambient_orbit_gram
        and exact_inertia(orbit_gram)
        == (1, fixed_rank - 1, len(wall_orbits) - fixed_rank)
    ):
        raise ArithmeticError("fixed and ambient folded mirror Grams differ")
    ample_pairings = tuple(sp.Rational(value) for value in ample.T * pairing_matrix)
    if any(value <= 0 for value in ample_pairings):
        raise ArithmeticError("averaged interior is not strict in folded cone")

    coordinates = pairing_matrix.T
    conic_facets = []
    conic_redundant = []
    for target in range(len(wall_orbits)):
        destination = (
            conic_redundant
            if _exact_nonnegative_dependence(coordinates, target) is not None
            else conic_facets
        )
        destination.append(target)
    redundancy_certificates = []
    for target in conic_redundant:
        dependence = _dependence_on_retained_facets(
            coordinates, target, tuple(conic_facets)
        )
        redundancy_certificates.append(
            {
                "orbit_index": target + 1,
                "terms": [
                    {
                        "facet_orbit_index": support + 1,
                        "coefficient": _rational_text(coefficient),
                    }
                    for support, coefficient in dependence
                ],
            }
        )

    active_facets: list[int] = []
    causal_inactive: list[int] = []
    unresolved: list[int] = []
    witnesses = []

    def accept_witness(target: int, result: tuple[sp.Matrix, dict[str, Any]]) -> None:
        witness, record = result
        square, pairings = _audit_witness(witness, target, fixed_gram, pairing_matrix)
        record |= {
            "orbit_index": target + 1,
            "fixed_divisor_lattice_coordinates": [
                _rational_text(sp.Rational(value)) for value in witness
            ],
            "witness_square": _rational_text(square),
            "minimum_strict_pairing": _rational_text(
                min(value for index, value in enumerate(pairings) if index != target)
            ),
        }
        active_facets.append(target)
        witnesses.append(record)

    for target in conic_facets:
        if orbit_gram[target, target] >= 0:
            causal_inactive.append(target)
            continue
        result = _strict_timelike_witness(
            target, fixed_gram, pairing_matrix, orbit_gram, ample
        )
        if result is None:
            result = _simplicial_exact_facet_witness(
                target, fixed_gram, pairing_matrix
            )
        if result is None:
            unresolved.append(target)
        else:
            accept_witness(target, result)

    preliminary = _pair_gate(orbit_gram.extract(active_facets, active_facets))
    if unresolved and preliminary["non_coxeter_pair_count"] == 0:
        still_unresolved = []
        for target in unresolved:
            result = _exact_face_ray_facet_witness(
                target, fixed_gram, pairing_matrix
            )
            if result is None:
                still_unresolved.append(target)
            else:
                accept_witness(target, result)
        unresolved = still_unresolved

    active_facets.sort()
    witnesses.sort(key=lambda record: record["orbit_index"])
    facet_gram = orbit_gram.extract(active_facets, active_facets)
    pair_gate = _pair_gate(facet_gram)
    if pair_gate["non_coxeter_pair_count"]:
        classification = "not_coxeter"
    elif unresolved:
        classification = "unresolved_facet_causality"
    else:
        classification = "coxeter_candidate_requires_volume_audit"

    mirror_records = []
    reflection_flags = {}
    for orbit_index, (orbit, normal) in enumerate(zip(wall_orbits, orbit_normals, strict=True)):
        fixed_normal = inverse_fixed_gram * pairing_matrix[:, orbit_index]
        primitive, scale = _primitive(fixed_normal)
        norm = sp.Rational(orbit_gram[orbit_index, orbit_index])
        reflection_integral = None
        if norm < 0:
            reflection_integral, _ = _reflection_integrality(primitive, fixed_gram)
            reflection_flags[orbit_index] = reflection_integral
        mirror_records.append(
            {
                "orbit_index": orbit_index + 1,
                "source_wall_indices": [index + 1 for index in orbit],
                "ambient_dual_normal": [int(value) for value in normal],
                "fixed_divisor_pairing_column": [
                    _rational_text(sp.Rational(value))
                    for value in pairing_matrix[:, orbit_index]
                ],
                "rational_fixed_mirror_normal_coordinates": [
                    _rational_text(sp.Rational(value)) for value in fixed_normal
                ],
                "primitive_integral_same_mirror_direction_coordinates": [
                    int(value) for value in primitive
                ],
                "presentation_scale_from_primitive_direction": _rational_text(scale),
                "square": _rational_text(norm),
                "reflection_integral_on_saturated_fixed_divisor_lattice": reflection_integral,
                "conic_status": "facet" if orbit_index in conic_facets else "redundant",
                "hyperbolic_status": (
                    "active_facet"
                    if orbit_index in active_facets
                    else "causally_inactive_nonnegative_normal_square"
                    if orbit_index in causal_inactive
                    else "unresolved"
                    if orbit_index in unresolved
                    else "conically_redundant"
                ),
            }
        )
    active_reflection_flags = [reflection_flags[index] for index in active_facets]

    return {
        "schema": CASE_SCHEMA,
        "source": {
            "discriminant": discriminant,
            "primary_sha256": source_hash,
            "inventory_path": str(inventory_path),
            "inventory_sha256": inventory_hash,
        },
        "id": _case_id(chamber_index, class_index),
        "case": {
            "chamber_index": chamber_index,
            "class_index": class_index,
            "published_wall_count": len(walls),
            "archived_AutD_order": chamber_record["archived_AutD"]["order"],
            "oriented_weighted_wall_group_order": chamber_record[
                "oriented_weighted_wall_group"
            ]["order"],
            "weighted_group_strictly_extends_archived_AutD": chamber_record[
                "oriented_weighted_wall_group"
            ]["strictly_extends_archived_AutD"],
            "subgroup_order": class_record["order"],
            "subgroup_conjugacy_class_size": class_record["conjugacy_class_size"],
            "representative_contained_in_archived_AutD": class_record.get(
                "representative_contained_in_archived_AutD"
            ),
            "fixed_rank": fixed_rank,
            "hyperbolic_dimension": fixed_rank - 1,
            "subgroup_wall_permutations": [list(element) for element in sorted(subgroup)],
            "rational_primal_action_denominator_histogram": {
                str(key): value
                for key, value in sorted(Counter(action_denominators).items())
            },
            "all_subgroup_primal_actions_integral": all(
                denominator == 1 for denominator in action_denominators
            ),
            "wall_orientation": orientation,
            "strict_source_interior": source_interior_record,
        },
        "scope": {
            "stock_bounded_to_one_complete_published_induced_chamber": True,
            "surface_automorphism_interpretation_used_as_gate": False,
            "rational_Lorentz_lift_and_integral_divisor_kernel_distinguished": True,
            "divisor_fixed_lattice_and_reflection_mirror_lattice_distinguished": True,
            "finite_volume_gate_performed": False,
        },
        "saturated_fixed_divisor_lattice": {
            "definition": "NS(X) intersect Fix_Q(H)",
            "basis_primal_rows": _matrix_payload(fixed_basis),
            "gram": _matrix_payload(fixed_gram),
            "determinant": fixed["determinant"],
            "determinant_absolute": abs(fixed["determinant"]),
            "inertia": list(exact_inertia(fixed_gram)),
            "smith_diagonal_absolute": fixed["smith_diagonal_absolute"],
            "full_constraint_row_count": fixed["full_constraint_row_count"],
            "independent_constraint_row_indices": fixed[
                "independent_constraint_row_indices"
            ],
            "rational_constraint_rank": fixed["rational_constraint_rank"],
            "rational_constraint_clearing_denominator": fixed[
                "clearing_denominator"
            ],
            "smith_constraint_diagonal": fixed["smith_constraint_diagonal"],
            "averaged_interior_fixed_coordinates": [
                _rational_text(sp.Rational(value)) for value in ample
            ],
            "averaged_interior_square": _rational_text(
                sp.Rational((ample.T * fixed_gram * ample)[0])
            ),
            "minimum_folded_wall_pairing": _rational_text(min(ample_pairings)),
        },
        "restricted_mirror_geometry": {
            "wall_orbit_count": len(wall_orbits),
            "wall_orbit_size_histogram": {
                str(key): value
                for key, value in sorted(Counter(map(len, wall_orbits)).items())
            },
            "orbit_gram_inertia": list(exact_inertia(orbit_gram)),
            "orbit_records": mirror_records,
            "active_reflection_integrality_histogram": {
                str(key).lower(): value
                for key, value in sorted(Counter(active_reflection_flags).items())
            },
            "saturated_fixed_divisor_lattice_is_stable_under_all_active_reflections": bool(
                active_facets
            )
            and all(active_reflection_flags),
        },
        "exact_reduction": {
            "conic_facet_count": len(conic_facets),
            "conic_redundant_count": len(conic_redundant),
            "conic_facet_orbit_indices": [index + 1 for index in conic_facets],
            "conic_redundancy_certificates": redundancy_certificates,
            "causally_inactive_conic_facet_count": len(causal_inactive),
            "causally_inactive_orbit_indices": [index + 1 for index in causal_inactive],
            "unresolved_conic_facet_count": len(unresolved),
            "unresolved_orbit_indices": [index + 1 for index in unresolved],
            "hyperbolic_facet_count": len(active_facets),
            "hyperbolic_facet_orbit_indices": [index + 1 for index in active_facets],
            "strict_timelike_facet_witnesses": witnesses,
        },
        "coxeter_gate": pair_gate
        | {
            "facet_gram": _matrix_payload(facet_gram),
            "positive_wall_gram": _matrix_payload(-facet_gram),
        },
        "decision": {
            "classification": classification,
            "all_hyperbolic_facets_resolved": not unresolved,
            "all_resolved_facet_pairs_coxeter": pair_gate["all_pairs_coxeter"],
            "finite_volume_claimed": False,
        },
        "checks": {
            "oriented_wall_inventory_replayed": True,
            "rational_wall_actions_replayed": True,
            "saturated_divisor_fixed_lattice_replayed": True,
            "all_published_walls_folded": True,
            "ambient_and_fixed_mirror_grams_agree": True,
            "all_conic_redundancies_use_final_facets": True,
            "every_active_facet_has_exact_strict_timelike_witness": True,
            "every_resolved_facet_pair_checked_exactly": True,
        },
    }


def _inventory_cases(inventory: dict[str, Any]) -> list[tuple[dict[str, Any], dict[str, Any]]]:
    cases = []
    for chamber in inventory["chambers"]:
        for record in chamber["oriented_weighted_wall_group"]["classes"]:
            if record["order"] > 1 and record["fixed_rank"] >= MIN_FIXED_RANK:
                cases.append((chamber, record))
    return sorted(
        cases,
        key=lambda pair: (
            -pair[1]["hyperbolic_dimension"],
            pair[0]["wall_count"],
            pair[0]["chamber_index"],
            pair[1]["class_index"],
        ),
    )


def _valid_case(
    path: Path,
    discriminant: int,
    source_hash: str,
    inventory_hash: str,
) -> dict[str, Any] | None:
    if not path.is_file():
        return None
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    if not (
        payload.get("schema") == CASE_SCHEMA
        and payload.get("source", {}).get("discriminant") == discriminant
        and payload.get("source", {}).get("primary_sha256") == source_hash
        and payload.get("source", {}).get("inventory_sha256") == inventory_hash
        and all(payload.get("checks", {}).values())
    ):
        return None
    return payload


