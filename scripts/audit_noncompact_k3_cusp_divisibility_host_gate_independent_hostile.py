def bounded_spanning_repair_certificate(rank: int = 3, bound: int = 3) -> dict[str, Any]:
    if rank != 3:
        raise ValueError("the executable finite-box toy uses rank three")
    matrices: list[sp.Matrix] = []
    nonsingular: list[sp.Matrix] = []
    for x12, x13, x23 in product(range(bound + 1), repeat=3):
        gram = sp.Matrix([[-2, x12, x13], [x12, -2, x23], [x13, x23, -2]])
        matrices.append(gram)
        if gram.det() != 0:
            nonsingular.append(gram)
    assert len(matrices) == (bound + 1) ** len(list(combinations(range(rank), 2)))
    assert nonsingular
