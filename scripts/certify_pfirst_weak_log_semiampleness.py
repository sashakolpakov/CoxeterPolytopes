def _pair_class(gram: list[list[int]], left: Iterable[Any], right: Iterable[Any]) -> Fraction:
    x = [Fraction(value) for value in left]
    y = [Fraction(value) for value in right]
    return sum(Fraction(gram[i][j]) * x[i] * y[j] for i in range(3) for j in range(3))


def verify_f4_calibration(calibration: Mapping[str, Any]) -> bool:
    fan = calibration["blown_up_fan"]
    ray_rows = fan["cyclic_rays"]
    ray_ids = [row["id"] for row in ray_rows]
    rays = {row["id"]: tuple(row["vector"]) for row in ray_rows}
    coefficients = {
        row["id"]: int(row["divisor_coefficient_in_2D"]) for row in ray_rows
    }
    cones = [tuple(cone) for cone in fan["maximal_cones"]]
    if cones != [
        (ray_ids[index], ray_ids[(index + 1) % len(ray_ids)])
        for index in range(len(ray_ids))
    ]:
        raise ArithmeticError("toric affine charts are not the full cyclic fan cover")
    if any(_det(rays[first], rays[second]) != 1 for first, second in cones):
        raise ArithmeticError("the blown-up fan is not smooth and positively oriented")
    base_cone = calibration["base_fan_before_blowup"]["positive_section_fixed_cone"]
    inserted = calibration["star_subdivision"]["inserted_exceptional_ray"]
    if inserted != [base_cone[0][0] + base_cone[1][0], base_cone[0][1] + base_cone[1][1]]:
        raise ArithmeticError("exceptional ray is not the star-subdivision sum")

    self_intersections = {}
    for index, ray_id in enumerate(ray_ids):
        previous = rays[ray_ids[index - 1]]
        following = rays[ray_ids[(index + 1) % len(ray_ids)]]
        self_intersections[ray_id] = -_det(previous, following)
    if self_intersections != {"B": -4, "G": -1, "E": -1, "P": 3, "F": 0}:
        raise ArithmeticError("toric invariant-curve self-intersections changed")

    chart_rows = fan["smooth_complete_affine_cover"]
    if len(chart_rows) != len(cones):
        raise ArithmeticError("toric cover lost an affine cone")
    cartier_data = []
    for chart, cone in zip(chart_rows, cones):
        datum = _solve_cartier(
            rays[cone[0]], rays[cone[1]], -coefficients[cone[0]], -coefficients[cone[1]]
        )
        if list(datum) != chart["cartier_datum"]:
            raise ArithmeticError("archived Cartier datum changed")
        cartier_data.append(datum)

    toric = calibration["toric_divisor_2D"]
    sections = {
        row["section_id"]: tuple(row["character_exponent"])
        for row in toric["returned_global_sections"]
    }
    if set(sections.values()) != set(cartier_data):
        raise ArithmeticError("returned toric sections do not contain every Cartier vertex")
    for exponent in sections.values():
        if any(_dot(exponent, rays[ray_id]) < -coefficients[ray_id] for ray_id in ray_ids):
            raise ArithmeticError("a returned character is not a global section")

    local_rows = toric["local_generation"]
    if len(local_rows) != len(cones):
        raise ArithmeticError("local generation certificate lost a toric chart")
    for row, chart, cone, datum in zip(local_rows, chart_rows, cones, cartier_data):
        if row["chart_id"] != chart["chart_id"]:
            raise ArithmeticError("local generation chart order changed")
        chosen = row["chosen_unit_section_id"]
        if sections[chosen] != datum or row["chosen_local_representative"] != "1":
            raise ArithmeticError("chosen toric section is not the local frame")
        for section_id, exponent in sections.items():
            difference = tuple(exponent[i] - datum[i] for i in range(2))
            if list(difference) != row["regular_local_character_differences"][section_id]:
                raise ArithmeticError("local toric character difference changed")
            if any(_dot(difference, rays[ray_id]) < 0 for ray_id in cone):
                raise ArithmeticError("a local section representative is not regular")
        verify_localized_unit_identity(row["localized_unit_certificate"])

    classes = calibration["class_calculation"]
    gram = classes["intersection_gram"]
    canonical = classes["canonical_class"]
    boundary = classes["boundary_class"]
    expected_D = [-(Fraction(k) + Fraction(b, 2)) for k, b in zip(canonical, boundary)]
    archived_D = [Fraction(value) for value in classes["D"]]
    if expected_D != archived_D:
        raise ArithmeticError("D is not -(K+B/2)")
    m = classes["denominator_m"]
    if [m * value for value in archived_D] != [Fraction(value) for value in classes["mD"]]:
        raise ArithmeticError("mD does not clear D coefficientwise")
    if _pair_class(gram, classes["mD"], classes["mD"]) != classes["mD_square"]:
        raise ArithmeticError("(mD)^2 changed")
    if _pair_class(gram, archived_D, archived_D) != classes["D_square"]:
        raise ArithmeticError("D^2 changed")
    physical = classes["physical_curve_classes"]
    pairings = [
        _pair_class(gram, archived_D, physical[name])
        for name in ("B", "E", "G=F-E")
    ]
    if pairings != [Fraction(value) for value in classes["D_pairings_with_B_E_G"]]:
        raise ArithmeticError("weak-log pairings changed")
    if not calibration["conclusion"]["2D_is_toric_basepoint_free"]:
        raise ArithmeticError("calibration conclusion was disabled")
    return True


def verify_certificate(payload: Mapping[str, Any], *, validate_schema: bool = True) -> bool:
    if validate_schema:
        import jsonschema

        schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
        jsonschema.Draft202012Validator(schema).validate(payload)
    if payload["schema"] != SCHEMA_ID or payload["status"] != "PASS":
        raise ValueError("wrong semiampleness certificate header")
    for source in payload["sources"].values():
        if _sha256_bytes((ROOT / source["path"]).read_bytes()) != source["sha256"]:
            raise ArithmeticError(f"source pin changed: {source['path']}")
    copied = deepcopy(dict(payload))
    archived_digest = copied.pop("content_sha256_without_this_field")
    if archived_digest != _sha256_bytes(_canonical_json(copied)):
        raise ArithmeticError("certificate content digest changed")
    if not payload["theorem"]["no_wall_inequality_used_to_infer_nefness"]:
        raise ArithmeticError("circular proposed-wall nefness was enabled")
    if not payload["theorem"]["converse_for_fixed_sections_and_cover"]:
        raise ArithmeticError("fixed-cover completeness flag changed")
    adapter = payload["pb_atlas_adapter"]
    if (
        not adapter["adapter_contract_specified"]
        or adapter["arbitrary_B1_B2a_adapter_implemented_end_to_end"]
        or not adapter["generic_localized_unit_checker_implemented"]
        or not adapter["F4_toric_cover_and_section_provider_implemented"]
    ):
        raise ArithmeticError("PB-Atlas implementation boundary changed")
    verify_localized_unit_identity(
        payload["checker_control"]["localized_nonconstant_bezout_identity"]
    )
    if not payload["checker_control"]["identity_verified"]:
        raise ArithmeticError("localized unit checker control was disabled")
    verify_f4_calibration(payload["calibration"])
    forbidden_scope = (
        "incidence_nonemptiness_proved",
        "facet_effectivity_or_irreducibility_proved",
        "boundary_disjointness_or_smoothness_proved",
        "reflection_maximality_proved",
        "raw_surface_free_exhaustivity_proved",
    )
    if any(payload["scope"][key] for key in forbidden_scope):
        raise ArithmeticError("certificate crossed its declared geometric scope")
    return True


