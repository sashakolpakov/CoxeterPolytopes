#!/usr/bin/env python3
"""Complete65 cone after two separate endpoint caps joined at pi/4."""
import argparse
import json
from collections import Counter
from fractions import Fraction as F
from hashlib import sha256
from pathlib import Path

import fresh_nonarithmetic_pi8_quad_cone_20261017 as Q
import fresh_nonarithmetic_s6_split_pair_20261017 as B

P,U,I=Q.P,Q.U,Q.I
ROOT=Path(__file__).resolve().parents[1]
TAG='fresh_nonarithmetic_s6_split_pair_20261017_cone'
CAP=B.TAG
PRIOR='fresh_nonarithmetic_escape62_20261017_cone'


def run():
    old,cap=Q.read(PRIOR),Q.read(CAP)
    assert old['status']=='PASS_COMPLETE_63_WALL_CONE_AND_STRICT_ESCAPE'
    assert cap['status']=='PASS_EXACT_65_WALL_SPLIT_ENDPOINT_PI4_BRIDGE'
    z=B.geometry();q,normals=z['exact_gram'],z['normals'];assert len(normals)==65
    assert old['computational_root_basis']==cap['computational_root_basis']==z['basis_ids']
    assert old['computational_gram']==cap['computational_gram']==[P.enc(row)for row in q]
    h=Q.vector(cap['common_center']);assert P.enc(h)==old['computational_common_center']
    cov=[U.imv(q,n)for n in normals];hc=U.imv(q,h)
    assert U.idot(h,hc).h<0 and all(U.idot(h,c).h<0 for c in cov)
    # These are already in this exact root basis. No physical conversion or
    # initial re-solving is used or needed.
    rays=[dict(active=r['active'],mask=sum(1<<j for j in r['active']),kind=r['kind'],
               v=Q.vector(r['normalized_computational_coordinate_bounds']))for r in old['final_rays']]
    assert len(rays)==2988 and Counter(r['kind']for r in rays)==Counter(old['counts'])
    stages=[]
    for wall in [63,64]:
        products=[U.idot(r['v'],cov[wall])for r in rays]
        signs=[Q.sign(x)for x in products]
        negative=[i for i,s in enumerate(signs)if s<0];positive=[i for i,s in enumerate(signs)if s>0]
        assert all(rays[i]['kind']=='hyperideal_rays'for i in positive)
        assert positive
        print('COMPLETE65_PARTITION',len(negative),len(positive),flush=True)
        out={rays[i]['mask']:dict(rays[i])for i in negative};crossings=[];nonedges=[]
        for ni in negative:
            a=rays[ni]
            for pi in positive:
                b=rays[pi];common=a['mask']&b['mask']
                if common.bit_count()<8:continue
                # On the inherited complete pointed cone, the common-zero face
                # is generated by precisely the rays containing this mask.
                # More than two rays therefore certify a nonedge.
                face=[k for k,r in enumerate(rays)if r['mask']&common==common]
                assert ni in face and pi in face
                if len(face)>2:
                    nonedges.append(dict(negative=ni,positive=pi,common_support=Q.ids(common),
                                         face_ray_indices=face))
                    continue
                assert len(face)==2
                minor=Q.rank8([cov[k]for k in Q.ids(common)])
                ga,gb=products[ni],products[pi]
                ca,cb=U.rnd(gb/(gb-ga)),U.rnd(-ga/(gb-ga));assert ca.l>0 and cb.l>0
                v=[U.rnd(ca*x+cb*y)for x,y in zip(a['v'],b['v'])]
                mask=common|(1<<wall)
                v,reconstruction=Q.tighten(v,Q.ids(mask),cov)
                norm=U.idot(v,U.imv(q,v));kind='finite_vertices'if Q.sign(norm)<0 else'hyperideal_rays'
                if kind=='finite_vertices':assert U.idot(v,hc).h<0
                assert mask not in out,('duplicate crossing',Q.ids(mask))
                out[mask]=dict(active=Q.ids(mask),mask=mask,kind=kind,v=v)
                crossings.append(dict(negative_support=a['active'],positive_support=b['active'],
                    new_support=Q.ids(mask),rank8_minor=minor,positive_coefficients=P.enc([ca,cb]),
                    kind=kind,norm=norm.enc(),direct_ray_reconstruction=reconstruction))
                if len(crossings)%100==0:print('COMPLETE65_CROSSINGS',len(crossings),flush=True)
        before_supports=[r['active']for r in rays]
        rays=sorted(out.values(),key=lambda r:r['active'])
        stage=dict(wall=wall,negative=len(negative),positive=len(positive),
                   removed_ray_supports=[before_supports[i]for i in positive],crossings=crossings,
                   nonedge_rejections=nonedges,counts=dict(Counter(r['kind']for r in rays)))
        print('COMPLETE65_CLIP',wall,len(negative),len(positive),len(crossings),len(nonedges),stage['counts'],flush=True)
        stages.append(stage)
    final=[];counts=Counter()
    for number,ray in enumerate(rays,1):
        v=ray['v'];norm,time=U.idot(v,U.imv(q,v)),U.idot(v,hc)
        kind='finite_vertices'if Q.sign(norm)<0 else'hyperideal_rays'
        assert kind==ray['kind']
        if kind=='finite_vertices':assert time.h<0
        for i,c in enumerate(cov):
            value=U.idot(v,c)
            if (ray['mask']>>i)&1:assert value.l<=0<=value.h
            else:assert value.h<0,(ray['active'],i,value.enc())
        final.append(dict(active=ray['active'],kind=kind,norm=norm.enc(),center_product=time.enc(),
                          normalized_computational_coordinate_bounds=P.enc(v)))
        counts[kind]+=1
        if number%500==0:print('COMPLETE65_FINAL_GATES',number,flush=True)
    oldfinite={tuple(r['active'])for r in old['final_rays']if r['kind']=='finite_vertices'}
    newfinite={tuple(r['active'])for r in final if r['kind']=='finite_vertices'}
    assert oldfinite<=newfinite and len(oldfinite)==193 and len(newfinite)==196
    supplied={tuple(sorted(v['incident']))for v in cap['new_finite_vertices']}
    assert newfinite-oldfinite==supplied
    faces=[]
    for row in old['faces']+[dict(name='side30_patch',support=B.S+[30]),dict(name='new_A_S6_face',support=B.S+[63]),dict(name='new_B_S6_face',support=B.S+[64])]:
        support=row['support'];rr=[r for r in final if set(support)<=set(r['active'])]
        faces.append(dict(name=row['name'],support=support,counts=dict(Counter(r['kind']for r in rr)),
                          ray_supports=[r['active']for r in rr]))
    for name,count in [('compact_H4_I2_8_tetrahedron',4),('r8_quadrilateral',4),('new_H4_I2_9_prism',6)]:
        assert next(r for r in faces if r['name']==name)['counts']=={'finite_vertices':count}
    point=Q.vector(old['strict_escape']['computational_point'])
    norm,future=U.idot(point,U.imv(q,point)),U.idot(point,hc)
    products=[U.idot(point,c)for c in cov]
    assert norm.l>0 and future.h<0 and all(p.h<0 for p in products)
    escape=dict(ray_support=old['strict_escape']['ray_support'],
        computational_point=P.enc(point),physical_point=P.enc(P.combine(point,z['basis'])),
        norm=norm.enc(),future=future.enc(),all65_products=P.enc(products),
        provenance='The frozen63 strict escape, retained by both new caps.')
    paths=[f'scripts/{TAG}.py',f'scripts/{CAP}.py',f'results/{CAP}.json',
           f'scripts/{PRIOR}.py',f'results/{PRIOR}.json',f'scripts/{Q.TAG}.py']
    return dict(status='PASS_COMPLETE_65_WALL_CONE_AND_STRICT_ESCAPE',
        sources={p:sha256((ROOT/p).read_bytes()).hexdigest()for p in paths},
        initial_counts=old['counts'],counts=dict(counts),clipping_stages=stages,
        coordinate_system='Inherited computational root basis; identical basis ids and interval Gram checked before clipping.',
        computational_root_basis=z['basis_ids'],computational_gram=[P.enc(row)for row in q],computational_common_center=P.enc(h),
        final_rays=final,new_finite_supports=[list(s)for s in sorted(newfinite-oldfinite)],final_inequality_checks=65*len(final),faces=faces,
        strict_escape=escape,
        proof='Start from the frozen complete63 cone in the identical computational root basis. At each cut, strict signs partition every ray. An opposite-sign pair is adjacent exactly when its common-zero face contains only those two inherited extreme rays; all accepted pairs also have an explicit rank8 minor. Positive combinations give every new ray. Nine active equations reconstruct each new projective ray after positive normalization. All65 final inequalities and causal signs are checked. All193 finite rays persist, and exactly the three independently supplied new finite supports occur. Entire retained compact faces are checked from their complete active-ray sets.',
        scope='Complete primary65-wall cone, inheriting63 completeness and frozen arithmetic helpers. Not an independent arithmetic review. The preceding strict escape survives and proves infinite volume; boundary changes must be evaluated separately.')



if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--verify',action='store_true');a=ap.parse_args()
    data=json.loads(json.dumps(run()));path=ROOT/f'results/{TAG}.json'
    if a.verify:assert data==json.loads(path.read_text());print('PASS saved complete65 cone replay')
    else:path.write_text(json.dumps(data,indent=2)+'\n')
    print(data['status'],data['counts'],flush=True)
