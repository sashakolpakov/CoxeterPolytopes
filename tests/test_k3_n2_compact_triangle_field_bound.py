"""Regression tests for the finite-area K3 Coxeter-triangle field theorem."""

from __future__ import annotations

from itertools import combinations
import json
from pathlib import Path

from scripts.certify_k3_n2_compact_triangle_field_bound import (
    build_certificate,
    digest,
    encoded_certificate,
    triangle_field_record,
)


ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "results/k3_n2_compact_triangle_field_bound.md"
CERTIFIER = ROOT / "scripts/certify_k3_n2_compact_triangle_field_bound.py"
ARCHIVE = ROOT / "data/enumerations/k3_n2_compact_triangle_field_bound.json"


def test_all_simple_cycle_height_constants_recompute():
    record = triangle_field_record()
    assert record["field_degree_upper_bound"] == 6
    assert record["pair_cycle_conjugate_weak_upper_bound"] == 4
    assert record["length_three_cycle_absolute_conjugate_weak_upper_bound"] == 8
    assert record["simple_cyclic_packet_conjugate_bound"] == 8
    assert record["selected_generator_count_upper_bound"] == 2
    assert record["bad_primitive_combination_coefficient_count_upper_bound"] == 15
    assert record["primitive_element_conjugate_bound"] == 128
    assert record["Vandermonde_difference_bound"] == 256
    assert record["field_discriminant_bound"] == "256^30"


def test_primitive_grid_has_one_more_value_than_embedding_pairs():
    assert len(tuple(combinations(range(6), 2))) == 15
    assert len(range(16)) == 16


def test_archive_replays_and_scope_is_exact():
    envelope = json.loads(ARCHIVE.read_text(encoding="utf-8"))
    payload = build_certificate()
    assert envelope["payload"] == payload
    assert envelope["payload_sha256"] == digest(payload)
    assert ARCHIVE.read_text(encoding="utf-8") == encoded_certificate()
    conclusions = payload["conclusions"]
    assert conclusions["K3_full_trace_field_degree_at_most_6"] is True
    assert conclusions["all_pair_cycles_bounded_at_every_embedding"] is True
    assert conclusions["length_three_cycle_bounded_at_every_embedding"] is True
    assert conclusions["bounded_mixed_height_premise_required"] is False
    assert conclusions["angle_classification_required"] is False
    assert conclusions["Gram_determinant_closure_required"] is False
    scope = payload["scope"]
    assert scope["returned_field_is_cyclic_Cartan_ground_field_required"] is True
    assert scope["exact_same_finite_area_Coxeter_triangle_eigen_nef_chamber_required"] is True
    assert scope["complete_saturated_reflection_packet_retained"] is True
    assert scope["reflection_maximality_in_declared_order_host_retained"] is True
    assert scope["reflection_maximality_used_in_bound"] is False
    assert scope["compact_triangle_closed"] is True
    assert scope["ideal_vertex_triangle_closed"] is True
    assert scope["truncated_ultraideal_polyhedron_closed"] is False
    assert scope["arbitrary_n2_polygon_closed"] is False


def test_report_states_hypotheses_proof_and_nonclaims():
    text = " ".join(REPORT.read_text(encoding="utf-8").split())
    for phrase in (
        "proved for every full-trace complex-K3 field degree",
        "minimal complex projective K3 surface",
        "primitive full trace",
        "exactly a finite-area Coxeter triangle",
        "complete and saturated",
        "reflection-maximal",
        "ground field generated by the cyclic Cartan products",
        r"0\le\sigma(p_{ij})\le4",
        r"|\sigma(c_3)|\le8",
        "Every closed directed walk decomposes into simple directed cycles",
        r"|\operatorname {Disc}(k)|\le256^{30}",
        "Theorem 3.1 (finite-area-triangle field theorem)",
        "finite field set rather than merely bounded degree",
        "does not establish the incidence-independent automatic-height implication",
    ):
        assert phrase in text


def test_no_classification_or_hidden_height_is_imported():
    combined = " ".join(
        (REPORT.read_text(encoding="utf-8") + CERTIFIER.read_text(encoding="utf-8")).split()
    )
    assert "No angle list, reflective-lattice classification, imposed height" in combined
    assert '"uses_reflective_lattice_classification": true' not in combined
