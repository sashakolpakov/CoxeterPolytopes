CERTIFICATE = json.loads(OUTPUT.read_text(encoding="utf-8"))


def test_full_group_enrichment_certificate_replays_offline() -> None:
    assert build_certificate() == CERTIFICATE
    assert CERTIFICATE["all_checks_pass"] is True
    assert CERTIFICATE["summary"] == {
        "compact": 0,
        "cyclic_subgroup_realizations": 4,
        "finite_volume_noncompact": 4,
        "full_effective_group_rows": 3,
        "new_abstract_diagram_claims": 0,
    }


def test_full_groups_picard_images_and_kernels_are_pinned() -> None:
    assert {
        identifier: (
            row["group"],
            row["ns_image"],
            row["ns_image_order"],
            row["ns_kernel"],
        )
        for identifier, row in FULL_ROWS.items()
    } == {
        "1.4.3.1": ("C4 x C2", "C2 x C2", 4, "<g^2> = C2"),
        "1.8.1.1": ("C8 x C2", "C2 x C2", 4, "<g^2> = C4"),
        "1.16.0.1": ("C16 x C2", "C4 x C2", 8, "<g^4> = C4"),
    }
    for realization in CERTIFICATE["realizations"]:
        group = realization["full_effective_character"]
        assert group["symplectic_kernel_Hs"] == "C2 generated by s"
        assert group["effective_group_row"]
        assert group["common_invariant_kahler_class_exists"]


