def test_direct_coinvariant_intertwiners_are_integral() -> None:
    p14 = json.loads(
        (
            OUTPUT.parents[0]
            / "roulleau_r14_ue8a1x4_all_subgroup_folds.json"
        ).read_text(encoding="utf-8")
    )
    ud8d4 = json.loads(
        (OUTPUT.parents[0] / "roulleau_ud8d4_all_subgroup_folds.json").read_text(
            encoding="utf-8"
        )
    )
    for specification in ENRICHMENTS:
        archive = _archive_pair(specification, p14, ud8d4)
        source_gram = archive["coinvariant_gram"]
        source_action = archive["coinvariant_action"]
        target_gram = sp.Matrix(specification["coinvariant_gram"])
        target_action = sp.Matrix(specification["coinvariant_action"])
        intertwiner = sp.Matrix(specification["coin_intertwiner"])
        assert abs(intertwiner.det()) == 1
        assert intertwiner * source_gram * intertwiner.T == target_gram
        assert intertwiner * source_action == target_action * intertwiner
        assert all(sp.Rational(value).q == 1 for value in target_gram / 2)
        assert all((target_gram / 2)[i, i] % 2 == 0 for i in range(target_gram.rows))


def test_vinberg_handoffs_are_actual_finite_volume_polytopes() -> None:
    assert [
        (
            row["archived_polytope"]["id"],
            row["archived_polytope"]["dimension"],
            row["archived_polytope"]["facets"],
            row["archived_polytope"]["finite_vertices"],
            row["archived_polytope"]["cusps"],
            row["archived_polytope"]["elliptic_edges"],
        )
        for row in CERTIFICATE["realizations"]
    ] == [
        ("R14-UE8A1x4-C2D-H11-19", 11, 19, 114, 13, 795),
        ("R14-D8D4-T2-H11-16", 11, 16, 112, 9, 750),
        ("R14-D8D4-T2-H11-16", 11, 16, 112, 9, 750),
        ("R14-D8D4-T4-H10-14", 10, 14, 44, 3, 254),
    ]
    for row in CERTIFICATE["realizations"]:
        polytope = row["archived_polytope"]
        assert polytope["classification"] == "finite_volume_noncompact"
        assert polytope["bad_edges"] == 0
        assert polytope["bad_parabolic_neighborhoods"] == 0
        assert row["geometric_handoff"][
            "database_effectivity_supplies_actual_K3_automorphisms"
        ]


