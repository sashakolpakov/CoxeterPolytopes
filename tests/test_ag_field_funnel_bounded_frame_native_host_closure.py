"""Regression checks for the bounded-frame native-host closure theorem."""

from __future__ import annotations

from fractions import Fraction

from scripts.certify_ag_field_funnel_bounded_frame_native_host_closure import (
    REPORT,
    build_certificate,
    diagonal_rescale,
    directed_cycle_product,
    matrix_unit_hull_diagonal,
    recover_tree_scales,
    sha256_file,
    trace_cycle_product,
)


CERTIFIER_SHA256 = "44848ad5727458b1777a4989395229d847ad0e05136ae5c96d2ffd9ad12a6def"
REPORT_SHA256 = "7ba392dd833358379ea92d1385909a52b2dc65417a9cb4ccb856170118df02a3"


def sample_cartan():
    return (
        (Fraction(2), Fraction(-1), Fraction(-2), Fraction(0)),
        (Fraction(-3), Fraction(2), Fraction(-4), Fraction(-1)),
        (Fraction(-5), Fraction(-6), Fraction(2), Fraction(-2)),
        (Fraction(0), Fraction(-7), Fraction(-8), Fraction(2)),
    )


def test_frozen_owner_artifacts():
    certifier = (
        REPORT.parents[1]
        / "scripts/certify_ag_field_funnel_bounded_frame_native_host_closure.py"
    )
    assert sha256_file(REPORT) == REPORT_SHA256
    assert sha256_file(certifier) == CERTIFIER_SHA256


def test_projective_trace_orientation_includes_two_cycles():
    cartan = sample_cartan()
    cycles = ((0, 1), (1, 2), (2, 3), (0, 1, 2), (1, 2, 3))
    for cycle in cycles:
        assert trace_cycle_product(cartan, cycle) == directed_cycle_product(
            cartan, cycle
        )
    assert directed_cycle_product(cartan, (0, 1)) == 3
    assert directed_cycle_product(cartan, (0, 1, 2)) == -20


def test_cycle_packet_is_diagonal_invariant_and_recovers_tree_scales():
    cartan = sample_cartan()
    scales = (Fraction(2), Fraction(3), Fraction(5), Fraction(7))
    changed = diagonal_rescale(cartan, scales)
    cycles = ((0, 1), (1, 2), (2, 3), (0, 1, 2), (1, 2, 3))
    assert all(
        directed_cycle_product(cartan, cycle)
        == directed_cycle_product(changed, cycle)
        for cycle in cycles
    )
    recovered = recover_tree_scales(cartan, changed, ((0, 1), (1, 2), (2, 3)))
    assert recovered == (
        Fraction(1),
        Fraction(3, 2),
        Fraction(5, 2),
        Fraction(7, 2),
    )
    assert diagonal_rescale(cartan, recovered) == changed


def test_matrix_units_force_one_scalar_ideal():
    # M_3(Z) acting on the diagonal lattice generated by 6e1,10e2,14e3
    # transfers every coordinate generator to every coordinate, producing
    # gcd(6,10,14) Z^3.
    assert matrix_unit_hull_diagonal((6, 10, 14), 3) == 2


