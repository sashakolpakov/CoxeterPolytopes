from coxeter_polytopes.exact.silver import Silver
from coxeter_polytopes.search.silver_s26 import RHO


DIRECTION_NORM = 3
PELL_A = Silver(16, 12)
PELL_U = Silver(7, 5)
WITNESS_SCALE = Fraction(43, 55)

CRITERION = PellBoostCriterion(
    coefficient=RHO,
    direction_norm=DIRECTION_NORM,
    pell_A=PELL_A,
    pell_U=PELL_U,
    witness_scale=WITNESS_SCALE,
)

TIME_FROM_DIRECTION = CRITERION.time_from_direction
SPATIAL_FROM_TIME = CRITERION.spatial_from_time
DIRECTION_FROM_DIRECTION = CRITERION.direction_from_direction
SEPARATOR_SLOPE = CRITERION.separator_direction_slope
CONTROL_SQUARE_BOUND = CRITERION.control_square_bound
SEPARATOR_HEIGHT_BOUND = CRITERION.separator_height_bound
WITNESS_SEPARATOR_COEFFICIENT = CRITERION.witness_separator_coefficient

