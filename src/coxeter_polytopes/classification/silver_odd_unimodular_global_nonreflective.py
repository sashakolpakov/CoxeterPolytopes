def boost_audit() -> bool:
    """Audit the exact boost and separator constants."""

    return (
        CRITERION.audit()
        and TIME_FROM_DIRECTION == Silver(7, 5)
        and SPATIAL_FROM_TIME == Silver(13, 9)
        and DIRECTION_FROM_DIRECTION == Silver(5, 4)
        and SEPARATOR_SLOPE == Silver(8, -4)
        and CONTROL_SQUARE_BOUND == Silver(297, 210)
        and SEPARATOR_HEIGHT_BOUND == Silver(543, 384)
        and WITNESS_SEPARATOR_COEFFICIENT == Silver(399, -282) / 55
    )


def boost_plane_matrix() -> tuple[tuple[Silver, Silver], tuple[Silver, Silver]]:
    """Matrix on coordinates ``(x,c)`` where ``y=c*d``."""

    return (
        (PELL_A, DIRECTION_NORM * TIME_FROM_DIRECTION),
        (SPATIAL_FROM_TIME, PELL_A),
    )


def apply_boost_to_plane(x: Silver, c: Silver) -> tuple[Silver, Silver]:
    matrix = boost_plane_matrix()
    return (
        matrix[0][0] * x + matrix[0][1] * c,
        matrix[1][0] * x + matrix[1][1] * c,
    )


def inverse_boost_on_plane(x: Silver, c: Silver) -> tuple[Silver, Silver]:
    matrix = boost_plane_matrix()
    return (
        matrix[1][1] * x - matrix[0][1] * c,
        -matrix[1][0] * x + matrix[0][0] * c,
    )


def plane_isometry_audit() -> bool:
    """Audit determinant one, inverse, and preservation of diag(-rho,3)."""

    basis = ((Silver(1), Silver(0)), (Silver(0), Silver(1)))

    def pair(left: tuple[Silver, Silver], right: tuple[Silver, Silver]) -> Silver:
        return -RHO * left[0] * right[0] + DIRECTION_NORM * left[1] * right[1]

    images = tuple(apply_boost_to_plane(*vector) for vector in basis)
    return (
        boost_audit()
        and PELL_A**2
        - DIRECTION_NORM * TIME_FROM_DIRECTION * SPATIAL_FROM_TIME
        == Silver(1)
        and all(inverse_boost_on_plane(*images[i]) == basis[i] for i in range(2))
        and all(
            pair(images[i], images[j]) == pair(basis[i], basis[j])
            for i in range(2)
            for j in range(2)
        )
    )


