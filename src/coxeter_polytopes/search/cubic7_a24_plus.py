"""Glue-aware first shell for the Niemeier lattice with root system A24.

Use the standard realization in ``Q^25`` with coordinate sum zero.  The root
lattice is ``A24={z in Z^25: sum z_i=0}``; its unique even unimodular
overlattice is generated by the glue vector

``g=(1/5,...,1/5,-24/5)``.

Equivalently, a vector belongs to the overlattice iff all 25 coordinates have
one common residue ``lambda/5`` modulo ``O_K`` and their sum is zero.  The
code below exhausts all four nonzero coefficient-residue directions in
``O_K/5O_K`` only after iterating every nonzero field coefficient triple;
it never pads a nonzero glue class with literal zeros.

The positive lattice is even unimodular, so for timelike coefficient
``2*theta`` the complete primitive mirror-norm ideals are ``(1),(2)`` by the
same local argument as D24+: away from inert two the pairing ideal is a unit,
and at two a primitive control coordinate gives valuation exactly one.
"""

from __future__ import annotations

from dataclasses import dataclass
from fractions import Fraction
from functools import lru_cache
from itertools import product
from typing import Iterable

from coxeter_polytopes.exact.cubic7 import CUBIC7_ZERO, THETA7, Cubic7
from coxeter_polytopes.search.bugaenko_vinberg import _fraction_inverse
from coxeter_polytopes.search.cubic7_dn import (
    FIRST_CONTROL,
    FIRST_HEIGHT,
    TIMELIKE,
    _fixed_alphabet_square_partitions,
)
from coxeter_polytopes.search.cubic7_root_blocks import _bounded_for_caps


Vector = tuple[Cubic7, ...]


def a24_niemeier_membership(coordinates: Vector) -> str | None:
    if len(coordinates) != 25 or sum(coordinates, start=CUBIC7_ZERO):
        return None
    residues = []
    for value in coordinates:
        scaled = 5 * value
        if not scaled.is_integral:
            return None
        residues.append(tuple(int(coefficient) % 5 for coefficient in (scaled.a, scaled.b, scaled.c)))
    if len(set(residues)) != 1:
        return None
    return "A24" if residues[0] == (0, 0, 0) else "glue"


def a24_niemeier_basis_euclidean() -> tuple[tuple[Fraction, ...], ...]:
    roots = []
    for index in range(24):
        vector = [Fraction(0)] * 25
        vector[index] = 1
        vector[index + 1] = -1
        roots.append(tuple(vector))
    glue = (Fraction(1, 5),) * 24 + (Fraction(-24, 5),)
    return (*roots[1:], glue)


def _dot(left: Iterable[Fraction], right: Iterable[Fraction]) -> Fraction:
    return sum((x * y for x, y in zip(left, right)), start=Fraction(0))


@lru_cache(maxsize=1)
def a24_niemeier_gram() -> tuple[tuple[Fraction, ...], ...]:
    basis = a24_niemeier_basis_euclidean()
    return tuple(tuple(_dot(left, right) for right in basis) for left in basis)


def _determinant(matrix: tuple[tuple[Fraction, ...], ...]) -> Fraction:
    work = [list(row) for row in matrix]
    result = Fraction(1)
    for column in range(len(work)):
        pivot = next(row for row in range(column, len(work)) if work[row][column])
        if pivot != column:
            work[column], work[pivot] = work[pivot], work[column]
            result *= -1
        value = work[column][column]
        result *= value
        for row in range(column + 1, len(work)):
            factor = work[row][column] / value
            for index in range(column + 1, len(work)):
                work[row][index] -= factor * work[column][index]
    return result


def a24_basis_audit() -> bool:
    gram = a24_niemeier_gram()
    return (
        _determinant(gram) == 1
        and all(value.denominator == 1 for row in gram for value in row)
        and all(gram[index][index].numerator % 2 == 0 for index in range(24))
    )


@dataclass(frozen=True, slots=True)
class A24Pattern:
    coset: str
    coordinates: Vector


@lru_cache(maxsize=1)
def first_a24_patterns() -> tuple[A24Pattern, ...]:
    target = 2 + TIMELIKE * FIRST_CONTROL**2
    doubled = _bounded_for_caps((25 * target, 25 * target, 25 * target))
    residue_buckets: dict[tuple[int, int, int], list[Cubic7]] = {}
    for value in doubled:
        residue = tuple(int(coefficient) % 5 for coefficient in (value.a, value.b, value.c))
        coordinate = value / 5
        if all((target - coordinate * coordinate).sign(place) >= 0 for place in range(3)):
            residue_buckets.setdefault(residue, []).append(coordinate)
    output: list[A24Pattern] = []
    for residue in product(range(5), repeat=3):
        values = tuple(residue_buckets.get(residue, ()))
        if not values:
            continue
        for coordinates in _fixed_alphabet_square_partitions(values, 25, target):
            coset = a24_niemeier_membership(coordinates)
            if coset is not None:
                output.append(A24Pattern(coset, coordinates))
    return tuple(sorted(set(output), key=lambda pattern: (pattern.coset, pattern.coordinates)))


