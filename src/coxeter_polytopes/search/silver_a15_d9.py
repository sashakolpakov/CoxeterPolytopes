Vector: TypeAlias = tuple[Silver, ...]
RationalMatrix: TypeAlias = tuple[tuple[Fraction, ...], ...]
IntegerPair: TypeAlias = tuple[int, int]

EPSILON = SILVER_ONE + SQRT2
UNIT_NORM_CLASSES = (SILVER_ONE, Silver(2))
A15_COMPONENT = ("A", 15)
D9_COMPONENT = ("D", 9)
A15_RESIDUE_MODULUS = 16
D9_RESIDUE_MODULUS = 4
FIRST_PACKET_HEIGHT = Silver(2, 2)
SECOND_PACKET_HEIGHT = Silver(7, 5)

COMPLETE_UNIT_NORM_PROOF = (
    "Put pi=sqrt(2) and epsilon=1+pi. The coefficient epsilon is a unit "
    "and N(A15 D9) is even unimodular. For primitive r=(x,y), reflection "
    "integrality says q(r) divides 2I(r), I(r)=(epsilon*x,(y,N)). Away "
    "from (pi), local unimodularity and primitivity make I(r) the unit "
    "ideal. At (pi), a unit control gives v_pi(q)=0; otherwise a primitive "
    "spatial coordinate makes I(r) a unit, while evenness and q|2I force "
    "v_pi(q)=2. Every totally-positive unit of Z[sqrt(2)] is a square, so "
    "the complete canonical positive norms are 1 and 2."
)


@lru_cache(maxsize=1)
def a15_d9_niemeier_gram() -> RationalMatrix:
    """Gram matrix in the basis ``A15[1:14], D9[1:9], g``.

    More explicitly, the basis contains the first fourteen A15 simple roots,
    all nine D9 simple roots, and ``g=omega_2+omega_9``.  The omitted A15
    simple root has coefficient ``1/8`` in ``g``, so the basis has index eight
    over the root lattice.
    """

    a15 = cartan_gram(A15_COMPONENT)
    d9 = cartan_gram(D9_COMPONENT)
    gram = [[Fraction(0) for _ in range(24)] for _ in range(24)]
    for i in range(14):
        for j in range(14):
            gram[i][j] = a15[i][j]
    for i in range(9):
        for j in range(9):
            gram[14 + i][14 + j] = d9[i][j]
    gram[1][23] = gram[23][1] = Fraction(1)
    gram[14 + 8][23] = gram[23][14 + 8] = Fraction(1)
    gram[23][23] = Fraction(4)
    return tuple(tuple(row) for row in gram)


def a15_d9_basis_audit() -> bool:
    gram = a15_d9_niemeier_gram()
    return (
        _determinant(gram) == 1
        and all(value.denominator == 1 for row in gram for value in row)
        and all(gram[index][index].numerator % 2 == 0 for index in range(24))
    )


@lru_cache(maxsize=1)
def glue_coset_minima() -> tuple[Fraction, ...]:
    """Minimum squared norms of the seven nonzero glue cosets.

    The minimum in A15 discriminant class ``k`` is ``k(16-k)/16``.
    The four D9 classes ``0,1,2,3`` have minima ``0,9/4,1,9/4``.
    Combining the classes ``(2*j,j)`` gives an exact root-exclusion audit.
    """

    d9_minima = (Fraction(0), Fraction(9, 4), Fraction(1), Fraction(9, 4))
    return tuple(
        Fraction((2 * multiple % 16) * (16 - (2 * multiple % 16)), 16)
        + d9_minima[multiple % 4]
        for multiple in range(1, 8)
    )


def a15_residue(weights: Sequence[Silver]) -> tuple[int, int]:
    if len(weights) != 15 or not all(value.is_integral for value in weights):
        raise ValueError("A15 Dynkin weights must be fifteen silver integers")
    return tuple(
        sum(
            (index + 1) * int(getattr(value, coefficient))
            for index, value in enumerate(weights)
        )
        % 16
        for coefficient in ("a", "b")
    )


D9_RESIDUE_FUNCTIONAL = (2, 0, 2, 0, 2, 0, 2, 3, 1)


def d9_residue(weights: Sequence[Silver]) -> tuple[int, int]:
    if len(weights) != 9 or not all(value.is_integral for value in weights):
        raise ValueError("D9 Dynkin weights must be nine silver integers")
    return tuple(
        sum(
            functional * int(getattr(value, coefficient))
            for functional, value in zip(D9_RESIDUE_FUNCTIONAL, weights)
        )
        % 4
        for coefficient in ("a", "b")
    )


def a15_d9_glue_membership(
    a15_weights: Sequence[Silver], d9_weights: Sequence[Silver]
) -> bool:
    """Test the cyclic glue ``<(2,1)>`` in both silver coefficients."""

    try:
        a_residue = a15_residue(a15_weights)
        d_residue = d9_residue(d9_weights)
    except ValueError:
        return False
    return all(
        a_residue[index] % 2 == 0
        and d_residue[index] == (a_residue[index] // 2) % 4
        for index in (0, 1)
    )


