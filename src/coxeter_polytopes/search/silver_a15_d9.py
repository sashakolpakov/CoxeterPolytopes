"""Exact silver Vinberg packets for the Niemeier lattice ``N(A15 D9)``.

Let ``R=A15+D9``.  In the Dynkin numbering used by
:mod:`niemeier_host_triage`, the even unimodular extension is generated by

``g = omega_2(A15) + omega_9(D9)``.

Its class is ``(2,1)`` in ``Z/16 + Z/4``, has order eight, and has square
``7/4+9/4=4``.  Thus a Dynkin-weight pair belongs to the Niemeier lattice
exactly when

``rho_A`` is even and ``rho_D = rho_A/2 (mod 4)``.

The condition is imposed separately on both coefficients of ``Z[sqrt(2)]``.
The Lorentzian seed is ``<-(1+sqrt(2))> + N(A15 D9)``.  Since the spatial
lattice is even unimodular and the coefficient is a unit, the complete
canonical primitive mirror norms are ``1`` and ``2``.
"""

