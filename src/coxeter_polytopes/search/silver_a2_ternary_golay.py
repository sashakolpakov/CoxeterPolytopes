"""Exact first Vinberg packet for the Niemeier lattice ``N(A2^12)``.

The spatial lattice is obtained from ``A2^12`` by the extended ternary
Golay code.  We use the cyclic length-eleven ternary Golay code generated by

``2 + x^2 + 2*x^3 + x^4 + x^5``

and append the negative coordinate sum.  The resulting length-twelve code is
self-dual, has dimension six, and has weight enumerator
``1 + 264*y^6 + 440*y^9 + 24*y^12``.  These properties are checked by the
module rather than assumed.

Two silver coefficients are screened:

``<-sqrt(2)> + N(A2^12)`` and ``<-2*sqrt(2)> + N(A2^12)``.

The positive block is even unimodular, so their complete primitive mirror
norm lists are the same local lists already proved for ``E8^3``.  The exact
control census through height ten is reused, but the spatial enumeration is
independent and glue-aware.

At the first nonempty height, the only dominant roots are the twelve affine
``A2`` highest-root caps.  Any other block decomposition uses a nonzero glue
word of support at most three, contradicting the ternary Golay minimum six.
The section is therefore the Cartesian product of twelve triangles.  Its
``3^12`` vertices are classified exactly by Lorentz norm.

The search is then continued through real height seventeen.  A contingency
table for ordered pairs of ternary Golay words reduces the ``3^12`` glue
conditions to 288 exact types.  The next nonempty packet, at
``8+6*sqrt(2)``, has 3,960 dominant norm-two walls for either timelike
coefficient.  Their maximum pairing with the uniform Dynkin-weight direction
is ``9+9*sqrt(2)``.  Scaling that direction to ``sqrt(2)/5`` (respectively
``2/5``) in every coordinate gives a strict hyperideal witness after the
second packet.  Thus the deeper prefix is still not finite-volume.

The later norm-two target ``10+6*sqrt(2)`` has a short intrinsic rejection.
Writing ``y=u+sqrt(2)*v`` in the Niemeier lattice gives
``u^2+2v^2=10`` and ``u.v=3``.  Minimum two forces ``v^2=2``, ``u^2=6`` and
``(u-v)^2=2``.  Hence both ``v`` and ``u-v`` are roots in a single ``A2``
component.  Its dominant representative has Dynkin weights
``(sqrt(2),3+sqrt(2))`` (up to reversal), whose sum exceeds the earlier
affine cap.  Thus every such vector is rejected by the first packet.
"""

