def _a2_weight_inner_product(
    left: tuple[Silver, Silver], option: A2BlockOption
) -> Silver:
    first, second = left
    return (
        2 * first * option.weight_left
        + first * option.weight_right
        + second * option.weight_left
        + 2 * second * option.weight_right
    ) / 3


@lru_cache(maxsize=1)
def _base_h24_cutter_second_packet_maximum() -> tuple[int, Silver]:
    """Exact pointed-contingency replay against all 3,960 H8 walls."""

    seed = SQRT2_A2_GOLAY_SEED
    second = next(
        level
        for level in control_levels(seed, 17)
        if level.height == Silver(8, 6)
    )
    grouped = _packet_block_options(seed, second)
    cutter_blocks = (
        (Silver(2, 2), Silver(2, 2)),
        (Silver(1), Silver(4, 3)),
    )
    target_key = (second.target.a, second.target.b)
    total = 0
    maximum: Silver | None = None
    for pointed, contingency, multiplicity in (
        ternary_golay_two_pointed_pair_contingencies()
    ):
        states: dict[tuple[Fraction, Fraction], tuple[int, Silver]] = {
            (Fraction(0), Fraction(0)): (1, SILVER_ZERO)
        }
        for position, residue in enumerate(pointed):
            next_states: dict[
                tuple[Fraction, Fraction], tuple[int, Silver]
            ] = {}
            for (left, right), (count, objective) in states.items():
                for option in grouped[residue]:
                    new_left = left + option.square.a
                    new_right = right + option.square.b
                    remainder = second.target - Silver(new_left, new_right)
                    if any(remainder.sign(place) < 0 for place in (0, 1)):
                        continue
                    key = (new_left, new_right)
                    new_objective = objective + _a2_weight_inner_product(
                        cutter_blocks[position], option
                    )
                    old = next_states.get(key)
                    if old is None:
                        next_states[key] = (count, new_objective)
                    else:
                        next_states[key] = (
                            old[0] + count,
                            new_objective
                            if (new_objective - old[1]).sign(0) > 0
                            else old[1],
                        )
            states = next_states
        for residue, coordinate_count in enumerate(contingency):
            for _ in range(coordinate_count):
                next_states = {}
                for (left, right), (count, objective) in states.items():
                    for option in grouped[residue]:
                        new_left = left + option.square.a
                        new_right = right + option.square.b
                        remainder = second.target - Silver(new_left, new_right)
                        if any(remainder.sign(place) < 0 for place in (0, 1)):
                            continue
                        key = (new_left, new_right)
                        old = next_states.get(key)
                        if old is None:
                            next_states[key] = (count, objective)
                        else:
                            next_states[key] = (
                                old[0] + count,
                                objective
                                if (objective - old[1]).sign(0) > 0
                                else old[1],
                            )
                states = next_states
                if not states:
                    break
            if not states:
                break
        hit = states.get(target_key)
        if hit is None:
            continue
        count, objective = hit
        total += multiplicity * count
        if maximum is None or (objective - maximum).sign(0) > 0:
            maximum = objective
    if total != 3960 or maximum != Silver(27, 20):
        raise AssertionError(
            f"the pointed H8 packet replay changed: total={total}, maximum={maximum}"
        )
    return total, maximum


def h24_cutter_second_packet_max_pairing(seed: SilverA2GolaySeed) -> Silver:
    """Maximum exact pairing of the displayed H24 cutter with the H8 packet."""

    if seed not in SUPPORTED_A2_GOLAY_SEEDS:
        raise ValueError("unsupported A2^12 seed")
    _, spatial_maximum = _base_h24_cutter_second_packet_maximum()
    h24 = next(
        level
        for level in control_levels(seed, 100)
        if level.height == Silver(24, 17)
    )
    h8 = next(
        level
        for level in control_levels(seed, 17)
        if level.height == Silver(8, 6)
    )
    pairing = (
        spatial_maximum
        - seed.timelike_coefficient * h24.control * h8.control
    )
    if pairing != -1:
        raise AssertionError("the H24 cutter ceased to be strict against H8")
    return pairing


def first_h24_cutter(seed: SilverA2GolaySeed) -> ExplicitA2GolayCutter:
    """An explicit accepted wall in either host at H=24+17sqrt2.

    The chronological maximum against all 3,960 earlier walls was first
    obtained by an independent full packet replay.  Its value ``-1`` is
    archived here and must be independently regenerated by the hostile audit;
    this function checks all intrinsic arithmetic and the earlier affine caps.
    """

    if seed not in SUPPORTED_A2_GOLAY_SEEDS:
        raise ValueError("unsupported A2^12 seed")
    level = next(
        level
        for level in control_levels(seed, 100)
        if level.height == Silver(24, 17)
    )
    blocks = (
        (Silver(2, 2), Silver(2, 2)),
        (Silver(1), Silver(4, 3)),
    ) + ((SILVER_ZERO, SILVER_ZERO),) * 10
    square = sum(
        Silver(Fraction(2, 3)) * (left * left + left * right + right * right)
        for left, right in blocks
    )
    if square != level.target:
        raise AssertionError("the H24 cutter lost its norm")
    cap_bound = _prior_cap_bound(seed, level)
    if any(
        (cap_bound - left - right).sign(0) < 0 for left, right in blocks
    ):
        raise AssertionError("the H24 cutter crossed an affine cap")
    if any(not (left - right).is_integral for left, right in blocks):
        raise AssertionError("the H24 cutter lost its integral glue residue")
    residues_rational = tuple((left - right).a.numerator % 3 for left, right in blocks)
    residues_radical = tuple((left - right).b.numerator % 3 for left, right in blocks)
    words = set(ternary_golay_codewords())
    if residues_rational not in words or residues_radical not in words:
        raise AssertionError("the H24 cutter is not in the ternary glue")
    # The coefficient 1 in the second block prevents divisibility by sqrt(2).
    primitive = blocks[1][0].a.numerator % 2 == 1
    reflection_integral = all(
        (2 * entry / level.norm).is_integral
        for block in blocks
        for entry in block
    ) and (
        2 * seed.timelike_coefficient * level.control / level.norm
    ).is_integral
    maximum_second_packet_pairing = h24_cutter_second_packet_max_pairing(seed)
    return ExplicitA2GolayCutter(
        level.height,
        level.norm,
        level.control,
        level.target,
        blocks,
        maximum_second_packet_pairing,
        primitive,
        reflection_integral,
        primitive and reflection_integral,
    )


def h24_candidate_census(seed: SilverA2GolaySeed) -> A2GolayPacketCensus:
    """Complete first-cap candidate superset at ``H=24+17*sqrt(2)``.

    The two hosts have identical target, norm, and affine-cap bound at this
    level.  We therefore run the 288-contingency dynamic program once and
    transport its exact count/maximal weight sum to the second control.
    Chronological filtering by the 3,960-wall packet may only delete members
    of this superset and is unnecessary for the strict witness below.
    """

    if seed not in SUPPORTED_A2_GOLAY_SEEDS:
        raise ValueError("unsupported A2^12 seed")
    base_level = next(
        level
        for level in control_levels(SQRT2_A2_GOLAY_SEED, 100)
        if level.height == Silver(24, 17)
    )
    level = next(
        level
        for level in control_levels(seed, 100)
        if level.height == Silver(24, 17)
    )
    if (
        level.norm != base_level.norm
        or level.target != base_level.target
        or _packet_block_options(seed, level)
        != _packet_block_options(SQRT2_A2_GOLAY_SEED, base_level)
    ):
        raise AssertionError("the two H24 candidate problems ceased to agree")
    base = packet_census_after_first_caps(SQRT2_A2_GOLAY_SEED, base_level)
    if (
        base.candidate_count != 4_733_256
        or base.surviving_contingency_count != 106
        or base.maximum_uniform_weight_sum != Silver(21, 15)
    ):
        raise AssertionError("the H24 candidate census changed")
    return A2GolayPacketCensus(
        level.height,
        level.norm,
        level.control,
        level.target,
        base.candidate_count,
        base.surviving_contingency_count,
        base.maximum_uniform_weight_sum,
    )


def frontier_censuses_through_h24(
    seed: SilverA2GolaySeed,
) -> tuple[A2GolayPacketCensus, ...]:
    """Complete post-affine first-cap census through ``24+17*sqrt(2)``."""

    endpoint = Silver(24, 17)
    first_height = (
        seed.timelike_coefficient * seed.first_control**2 / seed.first_norm
    )
    output: list[A2GolayPacketCensus] = []
    for level in control_levels(seed, 49):
        if level.height <= first_height or level.height > endpoint:
            continue
        census = (
            h24_candidate_census(seed)
            if level.height == endpoint
            else packet_census_with_seed_reuse(seed, level)
        )
        output.append(census)
    nonempty = [census for census in output if census.candidate_count]
    if (
        len(nonempty) != 2
        or nonempty[0].height != Silver(8, 6)
        or nonempty[0].candidate_count != 3960
        or nonempty[1].height != endpoint
        or nonempty[1].candidate_count != 4_733_256
    ):
        raise AssertionError("the complete H24 candidate frontier changed")
    return tuple(output)


@dataclass(frozen=True, slots=True)
class H24UniformHyperidealWitness:
    block_dynkin_weight: Silver
    lorentz_norm: Silver
    first_packet_maximum_pairing: Silver
    second_packet_maximum_pairing: Silver
    h24_candidate_maximum_pairing: Silver
    strict: bool


def h24_uniform_witness(seed: SilverA2GolaySeed) -> H24UniformHyperidealWitness:
    """A strict point against every possible wall through the H24 control."""

    census = h24_candidate_census(seed)
    second = second_packet_census(seed)
    weight = Silver(Fraction(1, 4)) if seed is SQRT2_A2_GOLAY_SEED else Silver(Fraction(3, 8))
    first_pairing = (
        -seed.timelike_coefficient * seed.first_control
        + 2 * seed.first_spatial_scale * weight
    )
    second_pairing = (
        -seed.timelike_coefficient * second.control
        + weight * second.maximum_uniform_weight_sum
    )
    h24_pairing = (
        -seed.timelike_coefficient * census.control
        + weight * census.maximum_uniform_weight_sum
    )
    norm = -seed.timelike_coefficient + 24 * weight * weight
    strict = (
        norm.sign(0) > 0
        and first_pairing.sign(0) < 0
        and second_pairing.sign(0) < 0
        and h24_pairing.sign(0) < 0
    )
    return H24UniformHyperidealWitness(
        weight,
        norm,
        first_pairing,
        second_pairing,
        h24_pairing,
        strict,
    )


