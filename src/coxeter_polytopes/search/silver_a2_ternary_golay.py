@dataclass(frozen=True, slots=True)
class A2GolayPacketCensus:
    height: Silver
    norm: Silver
    control: Silver
    target: Silver
    candidate_count: int
    surviving_contingency_count: int
    maximum_uniform_weight_sum: Silver


def _prior_cap_bound(
    seed: SilverA2GolaySeed, level: SilverH24ControlLevel
) -> Silver:
    """Maximum sum of the two Dynkin weights imposed by the first cap."""

    return (
        seed.timelike_coefficient
        * level.control
        * seed.first_control
        / seed.first_spatial_scale
    )


def _packet_block_options(
    seed: SilverA2GolaySeed, level: SilverH24ControlLevel
) -> dict[int, tuple[A2BlockOption, ...]]:
    cap_bound = _prior_cap_bound(seed, level)
    grouped: dict[int, list[A2BlockOption]] = {index: [] for index in range(9)}
    for option in dominant_a2_block_options(level.target, level.norm):
        if (cap_bound - option.weight_left - option.weight_right).sign(0) < 0:
            continue
        residue = 3 * option.rational_residue + option.radical_residue
        grouped[residue].append(option)
    return {index: tuple(options) for index, options in grouped.items()}


@lru_cache(maxsize=None)
def packet_census_after_first_caps(
    seed: SilverA2GolaySeed, level: SilverH24ControlLevel
) -> A2GolayPacketCensus:
    """Count a complete dominant packet using the two ternary glue words.

    A dynamic-programming state records the two coefficients of the partial
    spatial square, the number of labelled block assignments, and the largest
    possible sum of all Dynkin weights.  Multiplication by the exact
    contingency multiplicity restores all ordered pairs of glue words.
    """

    grouped = _packet_block_options(seed, level)
    total = 0
    surviving_types = 0
    maximum: Silver | None = None
    target_key = (level.target.a, level.target.b)
    for contingency, multiplicity in ternary_golay_pair_contingencies():
        states: dict[tuple[Fraction, Fraction], tuple[int, Silver]] = {
            (Fraction(0), Fraction(0)): (1, SILVER_ZERO)
        }
        for residue, coordinate_count in enumerate(contingency):
            for _ in range(coordinate_count):
                next_states: dict[
                    tuple[Fraction, Fraction], tuple[int, Silver]
                ] = {}
                for (left, right), (count, weight_sum) in states.items():
                    for option in grouped[residue]:
                        new_left = left + option.square.a
                        new_right = right + option.square.b
                        remainder = level.target - Silver(new_left, new_right)
                        if any(remainder.sign(place) < 0 for place in (0, 1)):
                            continue
                        key = (new_left, new_right)
                        new_weight_sum = (
                            weight_sum
                            + option.weight_left
                            + option.weight_right
                        )
                        old = next_states.get(key)
                        if old is None:
                            next_states[key] = (count, new_weight_sum)
                        else:
                            old_count, old_maximum = old
                            next_states[key] = (
                                old_count + count,
                                new_weight_sum
                                if (new_weight_sum - old_maximum).sign(0) > 0
                                else old_maximum,
                            )
                states = next_states
                if not states:
                    break
            if not states:
                break
        hit = states.get(target_key)
        if hit is None:
            continue
        count, local_maximum = hit
        surviving_types += 1
        total += multiplicity * count
        if maximum is None or (local_maximum - maximum).sign(0) > 0:
            maximum = local_maximum
    return A2GolayPacketCensus(
        level.height,
        level.norm,
        level.control,
        level.target,
        total,
        surviving_types,
        maximum or SILVER_ZERO,
    )


def packet_census_with_seed_reuse(
    seed: SilverA2GolaySeed, level: SilverH24ControlLevel
) -> A2GolayPacketCensus:
    """Reuse an identical ``a=sqrt(2)`` block problem when one exists."""

    if seed is TWO_SQRT2_A2_GOLAY_SEED:
        bound = _prior_cap_bound(seed, level)
        equivalent = next(
            (
                candidate
                for candidate in control_levels(SQRT2_A2_GOLAY_SEED, 1000)
                if candidate.norm == level.norm
                and candidate.target == level.target
                and _prior_cap_bound(SQRT2_A2_GOLAY_SEED, candidate) == bound
            ),
            None,
        )
        if equivalent is not None:
            base = packet_census_after_first_caps(
                SQRT2_A2_GOLAY_SEED, equivalent
            )
            return A2GolayPacketCensus(
                level.height,
                level.norm,
                level.control,
                level.target,
                base.candidate_count,
                base.surviving_contingency_count,
                base.maximum_uniform_weight_sum,
            )
    return packet_census_after_first_caps(seed, level)


def second_packet_census(seed: SilverA2GolaySeed) -> A2GolayPacketCensus:
    level = next(
        level
        for level in control_levels(seed, 17)
        if level.height == Silver(8, 6)
    )
    census = packet_census_with_seed_reuse(seed, level)
    if (
        census.norm != Silver(2)
        or census.target != Silver(18, 12)
        or census.candidate_count != 3960
        or census.surviving_contingency_count != 6
        or census.maximum_uniform_weight_sum != Silver(9, 9)
    ):
        raise AssertionError("the exact second A2^12 packet census changed")
    return census


@dataclass(frozen=True, slots=True)
class UniformHyperidealWitness:
    block_dynkin_weight: Silver
    lorentz_norm: Silver
    first_packet_maximum_pairing: Silver
    second_packet_maximum_pairing: Silver
    strict: bool


def second_packet_uniform_witness(
    seed: SilverA2GolaySeed,
) -> UniformHyperidealWitness:
    """Return a strict symmetric hyperideal point after both packets."""

    census = second_packet_census(seed)
    weight = seed.cap / 5
    first_pairing = (
        -seed.timelike_coefficient * seed.first_control
        + 2 * seed.first_spatial_scale * weight
    )
    second_pairing = (
        -seed.timelike_coefficient * census.control
        + weight * census.maximum_uniform_weight_sum
    )
    lorentz_norm = -seed.timelike_coefficient + 24 * weight * weight
    strict = (
        first_pairing.sign(0) < 0
        and second_pairing.sign(0) < 0
        and lorentz_norm.sign(0) > 0
    )
    return UniformHyperidealWitness(
        weight,
        lorentz_norm,
        first_pairing,
        second_pairing,
        strict,
    )


