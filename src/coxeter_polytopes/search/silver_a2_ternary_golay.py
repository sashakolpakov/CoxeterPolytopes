def control_levels(
    seed: SilverA2GolaySeed, height_bound: int = 10
) -> tuple[SilverH24ControlLevel, ...]:
    if seed not in SUPPORTED_A2_GOLAY_SEEDS:
        raise ValueError("unsupported A2^12 seed")
    return enumerate_control_levels(seed.control_seed, height_bound)


def a2_golay_pair(
    seed: SilverA2GolaySeed,
    left: Sequence[Silver],
    right: Sequence[Silver],
) -> Silver:
    if len(left) != 25 or len(right) != 25:
        raise ValueError("an H24 A2^12 vector has 25 coordinates")
    value = -seed.timelike_coefficient * left[0] * right[0]
    for block in range(12):
        offset = 1 + 2 * block
        value += (
            2 * left[offset] * right[offset]
            - left[offset] * right[offset + 1]
            - left[offset + 1] * right[offset]
            + 2 * left[offset + 1] * right[offset + 1]
        )
    return value


@lru_cache(maxsize=None)
def height_zero_simple_roots() -> tuple[Vector, ...]:
    roots: list[Vector] = []
    for index in range(24):
        root = [SILVER_ZERO] * 25
        root[index + 1] = -SILVER_ONE
        roots.append(tuple(root))
    return tuple(roots)


@lru_cache(maxsize=None)
def first_packet_roots(seed: SilverA2GolaySeed) -> tuple[Vector, ...]:
    roots: list[Vector] = []
    for block in range(12):
        root = [SILVER_ZERO] * 25
        root[0] = seed.first_control
        root[1 + 2 * block] = seed.first_spatial_scale
        root[2 + 2 * block] = seed.first_spatial_scale
        roots.append(tuple(root))
    return tuple(roots)


def first_packet_is_exact(seed: SilverA2GolaySeed) -> bool:
    """Verify the block census and the ternary-code support exclusion."""

    target = seed.first_norm + seed.timelike_coefficient * seed.first_control**2
    options = dominant_a2_block_options(target, seed.first_norm)
    affine = [option for option in options if option.square == target]
    if len(options) != 6 or len(affine) != 1 or not affine[0].residue_is_zero:
        return False
    unit = target / 3
    for option in options:
        quotient = option.square / unit
        if not quotient.is_rational or quotient.a.denominator != 1:
            return False
        multiplicity = quotient.a.numerator
        if multiplicity not in (0, 1, 2, 3):
            return False
        if multiplicity < 3 and multiplicity and option.residue_is_zero:
            return False
    # Any non-affine decomposition of total multiplicity three occupies at
    # most three blocks.  At least one coefficient residue is nonzero there,
    # contradicting the code minimum six.
    if min(weight for weight in ternary_golay_weight_enumerator() if weight) != 6:
        return False
    roots = first_packet_roots(seed)
    return all(
        a2_golay_pair(seed, root, root) == seed.first_norm for root in roots
    ) and all(
        a2_golay_pair(seed, roots[i], roots[j]).sign(0) < 0
        for i in range(12)
        for j in range(i + 1, 12)
    )


