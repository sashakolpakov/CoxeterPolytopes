def _control_decision(
    seed: SilverA2GolaySeed, level: SilverH24ControlLevel
) -> ControlDecision:
    target = level.target
    first_height = seed.timelike_coefficient * seed.first_control**2 / seed.first_norm
    if level.height == first_height:
        return ControlDecision(
            level.height,
            level.norm,
            level.control,
            target,
            "accepted",
            "exactly the twelve affine A2 highest-root caps",
        )
    if target in (Silver(2, 1), Silver(6, 3), Silver(10, 7)):
        return ControlDecision(
            level.height,
            level.norm,
            level.control,
            target,
            "empty",
            "the sqrt(2)-coefficient of y^2 would make the integral pairing u.v half-integral",
        )
    if target == Silver(20, 14):
        return ControlDecision(
            level.height,
            level.norm,
            level.control,
            target,
            "empty",
            "u^2+2v^2=20 and u.v=7 contradict minimum two after testing v^2=2,4,6",
        )
    if target == Silver(10, 6):
        return ControlDecision(
            level.height,
            level.norm,
            level.control,
            target,
            "rejected",
            "minimum two forces two roots in one A2 block; dominant weights sum to 3+2sqrt(2), above the prior cap 2+2sqrt(2)",
        )
    if level.height == Silver(7, 5):
        census = packet_census_after_first_caps(seed, level)
        if census.candidate_count:
            raise AssertionError("the H=7+5*sqrt(2) packet ceased to be empty")
        return ControlDecision(
            level.height,
            level.norm,
            level.control,
            target,
            "empty",
            "the exact 288-type ternary-glue contingency program has zero block assignments after the affine caps",
        )
    if level.height == Silver(8, 6):
        census = second_packet_census(seed)
        return ControlDecision(
            level.height,
            level.norm,
            level.control,
            target,
            "accepted",
            f"the complete ternary-glue packet has {census.candidate_count} dominant norm-two walls",
        )
    # A defensive exact block check for any future control added below H=10.
    options = dominant_a2_block_options(target, level.norm)
    if len(options) == 1 and options[0].square == 0:
        return ControlDecision(
            level.height,
            level.norm,
            level.control,
            target,
            "empty",
            "the exact dominant A2 block census contains only zero",
        )
    raise AssertionError(f"unclassified A2^12 control at {level.height}")


def control_decisions(
    seed: SilverA2GolaySeed, height_bound: int = 10
) -> tuple[ControlDecision, ...]:
    return tuple(_control_decision(seed, level) for level in control_levels(seed, height_bound))


@dataclass(frozen=True, slots=True)
class ProductTriangleGeometry:
    cap: Silver
    extreme_ray_count: int
    finite_vertex_count: int
    cusp_count: int
    hyperideal_ray_count: int
    finite_volume: bool
    compact: bool
    exact_norms_by_nonzero_blocks: tuple[Silver, ...]


def first_packet_geometry(seed: SilverA2GolaySeed) -> ProductTriangleGeometry:
    if not first_packet_is_exact(seed):
        raise AssertionError("the first packet is not the twelve affine caps")
    norms = tuple(
        -seed.timelike_coefficient + Silver(Fraction(2 * count, 3)) * seed.cap**2
        for count in range(13)
    )
    counts = tuple(comb(12, count) * 2**count for count in range(13))
    finite = sum(counts[index] for index, norm in enumerate(norms) if norm.sign(0) < 0)
    cusp = sum(counts[index] for index, norm in enumerate(norms) if norm.sign(0) == 0)
    hyperideal = sum(
        counts[index] for index, norm in enumerate(norms) if norm.sign(0) > 0
    )
    if finite + cusp + hyperideal != 3**12:
        raise AssertionError("the product-of-triangles vertex census is incomplete")
    return ProductTriangleGeometry(
        seed.cap,
        3**12,
        finite,
        cusp,
        hyperideal,
        hyperideal == 0,
        hyperideal == 0 and cusp == 0,
        norms,
    )


@dataclass(frozen=True, slots=True)
class SilverA2GolaySearch:
    seed: SilverA2GolaySeed
    height_bound: int
    controls: tuple[ControlDecision, ...]
    height_zero_wall_count: int
    accepted_positive_wall_count: int
    total_wall_count: int
    geometry: ProductTriangleGeometry
    second_packet: A2GolayPacketCensus | None = None
    strict_hyperideal_witness: UniformHyperidealWitness | None = None


def run_a2_golay_search(
    seed: SilverA2GolaySeed, height_bound: int = 10
) -> SilverA2GolaySearch:
    if height_bound not in (10, 17):
        raise ValueError("the frozen exact control audit supports H=10 or H=17")
    if not niemeier_construction_is_even_unimodular():
        raise AssertionError("the ternary Golay construction lost its lattice proof")
    decisions = control_decisions(seed, height_bound)
    accepted_packet_count = sum(
        decision.status == "accepted" for decision in decisions
    )
    expected_packet_count = 1 if height_bound == 10 else 2
    if accepted_packet_count != expected_packet_count:
        raise AssertionError("the A2^12 packet count changed")
    geometry = first_packet_geometry(seed)
    second_packet = second_packet_census(seed) if height_bound == 17 else None
    witness = (
        second_packet_uniform_witness(seed) if height_bound == 17 else None
    )
    if witness is not None and not witness.strict:
        raise AssertionError("the H17 hyperideal witness ceased to be strict")
    positive_wall_count = 12 + (
        second_packet.candidate_count if second_packet is not None else 0
    )
    return SilverA2GolaySearch(
        seed,
        height_bound,
        decisions,
        24,
        positive_wall_count,
        24 + positive_wall_count,
        geometry,
        second_packet,
        witness,
    )


def all_seed_searches() -> tuple[SilverA2GolaySearch, ...]:
    return tuple(run_a2_golay_search(seed) for seed in SUPPORTED_A2_GOLAY_SEEDS)


def all_seed_h17_searches() -> tuple[SilverA2GolaySearch, ...]:
    return tuple(
        run_a2_golay_search(seed, 17) for seed in SUPPORTED_A2_GOLAY_SEEDS
    )
