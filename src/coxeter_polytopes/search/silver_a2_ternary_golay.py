# A row basis of the extended ternary Golay code.  The first eleven entries
# are the first six cyclic shifts of the degree-five generator, and the last
# coordinate is minus the row sum modulo three.
TERNARY_GOLAY_GENERATOR = (
    (2, 0, 1, 2, 1, 1, 0, 0, 0, 0, 0, 2),
    (0, 2, 0, 1, 2, 1, 1, 0, 0, 0, 0, 2),
    (0, 0, 2, 0, 1, 2, 1, 1, 0, 0, 0, 2),
    (0, 0, 0, 2, 0, 1, 2, 1, 1, 0, 0, 2),
    (0, 0, 0, 0, 2, 0, 1, 2, 1, 1, 0, 2),
    (0, 0, 0, 0, 0, 2, 0, 1, 2, 1, 1, 2),
)


def _rank_mod_three(rows: Sequence[Sequence[int]]) -> int:
    work = [[entry % 3 for entry in row] for row in rows]
    rank = 0
    for column in range(len(work[0]) if work else 0):
        pivot = next(
            (index for index in range(rank, len(work)) if work[index][column]),
            None,
        )
        if pivot is None:
            continue
        work[rank], work[pivot] = work[pivot], work[rank]
        inverse = 1 if work[rank][column] == 1 else 2
        work[rank] = [(inverse * entry) % 3 for entry in work[rank]]
        for index in range(len(work)):
            if index == rank or not work[index][column]:
                continue
            factor = work[index][column]
            work[index] = [
                (left - factor * right) % 3
                for left, right in zip(work[index], work[rank], strict=True)
            ]
        rank += 1
    return rank


@lru_cache(maxsize=1)
def ternary_golay_codewords() -> tuple[tuple[int, ...], ...]:
    words = {
        tuple(
            sum(coefficients[row] * TERNARY_GOLAY_GENERATOR[row][column]
                for row in range(6))
            % 3
            for column in range(12)
        )
        for coefficients in product(range(3), repeat=6)
    }
    return tuple(sorted(words))


def ternary_golay_weight_enumerator() -> dict[int, int]:
    return dict(
        sorted(
            Counter(
                sum(entry != 0 for entry in word)
                for word in ternary_golay_codewords()
            ).items()
        )
    )


def ternary_golay_is_self_dual() -> bool:
    rows = TERNARY_GOLAY_GENERATOR
    return (
        _rank_mod_three(rows) == 6
        and all(
            sum(left * right for left, right in zip(rows[i], rows[j], strict=True))
            % 3
            == 0
            for i in range(6)
            for j in range(6)
        )
        and len(ternary_golay_codewords()) == 3**6
    )


@lru_cache(maxsize=1)
def ternary_golay_pair_contingencies(
) -> tuple[tuple[tuple[int, ...], int], ...]:
    """Return the exact 3-by-3 residue contingency distribution.

    A pair of length-twelve ternary codewords is represented by the nine
    counts ``#{i:(c_i,d_i)=(r,s)}``, ordered by ``3*r+s``.  There are only
    288 types instead of ``729^2`` word pairs.  Their multiplicities still
    sum to ``3^12`` and retain every rational/radical glue condition needed
    by the block dynamic program below.
    """

    distribution: Counter[tuple[int, ...]] = Counter()
    words = ternary_golay_codewords()
    for rational_word in words:
        for radical_word in words:
            histogram = [0] * 9
            for rational, radical in zip(
                rational_word, radical_word, strict=True
            ):
                histogram[3 * rational + radical] += 1
            distribution[tuple(histogram)] += 1
    return tuple(sorted(distribution.items()))


@lru_cache(maxsize=1)
def ternary_golay_two_pointed_pair_contingencies(
) -> tuple[tuple[tuple[int, int], tuple[int, ...], int], ...]:
    """Preserve two labelled residue classes and histogram the other ten."""

    distribution: Counter[tuple[tuple[int, int], tuple[int, ...]]] = Counter()
    words = ternary_golay_codewords()
    for rational_word in words:
        for radical_word in words:
            pointed = (
                3 * rational_word[0] + radical_word[0],
                3 * rational_word[1] + radical_word[1],
            )
            histogram = [0] * 9
            for rational, radical in zip(
                rational_word[2:], radical_word[2:], strict=True
            ):
                histogram[3 * rational + radical] += 1
            distribution[(pointed, tuple(histogram))] += 1
    return tuple(
        (pointed, histogram, multiplicity)
        for (pointed, histogram), multiplicity in sorted(distribution.items())
    )


def niemeier_construction_is_even_unimodular() -> bool:
    """Certify the code-overlattice determinant and evenness conditions."""

    weights = ternary_golay_weight_enumerator()
    # det(A2^12)=3^12 and the glue index is |C|=3^6.
    determinant = 3**12 // len(ternary_golay_codewords()) ** 2
    # A discriminant representative of support w has norm 2w/3 modulo 2Z.
    glue_norms_even = all((2 * weight) % 6 == 0 for weight in weights)
    return ternary_golay_is_self_dual() and determinant == 1 and glue_norms_even


@dataclass(frozen=True, slots=True)
class A2BlockOption:
    weight_left: Silver
    weight_right: Silver
    square: Silver
    rational_residue: int
    radical_residue: int

    @property
    def residue_is_zero(self) -> bool:
        return self.rational_residue == self.radical_residue == 0


def _integral_residue(value: Fraction) -> int:
    if value.denominator != 1:
        raise AssertionError("a Dynkin weight coefficient ceased to be integral")
    return value.numerator % 3


@lru_cache(maxsize=None)
def dominant_a2_block_options(
    target: Silver, root_norm: Silver
) -> tuple[A2BlockOption, ...]:
    """Enumerate every dominant reflective A2 block below ``target``."""

    twice_target = 2 * target
    alphabet = tuple(
        value
        for value in _bounded_for_caps((twice_target, twice_target))
        if value.sign(0) >= 0 and (2 * value / root_norm).is_integral
    )
    output: list[A2BlockOption] = []
    for left in alphabet:
        for right in alphabet:
            square = Silver(Fraction(2, 3)) * (
                left * left + left * right + right * right
            )
            if any((target - square).sign(place) < 0 for place in (0, 1)):
                continue
            residue = left - right
            output.append(
                A2BlockOption(
                    left,
                    right,
                    square,
                    _integral_residue(residue.a),
                    _integral_residue(residue.b),
                )
            )
    return tuple(sorted(output, key=lambda item: (item.square, item.weight_left, item.weight_right)))


