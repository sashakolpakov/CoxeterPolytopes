def _pair_add(left: IntegerPair, right: IntegerPair) -> IntegerPair:
    return left[0] + right[0], left[1] + right[1]


def _pair_sub(left: IntegerPair, right: IntegerPair) -> IntegerPair:
    return left[0] - right[0], left[1] - right[1]


def _pair_scale(scale: int, value: IntegerPair) -> IntegerPair:
    return scale * value[0], scale * value[1]


def _pair_mul(left: IntegerPair, right: IntegerPair) -> IntegerPair:
    return (
        left[0] * right[0] + 2 * left[1] * right[1],
        left[0] * right[1] + left[1] * right[0],
    )


def _pair_sign(value: IntegerPair) -> int:
    rational, radical = value
    if rational == 0:
        return (radical > 0) - (radical < 0)
    if radical == 0 or (rational > 0) == (radical > 0):
        return (rational > 0) - (rational < 0)
    if rational * rational > 2 * radical * radical:
        return (rational > 0) - (rational < 0)
    return (radical > 0) - (radical < 0)


def _pair_conjugate(value: IntegerPair) -> IntegerPair:
    return value[0], -value[1]


def _dominant_alphabet(target: Silver, root_norm: Silver) -> tuple[Silver, ...]:
    twice_target = 2 * target
    return tuple(
        value
        for value in _bounded_for_caps((twice_target, twice_target))
        if value.sign(0) >= 0
        and all((twice_target - value * value).sign(place) >= 0 for place in (0, 1))
        and (2 * value / root_norm).is_integral
    )


@lru_cache(maxsize=None)
def enumerate_dominant_e7_weights(
    target: Silver,
    root_norm: Silver,
    control_cap: Silver | None,
) -> E7Enumeration:
    """Exhaust dominant E7 weights, optionally below its affine cap."""

    gram = cartan_gram(E7_COMPONENT)
    inverse = _fraction_inverse(gram)
    schur = _prefix_schur_complements(inverse)
    marks = highest_root_marks(E7_COMPONENT)
    alphabet = _dominant_alphabet(target, root_norm)
    visited = [0] * 8
    cap_pruned = [0] * 8
    schur_pruned = [0] * 8
    output: list[DominantWeight] = []

    def extend(prefix: Vector) -> None:
        depth = len(prefix)
        visited[depth] += 1
        if depth:
            if control_cap is not None and (
                2 * control_cap
                - sum(
                    (marks[index] * prefix[index] for index in range(depth)),
                    start=SILVER_ZERO,
                )
            ).sign(0) < 0:
                cap_pruned[depth] += 1
                return
            minimum = _quadratic(prefix, schur[depth - 1])
            if any((target - minimum).sign(place) < 0 for place in (0, 1)):
                schur_pruned[depth] += 1
                return
        if depth == 7:
            square = _quadratic(prefix, inverse)
            output.append(
                DominantWeight(square, prefix, _mat_vec(inverse, prefix), e7_residue(prefix))
            )
            return
        for value in alphabet:
            extend((*prefix, value))

    extend(())
    return E7Enumeration(
        target,
        root_norm,
        control_cap,
        alphabet,
        tuple(visited),
        tuple(cap_pruned),
        tuple(schur_pruned),
        tuple(sorted(output, key=lambda item: (item.square, item.weights))),
    )


@lru_cache(maxsize=None)
def enumerate_dominant_a17_weights(
    target_energies: tuple[Silver, ...],
    root_norm: Silver,
    control_cap: Silver | None,
) -> A17Enumeration:
    """Exhaust A17 weights at the requested exact energies.

    Energies are multiplied by 18, so the recursion uses only integer pairs.
    The prefix lower bound is the exact Schur complement ``C_Ad^-1`` at both
    real embeddings.
    """

    targets = tuple(sorted(set(target_energies)))
    if not targets or any(target.sign(place) < 0 for target in targets for place in (0, 1)):
        return A17Enumeration(targets, root_norm, control_cap, (), (0,) * 18, (0,) * 18, (0,) * 18, 0, ())
    largest = max(targets)
    alphabet = _dominant_alphabet(largest, root_norm)
    if any(not value.is_integral for value in alphabet):
        raise AssertionError("the A17 Dynkin alphabet left Z[sqrt(2)]")
    integer_alphabet = tuple((int(value.a), int(value.b)) for value in alphabet)
    target_pairs = []
    for target in targets:
        scaled = 18 * target
        if not scaled.is_integral:
            raise AssertionError("an A17 target does not lie in (1/18)O")
        target_pairs.append((int(scaled.a), int(scaled.b)))
    target_pair_set = set(target_pairs)
    cap_pair = None
    if control_cap is not None:
        cap = 2 * control_cap
        if not cap.is_integral:
            raise AssertionError("the A17 affine cap is not integral")
        cap_pair = int(cap.a), int(cap.b)
    visited = [0] * 18
    cap_pruned = [0] * 18
    energy_pruned = [0] * 18
    leaves = 0
    raw: list[tuple[IntegerPair, tuple[IntegerPair, ...], IntegerPair]] = []
    zero = (0, 0)

    def extend(
        depth: int,
        weight_sum: IntegerPair,
        weighted_sum: IntegerPair,
        suffix_square_sum: IntegerPair,
        prefix: tuple[IntegerPair, ...],
    ) -> None:
        nonlocal leaves
        visited[depth] += 1
        if depth:
            # (depth+1) times the exact C_Ad^-1 prefix energy.
            minimum_numerator = _pair_sub(
                _pair_scale(depth + 1, suffix_square_sum),
                _pair_mul(weighted_sum, weighted_sum),
            )
            possible = False
            for target_pair in target_pairs:
                difference = _pair_sub(
                    _pair_scale(depth + 1, target_pair),
                    _pair_scale(18, minimum_numerator),
                )
                if _pair_sign(difference) >= 0 and _pair_sign(_pair_conjugate(difference)) >= 0:
                    possible = True
                    break
            if not possible:
                energy_pruned[depth] += 1
                return
        if depth == 17:
            leaves += 1
            energy_times_eighteen = _pair_sub(
                _pair_scale(18, suffix_square_sum),
                _pair_mul(weighted_sum, weighted_sum),
            )
            if energy_times_eighteen in target_pair_set:
                raw.append((energy_times_eighteen, prefix, weighted_sum))
            return
        position = depth + 1
        for value in integer_alphabet:
            new_sum = _pair_add(weight_sum, value)
            if cap_pair is not None and _pair_sign(_pair_sub(cap_pair, new_sum)) < 0:
                cap_pruned[depth + 1] += 1
                continue
            new_weighted = _pair_add(weighted_sum, _pair_scale(position, value))
            new_suffix_squares = _pair_add(
                suffix_square_sum,
                _pair_add(
                    _pair_scale(2, _pair_mul(value, weighted_sum)),
                    _pair_scale(position, _pair_mul(value, value)),
                ),
            )
            extend(
                depth + 1,
                new_sum,
                new_weighted,
                new_suffix_squares,
                (*prefix, value),
            )

    extend(0, zero, zero, zero, ())
    inverse = _fraction_inverse(cartan_gram(A17_COMPONENT))
    output = []
    for energy_pair, integer_weights, weighted_sum in raw:
        weights = tuple(Silver(*value) for value in integer_weights)
        square = Silver(*energy_pair) / 18
        coordinates = _mat_vec(inverse, weights)
        if _quadratic(weights, inverse) != square:
            raise AssertionError("the integer A17 energy recurrence disagrees with C^-1")
        residue = weighted_sum[0] % 18, weighted_sum[1] % 18
        if residue != a17_residue(weights):
            raise AssertionError("the A17 recurrence residue changed")
        output.append(DominantWeight(square, weights, coordinates, residue))
    return A17Enumeration(
        targets,
        root_norm,
        control_cap,
        alphabet,
        tuple(visited),
        tuple(cap_pruned),
        tuple(energy_pruned),
        leaves,
        tuple(sorted(output, key=lambda item: (item.square, item.weights))),
    )


@dataclass(frozen=True, slots=True)
class SilverA17E7ControlLevel:
    norm: Silver
    height: Silver
    control: Silver
    target: Silver


@lru_cache(maxsize=None)
def enumerate_control_levels(height_bound: int = 15) -> tuple[SilverA17E7ControlLevel, ...]:
    if height_bound < 0:
        raise ValueError("height bound must be nonnegative")
    levels: set[SilverA17E7ControlLevel] = set()
    for norm in UNIT_NORM_CLASSES:
        caps = (norm * height_bound / EPSILON, norm / (-EPSILON))
        for control in _bounded_for_caps(caps):
            if control.sign(0) <= 0 or not (2 * EPSILON * control / norm).is_integral:
                continue
            target = norm + EPSILON * control * control
            if target.sign(1) < 0:
                continue
            height = EPSILON * control * control / norm
            if (Silver(height_bound) - height).sign(0) < 0:
                continue
            levels.add(SilverA17E7ControlLevel(norm, height, control, target))
    return tuple(sorted(levels, key=lambda level: (level.height, level.norm, level.control)))


@dataclass(frozen=True, slots=True)
class SilverA17E7Candidate:
    norm: Silver
    height: Silver
    control: Silver
    target: Silver
    a17: DominantWeight
    e7: DominantWeight

    @property
    def glue_nontrivial(self) -> bool:
        return self.a17.residue != (0, 0) or self.e7.residue != (0, 0)

    @property
    def cross_component_glue(self) -> bool:
        """Whether the glue class has nonzero projections to both factors."""

        return self.e7.residue != (0, 0)


def _candidate_is_primitive(candidate: SilverA17E7Candidate) -> bool:
    if candidate.norm != 2 or not (candidate.control / SQRT2).is_integral:
        return True
    divided_a = tuple(value / SQRT2 for value in candidate.a17.weights)
    divided_e = tuple(value / SQRT2 for value in candidate.e7.weights)
    if not all(value.is_integral for value in (*divided_a, *divided_e)):
        return True
    return not a17_e7_glue_membership(divided_a, divided_e)


@lru_cache(maxsize=None)
def enumerate_control_level(
    level: SilverA17E7ControlLevel,
    affine_caps_active: bool,
) -> tuple[SilverA17E7Candidate, ...]:
    """Enumerate one complete dominant shell with the exact cyclic glue."""

    cap = level.control if affine_caps_active else None
    e7 = enumerate_dominant_e7_weights(level.target, level.norm, cap)
    e7_vectors = tuple(
        vector
        for vector in e7.vectors
        if all((level.target - vector.square).sign(place) >= 0 for place in (0, 1))
    )
    target_energies = tuple(sorted({level.target - vector.square for vector in e7_vectors}))
    a17 = enumerate_dominant_a17_weights(target_energies, level.norm, cap)
    e7_by_complement: dict[Silver, list[DominantWeight]] = defaultdict(list)
    for vector in e7_vectors:
        e7_by_complement[level.target - vector.square].append(vector)
    candidates = []
    for a_vector in a17.vectors:
        for e_vector in e7_by_complement.get(a_vector.square, ()):
            if not a17_e7_glue_membership(a_vector.weights, e_vector.weights):
                continue
            candidate = SilverA17E7Candidate(
                level.norm,
                level.height,
                level.control,
                level.target,
                a_vector,
                e_vector,
            )
            if _candidate_is_primitive(candidate):
                if a17_e7_pair(candidate, candidate) != level.norm:
                    raise AssertionError("A17E7 reconstruction has the wrong norm")
                candidates.append(candidate)
    return tuple(
        sorted(candidates, key=lambda root: (root.control, root.a17.weights, root.e7.weights))
    )


def a17_e7_pair(
    left: SilverA17E7Candidate, right: SilverA17E7Candidate
) -> Silver:
    return (
        -EPSILON * left.control * right.control
        + sum(
            (
                left.a17.weights[index] * right.a17.coordinates[index]
                for index in range(17)
            ),
            start=SILVER_ZERO,
        )
        + sum(
            (
                left.e7.weights[index] * right.e7.coordinates[index]
                for index in range(7)
            ),
            start=SILVER_ZERO,
        )
    )


@lru_cache(maxsize=1)
def height_zero_dominant_roots() -> tuple[SilverA17E7Candidate, ...]:
    roots = []
    for norm in UNIT_NORM_CLASSES:
        roots.extend(
            enumerate_control_level(
                SilverA17E7ControlLevel(norm, SILVER_ZERO, SILVER_ZERO, norm),
                False,
            )
        )
    return tuple(sorted(roots, key=lambda root: (root.norm, root.a17.weights, root.e7.weights)))


