@dataclass(frozen=True, slots=True)
class SilverA17E7Prefix:
    height_bound: int
    controls: tuple[SilverA17E7ControlLevel, ...]
    packets: tuple[SilverA17E7Packet, ...]
    accepted_roots: tuple[SilverA17E7Candidate, ...]


@lru_cache(maxsize=None)
def run_a17_e7_prefix(height_bound: int = 15) -> SilverA17E7Prefix:
    """Run the complete chronological prefix through the second packet."""

    if not a17_e7_basis_audit():
        raise AssertionError("the displayed A17E7 glue basis is not even unimodular")
    height_zero = height_zero_dominant_roots()
    if len(height_zero) != 2 or any(root.norm != 2 for root in height_zero):
        raise AssertionError("height zero is not exactly A17+E7")
    controls = enumerate_control_levels(height_bound)
    accepted: list[SilverA17E7Candidate] = []
    packets: list[SilverA17E7Packet] = []
    nonempty_packets = 0
    for height, iterator in groupby(controls, key=lambda level: level.height):
        packet_controls = tuple(iterator)
        candidates = tuple(
            root
            for level in packet_controls
            for root in enumerate_control_level(level, nonempty_packets > 0)
        )
        survivors = tuple(
            root
            for root in candidates
            if all(a17_e7_pair(root, wall).sign(0) <= 0 for wall in accepted)
        )
        if any(
            a17_e7_pair(left, right).sign(0) > 0
            for index, left in enumerate(survivors)
            for right in survivors[index + 1 :]
        ):
            raise AssertionError("same-height A17E7 survivors are not mutually acute")
        accepted.extend(survivors)
        packets.append(
            SilverA17E7Packet(
                height,
                packet_controls,
                len(candidates),
                len(candidates) - len(survivors),
                survivors,
            )
        )
        if survivors:
            nonempty_packets += 1
        if nonempty_packets == 2:
            break
    return SilverA17E7Prefix(height_bound, controls, tuple(packets), tuple(accepted))


@dataclass(frozen=True, slots=True)
class SilverA17E7FirstGeometry:
    extreme_ray_count: int
    finite_count: int
    cusp_count: int
    hyperideal_count: int


@lru_cache(maxsize=1)
def first_packet_geometry() -> SilverA17E7FirstGeometry:
    distribution = {Fraction(0): 1}
    for component in (A17_COMPONENT, E7_COMPONENT):
        updated: dict[Fraction, int] = {}
        for energy, multiplicity in distribution.items():
            for vertex_energy in affine_vertex_energies(component):
                total = energy + vertex_energy
                updated[total] = updated.get(total, 0) + multiplicity
        distribution = updated
    finite = sum(
        multiplicity
        for energy, multiplicity in distribution.items()
        if (Silver(energy) - EPSILON).sign(0) < 0
    )
    cusps = sum(
        multiplicity
        for energy, multiplicity in distribution.items()
        if (Silver(energy) - EPSILON).sign(0) == 0
    )
    total = sum(distribution.values())
    return SilverA17E7FirstGeometry(total, finite, cusps, total - finite - cusps)


