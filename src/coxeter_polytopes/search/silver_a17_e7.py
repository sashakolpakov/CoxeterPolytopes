SECOND_PACKET_HEIGHT = Silver(7, 5)

COMPLETE_UNIT_NORM_PROOF = (
    "Put pi=sqrt(2) and epsilon=1+pi. The coefficient epsilon is a unit "
    "and N(A17 E7) is even unimodular. For primitive r=(x,y), reflection "
    "integrality says q(r) divides 2I(r), I(r)=(epsilon*x,(y,N)). Away "
    "from (pi), local unimodularity and primitivity make I(r) the unit "
    "ideal. At (pi), a unit control gives v_pi(q)=0; otherwise a primitive "
    "spatial coordinate makes I(r) a unit, while evenness and q|2I force "
    "v_pi(q)=2. Every totally-positive unit of Z[sqrt(2)] is a square, so "
    "the complete canonical positive norms are 1 and 2."
)


def _determinant(matrix: RationalMatrix) -> Fraction:
    work = [list(row) for row in matrix]
    result = Fraction(1)
    for column in range(len(work)):
        pivot = next(row for row in range(column, len(work)) if work[row][column])
        if pivot != column:
            work[column], work[pivot] = work[pivot], work[column]
            result *= -1
        value = work[column][column]
        result *= value
        for row in range(column + 1, len(work)):
            factor = work[row][column] / value
            for index in range(column + 1, len(work)):
                work[row][index] -= factor * work[column][index]
    return result


@lru_cache(maxsize=1)
def a17_e7_niemeier_gram() -> RationalMatrix:
    """An explicit even unimodular glue basis Gram matrix.

    The basis is ``alpha_1,...,alpha_16``, all seven E7 simple roots, and
    ``g=omega_3(A17)+omega_6(E7)``.  Since the alpha_17 coefficient of g
    is ``1/6``, this basis contains the root lattice with index six.
    """

    a17 = cartan_gram(A17_COMPONENT)
    e7 = cartan_gram(E7_COMPONENT)
    rank = 24
    gram = [[Fraction(0) for _ in range(rank)] for _ in range(rank)]
    for i in range(16):
        for j in range(16):
            gram[i][j] = a17[i][j]
    for i in range(7):
        for j in range(7):
            gram[16 + i][16 + j] = e7[i][j]
    gram[2][23] = gram[23][2] = Fraction(1)
    gram[16 + 5][23] = gram[23][16 + 5] = Fraction(1)
    gram[23][23] = Fraction(4)
    return tuple(tuple(row) for row in gram)


def a17_e7_basis_audit() -> bool:
    gram = a17_e7_niemeier_gram()
    return (
        _determinant(gram) == 1
        and all(value.denominator == 1 for row in gram for value in row)
        and all(gram[index][index].numerator % 2 == 0 for index in range(24))
    )


def a17_residue(weights: Sequence[Silver]) -> tuple[int, int]:
    if len(weights) != 17 or not all(value.is_integral for value in weights):
        raise ValueError("A17 Dynkin weights must be 17 silver integers")
    return tuple(
        sum(
            (index + 1) * int(getattr(value, coefficient))
            for index, value in enumerate(weights)
        )
        % 18
        for coefficient in ("a", "b")
    )


def e7_residue(weights: Sequence[Silver]) -> tuple[int, int]:
    if len(weights) != 7 or not all(value.is_integral for value in weights):
        raise ValueError("E7 Dynkin weights must be seven silver integers")
    return tuple(
        sum(int(getattr(weights[index], coefficient)) for index in E7_RESIDUE_INDICES)
        % 2
        for coefficient in ("a", "b")
    )


def a17_e7_glue_membership(
    a17_weights: Sequence[Silver], e7_weights: Sequence[Silver]
) -> bool:
    """Test the cyclic ``<(3,1)>`` glue in both silver coefficients."""

    try:
        a_residue = a17_residue(a17_weights)
        e_residue = e7_residue(e7_weights)
    except ValueError:
        return False
    return all(
        a_residue[index] % 3 == 0
        and e_residue[index] == (a_residue[index] // 3) % 2
        for index in (0, 1)
    )


