"""Exact silver Vinberg packets for the Niemeier lattice ``N(A17 E7)``.

Let ``R=A17+E7``.  Its discriminant group has order ``18*2=36``.  In the
numbering used here, the even unimodular Niemeier extension is generated by

``g = omega_3(A17) + omega_6(E7)``.

The class of ``g`` has order six and square ``5/2+3/2=4``.  Consequently
the glue subgroup is

``<(3,1)> in (Z/18) + (Z/2)``.

For Dynkin weights ``z``, the two discriminant residues are

``rho_A(z)=sum((i+1)z_i) mod 18`` and
``rho_E(z)=z_4+z_6+z_7 mod 2``.

Membership in ``N(A17 E7) tensor Z[sqrt(2)]`` is imposed separately on the
rational and radical coefficient residues.  No root-lattice-only proxy is
used.

The Lorentzian seed is

``<-(1+sqrt(2))> + N(A17 E7)``.

For its even unimodular spatial block the complete primitive mirror-norm
representatives are ``1,2``.  The A17 enumerator uses a chain-specific exact
dynamic program.  If ``z_1,...,z_d`` is a prefix, its minimum possible
energy after completing the remaining A17 Dynkin weights is
``z^T C_Ad^-1 z``.  Writing ``W=sum(i*z_i)`` and
``T=sum_j(sum_{i>=j} z_i)^2``, this is ``T-W^2/(d+1)``.  Integer-pair
arithmetic therefore gives cheap, exact two-embedding Schur pruning even at
rank 17.
"""

