"""Exact H22 Vinberg prefix for the full-rank golden path host.

The host is the rank-23 ``Z[phi]`` lattice with Cartan matrix

``A_01=-1, A_10=-(2+2*phi), A_i,i+1=A_i+1,i=-1 (i>=1)``

and symmetrizer ``diag(2+2*phi,1^22)``.  Thus its symmetric Gram matrix
has diagonal ``(4+4*phi,2^22)``, first off-diagonal ``-(2+2*phi)``, and
all later off-diagonal entries ``-1``.

This module proves the complete primitive mirror-norm *candidate* alphabet
and performs an exact, chronological Vinberg enumeration through height 10.
It deliberately makes no claim beyond that height and no reflectivity claim.
"""

from __future__ import annotations

