"""Exact ``D24+`` prefixes for the three split-prime-13 directions.

Let ``theta=2*cos(2*pi/7)`` and let ``p`` be one of the three totally
positive generators of the primes above 13.  This module searches

``L(p) = < -theta*p > + D24+``.

The three choices are Galois conjugate as field elements but are retained
separately because the distinguished Lorentzian embedding is fixed.

For a primitive vector ``r=(x,y)``, put ``I=(theta*p*x,(y,D24+))``.
Even unimodularity gives ``(q(r)) | 2I``.  Away from the inert prime (2)
and the selected split prime (p), primitivity and self-duality force zero
valuation.  At either supported prime the valuation is zero or one.  Since
the field has class number one and every totally positive unit is a square,
the complete canonical mirror norms are ``1,2,p,2p``.

For the p-divisible norms, self-duality makes reflection integrality
equivalent to ``y in p*D24+``.  The spatial enumerator therefore writes
``y=p*z`` and performs the complete root/spinor glue enumeration at the
reduced square ``z^2=y^2/p^2``.
"""

from __future__ import annotations

from functools import lru_cache
from itertools import groupby

from coxeter_polytopes.exact.cubic7 import THETA7, Cubic7
from coxeter_polytopes.search.cubic7_d24_plus_coefficients import (
    Cubic7D24CoefficientCandidate,
    Cubic7D24CoefficientLevel,
    Cubic7D24CoefficientPacket,
    Cubic7D24CoefficientSearch,
    Cubic7D24CoefficientSeed,
    _reflection_integral,
    d24_coefficient_pair,
)
from coxeter_polytopes.search.cubic7_d24_plus_unit import (
    d24_height_zero_simple_roots_orthonormal,
    enumerate_dominant_d24_plus_spatial,
)
from coxeter_polytopes.search.cubic7_dn import d24_plus_basis_audit
from coxeter_polytopes.search.cubic7_root_blocks import _bounded_for_caps


P13_R7 = Cubic7(0, -1, 2)
P13_R10 = Cubic7(1, -1, 1)
P13_R8 = Cubic7(1, 0, 1)


def _local_norm_proof(prime: Cubic7, label: str) -> str:
    return (
        f"Let p=({label}), generated by {prime}, with N(p)=13, and put "
        "I(r)=(theta*p*x,(y,D24+)). Since D24+ is even unimodular, "
        "reflection integrality gives (q(r))|2I(r). Away from the inert "
        "prime (2) and p, primitivity and self-duality force v(q)=0. At p, "
        "either y is primitive and v_p(q)=0, or y lies in pD24+, x is a "
        "p-adic unit, and q=-theta*p*x^2 mod p^2 has v_p(q)=1. At (2), "
        "evenness and the same divisibility give v_2(q)=0 or 1. Hence the "
        "complete norm ideals are (1),(2),p,2p. Class number one and "
        "U^+=U^2 give the canonical totally-positive elements 1,2,p,2p."
    )


def _seed(seed_id: str, prime: Cubic7, label: str) -> Cubic7D24CoefficientSeed:
    if prime.norm() != 13 or any(prime.sign(place) <= 0 for place in range(3)):
        raise ValueError("a split-prime-13 generator must be totally positive of norm 13")
    return Cubic7D24CoefficientSeed(
        seed_id,
        THETA7 * prime,
        (Cubic7(1), Cubic7(2), prime, 2 * prime),
        label,
        _local_norm_proof(prime, label),
    )


P13_R7_D24_SEED = _seed(
    "cubic7-H24-D24+-a-theta-p13-r7", P13_R7, "p13(theta=7)"
)
P13_R10_D24_SEED = _seed(
    "cubic7-H24-D24+-a-theta-p13-r10", P13_R10, "p13(theta=10)"
)
P13_R8_D24_SEED = _seed(
    "cubic7-H24-D24+-a-theta-p13-r8", P13_R8, "p13(theta=8)"
)
P13_D24_SEEDS = (P13_R7_D24_SEED, P13_R10_D24_SEED, P13_R8_D24_SEED)


def split13_prime(seed: Cubic7D24CoefficientSeed) -> Cubic7:
    try:
        return {
            P13_R7_D24_SEED: P13_R7,
            P13_R10_D24_SEED: P13_R10,
            P13_R8_D24_SEED: P13_R8,
        }[seed]
    except KeyError as error:
        raise ValueError("unsupported split-prime-13 D24+ seed") from error


@lru_cache(maxsize=None)
def split13_height_zero_patterns(
    seed: Cubic7D24CoefficientSeed,
) -> tuple[tuple[Cubic7, str, tuple[Cubic7, ...]], ...]:
    """Return every reflective dominant height-zero spatial pattern.

    A singleton norm-two ``D`` pattern is exactly the ordinary ``D24`` root
    orbit.  Thus this finite enumeration certifies that the 24 classical
    simple roots give the complete height-zero reflection chamber.
    """

    split13_prime(seed)
    output = []
    for norm in seed.canonical_mirror_norms:
        for pattern in enumerate_dominant_d24_plus_spatial(norm):
            if _reflection_integral(seed, norm, Cubic7(0), pattern.coordinates):
                output.append((norm, pattern.coset, pattern.coordinates))
    return tuple(sorted(output, key=lambda row: (row[0], row[2], row[1])))


@lru_cache(maxsize=None)
def enumerate_split13_control_levels(
    seed: Cubic7D24CoefficientSeed, height_bound: int
) -> tuple[Cubic7D24CoefficientLevel, ...]:
    """Exhaust every control compatible with all three archimedean boxes."""

    split13_prime(seed)
    if not seed.admissible:
        raise ValueError("the split-prime coefficient is not Lorentzian")
    if height_bound < 0:
        raise ValueError("height_bound must be nonnegative")
    coefficient = seed.timelike_coefficient
    levels: set[Cubic7D24CoefficientLevel] = set()
    for norm in seed.canonical_mirror_norms:
        caps = (
            norm * height_bound / coefficient,
            norm / (-coefficient),
            norm / (-coefficient),
        )
        for control in _bounded_for_caps(caps):
            if control.sign(0) <= 0:
                continue
            if not (2 * coefficient * control / norm).is_integral:
                continue
            target = norm + coefficient * control * control
            if any(target.sign(place) < 0 for place in (1, 2)):
                continue
            height = coefficient * control * control / norm
            if (Cubic7(height_bound) - height).sign(0) < 0:
                continue
            levels.add(Cubic7D24CoefficientLevel(norm, height, control, target))
    return tuple(
        sorted(levels, key=lambda level: (level.height, level.norm, level.control))
    )


@lru_cache(maxsize=None)
def enumerate_split13_level(
    seed: Cubic7D24CoefficientSeed,
    level: Cubic7D24CoefficientLevel,
) -> tuple[Cubic7D24CoefficientCandidate, ...]:
    """Enumerate one control, including all eight ``D24+ / D24`` classes."""

    prime = split13_prime(seed)
    if level.norm not in seed.canonical_mirror_norms:
        raise ValueError("a level has a noncanonical mirror norm")
    prime_divisible = level.norm in (prime, 2 * prime)
    scale = prime if prime_divisible else Cubic7(1)
    reduced_target = level.target / (prime * prime) if prime_divisible else level.target
    if prime_divisible and not reduced_target.is_integral:
        return ()

    output = []
    for pattern in enumerate_dominant_d24_plus_spatial(reduced_target):
        spatial = tuple(scale * value for value in pattern.coordinates)
        if not _reflection_integral(seed, level.norm, level.control, spatial):
            continue
        vector = (level.control, *spatial)
        if d24_coefficient_pair(seed, vector, vector) != level.norm:
            raise AssertionError("a split-prime D24+ candidate has the wrong norm")
        output.append(
            Cubic7D24CoefficientCandidate(
                level.norm,
                level.height,
                level.control,
                level.target,
                pattern.coset,
                vector,
            )
        )
    return tuple(sorted(output, key=lambda root: (root.norm, root.vector, root.coset)))


@lru_cache(maxsize=None)
def run_split13_prefix(
    seed: Cubic7D24CoefficientSeed, height_bound: int = 300
) -> Cubic7D24CoefficientSearch:
    """Run glue-complete simultaneous-height Vinberg selection."""

    split13_prime(seed)
    if not d24_plus_basis_audit():
        raise AssertionError("the D24+ glue basis lost even unimodularity")
    levels = enumerate_split13_control_levels(seed, height_bound)
    walls = list(d24_height_zero_simple_roots_orthonormal())
    accepted: list[Cubic7D24CoefficientCandidate] = []
    packets = []
    for height, iterator in groupby(levels, key=lambda level: level.height):
        candidates = tuple(
            root
            for level in iterator
            for root in enumerate_split13_level(seed, level)
        )
        survivors = tuple(
            root
            for root in candidates
            if all(
                d24_coefficient_pair(seed, root.vector, wall).sign(0) <= 0
                for wall in walls
            )
        )
        if any(
            d24_coefficient_pair(seed, left.vector, right.vector).sign(0) > 0
            for index, left in enumerate(survivors)
            for right in survivors[index + 1 :]
        ):
            raise AssertionError("same-height split-prime D24+ roots are not acute")
        accepted.extend(survivors)
        walls.extend(root.vector for root in survivors)
        packets.append(Cubic7D24CoefficientPacket(height, len(candidates), survivors))
    return Cubic7D24CoefficientSearch(
        seed, height_bound, len(levels), tuple(packets), tuple(accepted)
    )


