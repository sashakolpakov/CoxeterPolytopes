def _block_weights(block: str, coordinates: Sequence[Cubic7]) -> Vector:
    gram, _inverse, _schur = _block_data(block)
    return tuple(
        sum(
            (
                Cubic7(gram[i][j]) * coordinates[j]
                for j in range(len(coordinates))
                if gram[i][j]
            ),
            start=CUBIC7_ZERO,
        )
        for i in range(len(coordinates))
    )


def _structured_h22_first_packet_geometry(
    seed: Cubic7RootBlockSeed,
    accepted: Sequence[H22RootBlockCandidate],
    walls: Sequence[Vector],
) -> H22RootBlockGeometry | None:
    """Exhaust the first packet as ``Delta_8 x Delta_8 x Delta_6``."""

    if len(accepted) != 3 or len(walls) != 25:
        return None
    blocks = (("E8", 0, 1, 9), ("E8", 1, 9, 17), ("E6", 2, 17, 23))
    controls = {root.control for root in accepted}
    if len(controls) != 1:
        return None
    control = next(iter(controls))
    data: dict[int, tuple[Vector, int]] = {}
    for root_offset, root in enumerate(accepted):
        nonzero = []
        for block_name, block_index, start, stop in blocks:
            coordinates = root.vector[start:stop]
            weights = _block_weights(block_name, coordinates)
            if any(weights):
                nonzero.append((block_name, block_index, coordinates, weights))
        if len(nonzero) != 1:
            return None
        block_name, block_index, coordinates, weights = nonzero[0]
        entries = [(index, value) for index, value in enumerate(weights) if value]
        if len(entries) != 1 or block_index in data:
            return None
        _index, scale = entries[0]
        highest = tuple(entry / scale for entry in coordinates)
        if not all(entry.is_rational and entry.a > 0 for entry in highest):
            return None
        data[block_index] = (highest, 22 + root_offset)
    if set(data) != {0, 1, 2}:
        return None
    # All three accepted roots have the same unit scale 1+theta.
    first_root = accepted[0]
    nonzero_coordinate = next(entry for entry in first_root.vector[1:] if entry)
    # Extract the scale intrinsically from a block weight, not from the
    # coordinate (which is generally a highest-root multiple).
    for block_name, block_index, start, stop in blocks:
        weights = _block_weights(block_name, first_root.vector[start:stop])
        if any(weights):
            scale = next(entry for entry in weights if entry)
            break
    else:  # pragma: no cover - guarded by the recognition above
        return None
    del first_root, nonzero_coordinate
    cap = seed.timelike_coefficient * control / scale
    if cap != 2:
        return None

    rays: list[H22ExtremeRay] = []
    ranges = (range(9), range(9), range(7))
    for choices in product(*ranges):
        vector_entries: list[Cubic7] = [CUBIC7_ONE]
        active: list[int] = []
        spatial_square = CUBIC7_ZERO
        for (block_name, block_index, _start, _stop), choice in zip(blocks, choices):
            highest, new_facet = data[block_index]
            _gram, inverse, _schur = _block_data(block_name)
            weights = [CUBIC7_ZERO] * len(highest)
            simple_offset = 8 * block_index
            for coordinate in range(len(highest)):
                if choice != coordinate + 1:
                    active.append(simple_offset + coordinate)
            if choice:
                coordinate = choice - 1
                weight = cap / highest[coordinate]
                weights[coordinate] = weight
                spatial_square += (
                    weight * Cubic7(inverse[coordinate][coordinate]) * weight
                )
                active.append(new_facet)
            vector_entries.extend(_mat_vec(inverse, tuple(weights)))
        vector = tuple(vector_entries)
        if len(active) != 22:
            raise AssertionError("product-simplex H22 active basis has the wrong rank")
        norm = -seed.timelike_coefficient + spatial_square
        sign = norm.sign(0)
        rays.append(
            H22ExtremeRay(
                vector,
                tuple(sorted(active)),
                norm,
                "finite" if sign < 0 else "cusp" if sign == 0 else "hyperideal",
                True,
            )
        )
    ordered = tuple(sorted(rays, key=lambda ray: ray.vector))
    if len(ordered) != 9 * 9 * 7 or len({ray.vector for ray in ordered}) != 9 * 9 * 7:
        raise AssertionError("the E8-E8-E6 product lost a projective ray")
    finite = sum(ray.kind == "finite" for ray in ordered)
    cusps = sum(ray.kind == "cusp" for ray in ordered)
    hyperideal = sum(ray.kind == "hyperideal" for ray in ordered)
    return H22RootBlockGeometry(
        ordered,
        finite,
        cusps,
        hyperideal,
        True,
        hyperideal == 0,
        hyperideal == 0 and cusps == 0,
    )


def analyze_h22_root_block_cone(
    seed: Cubic7RootBlockSeed, walls: Sequence[Vector]
) -> H22RootBlockGeometry | None:
    """Exact incremental double description for a pointed H22 prefix."""

    ambient_rank = 23
    if len(walls) < ambient_rank:
        return None
    gram = h22_basis_gram(seed)
    functionals = tuple(
        tuple(
            sum(
                (gram[i][j] * wall[j] for j in range(ambient_rank) if gram[i][j]),
                start=CUBIC7_ZERO,
            )
            for i in range(ambient_rank)
        )
        for wall in walls
    )
    initial = tuple(range(ambient_rank))
    if _row_rank(tuple(functionals[i] for i in initial), ambient_rank) != ambient_rank:
        return None

    processed = list(initial)
    rays: dict[tuple[Cubic7, ...], tuple[Vector, frozenset[int]]] = {}
    for omitted in initial:
        support = tuple(index for index in initial if index != omitted)
        ray = _kernel(tuple(functionals[index] for index in support))
        if ray is None:
            raise AssertionError("independent seed cone lost a projective ray")
        values = tuple(_functional_value(functionals[index], ray) for index in initial)
        if all(value.sign(0) <= 0 for value in values):
            oriented = ray
        elif all(value.sign(0) >= 0 for value in values):
            oriented = tuple(-entry for entry in ray)
        else:
            raise AssertionError("independent seed cone has inconsistent orientation")
        active = frozenset(
            index
            for index in initial
            if not _functional_value(functionals[index], oriented)
        )
        rays[_projective_key(oriented)] = (oriented, active)

    rank_cache: dict[frozenset[int], int] = {}
    for new_facet in range(ambient_rank, len(walls)):
        functional = functionals[new_facet]
        negative = []
        zero = []
        positive = []
        for ray, active in rays.values():
            value = _functional_value(functional, ray)
            (negative if value.sign(0) < 0 else positive if value.sign(0) > 0 else zero).append(
                (ray, active, value)
            )
        updated: dict[tuple[Cubic7, ...], tuple[Vector, frozenset[int]]] = {}
        for ray, active, _value in negative:
            updated[_projective_key(ray)] = (ray, active)
        for ray, active, _value in zero:
            updated[_projective_key(ray)] = (ray, active | frozenset((new_facet,)))
        for negative_ray, negative_active, negative_value in negative:
            for positive_ray, positive_active, positive_value in positive:
                common = negative_active & positive_active
                if len(common) < ambient_rank - 2:
                    continue
                common_rank = rank_cache.get(common)
                if common_rank is None:
                    common_rank = _row_rank(
                        tuple(functionals[index] for index in common), ambient_rank
                    )
                    rank_cache[common] = common_rank
                if common_rank != ambient_rank - 2:
                    continue
                ray = tuple(
                    positive_value * negative_ray[index]
                    - negative_value * positive_ray[index]
                    for index in range(ambient_rank)
                )
                active = frozenset(
                    index
                    for index in (*processed, new_facet)
                    if not _functional_value(functionals[index], ray)
                )
                updated[_projective_key(ray)] = (ray, active)
        rays = updated
        processed.append(new_facet)

    output: list[H22ExtremeRay] = []
    for ray, active in rays.values():
        norm = root_block_pair(seed, ray, ray)
        sign = norm.sign(0)
        output.append(
            H22ExtremeRay(
                ray,
                tuple(sorted(active)),
                norm,
                "finite" if sign < 0 else "cusp" if sign == 0 else "hyperideal",
                _row_rank(
                    tuple(functionals[index] for index in active), ambient_rank
                )
                == ambient_rank - 1,
            )
        )
    ordered = tuple(sorted(output, key=lambda ray: _projective_key(ray.vector)))
    finite = sum(ray.kind == "finite" for ray in ordered)
    cusps = sum(ray.kind == "cusp" for ray in ordered)
    hyperideal = sum(ray.kind == "hyperideal" for ray in ordered)
    irredundant = bool(ordered) and all(
        any(_functional_value(functionals[facet], ray.vector).sign(0) < 0 for ray in ordered)
        for facet in range(len(functionals))
    )
    finite_volume = irredundant and hyperideal == 0
    return H22RootBlockGeometry(
        ordered,
        finite,
        cusps,
        hyperideal,
        irredundant,
        finite_volume,
        finite_volume and cusps == 0,
    )


@dataclass(frozen=True, slots=True)
class H22RootBlockSearch:
    seed: Cubic7RootBlockSeed
    height_bound: int
    control_levels: tuple[H22ControlLevel, ...]
    levels: tuple[H22VinbergLevel, ...]
    cone_roots: tuple[Vector, ...]
    accepted_roots: tuple[H22RootBlockCandidate, ...]
    rejected_roots: tuple[H22RootBlockCandidate, ...]
    walls: tuple[Vector, ...]
    geometry: H22RootBlockGeometry | None


@lru_cache(maxsize=None)
def run_h22_root_block_vinberg(
    seed: Cubic7RootBlockSeed,
    height_bound: int,
    *,
    analyze_geometry: bool = True,
) -> H22RootBlockSearch:
    if seed not in SUPPORTED_ROOT_BLOCK_SEEDS:
        raise ValueError("unsupported root-block seed")
    if not height_zero_is_e8_e8_e6(seed):
        raise AssertionError("height-zero dominant census found an extra mirror orbit")
    controls = _control_levels(seed, height_bound)
    walls = list(h22_height_zero_simple_roots())
    accepted: list[H22RootBlockCandidate] = []
    rejected: list[H22RootBlockCandidate] = []
    levels: list[H22VinbergLevel] = []
    for height, control_iterator in groupby(controls, key=lambda item: item.height):
        packet_controls = tuple(control_iterator)
        candidates = tuple(
            candidate
            for control in packet_controls
            for candidate in enumerate_h22_control_level(seed, control)
        )
        survivors = tuple(
            candidate
            for candidate in candidates
            if all(root_block_pair(seed, candidate.vector, wall).sign(0) <= 0 for wall in walls)
        )
        if any(
            root_block_pair(seed, left.vector, right.vector).sign(0) > 0
            for index, left in enumerate(survivors)
            for right in survivors[index + 1 :]
        ):
            raise AssertionError("same-height H22 survivors are not mutually acute")
        survivor_set = set(survivors)
        accepted.extend(survivors)
        rejected.extend(candidate for candidate in candidates if candidate not in survivor_set)
        walls.extend(candidate.vector for candidate in survivors)
        levels.append(
            H22VinbergLevel(
                height,
                packet_controls,
                len(candidates),
                len(candidates) - len(survivors),
                survivors,
            )
        )
    geometry = None
    if analyze_geometry and len(walls) >= 23:
        geometry = _structured_h22_first_packet_geometry(seed, accepted, walls)
        if geometry is None:
            geometry = analyze_h22_root_block_cone(seed, walls)
    return H22RootBlockSearch(
        seed,
        height_bound,
        controls,
        tuple(levels),
        h22_height_zero_simple_roots(),
        tuple(accepted),
        tuple(rejected),
        tuple(walls),
        geometry,
    )


def _cubic(value: Cubic7) -> dict[str, str]:
    return value.to_json()


def _vector(vector: Iterable[Cubic7]) -> list[dict[str, str]]:
    return [_cubic(entry) for entry in vector]


