"""Exact H22 Vinberg prefixes for cubic-seven dense root-block lattices.

This module studies

``L_22(a) = <-a> + E8 + E8 + E6``

over ``O_K = Z[theta]``, where ``theta=2*cos(2*pi/7)``.  The three supported
timelike coefficients are ``theta``, ``2*theta`` and
``theta*(2-theta)``.  At the two nondistinguished real places ``-a`` is
positive, so the form is admissible.

The mirror-norm lists are complete.  For a primitive vector ``r=(x,y)`` of
norm ``q``, reflection integrality is ``q | 2 I(r)``, where
``I(r)=(a*x,G_R*y)``.  Away from primes dividing ``2*a*det(R)`` the pairing
ideal is locally the unit ideal.  The only spatial discriminant prime is the
inert prime ``(3)`` from E6.  Its radical modulo three is generated by
``(1,2,0,1,2,0)`` and has square ``12 mod 18``; hence a primitive vector in
that radical has norm valuation exactly one.  The same squarefree local
argument applies at ``(2)`` and, when present, ``(2-theta)``.  Thus each of
these primes occurs with exponent at most one.  Class number one and the
surjective unit-signature map make every totally positive unit a square, so
the explicit canonical generators below lose no mirror orbit.

At height zero, an exact dominant-weight census proves that the reflective
system is precisely ``E8 + E8 + E6``.  Positive levels enumerate Dynkin
weights ``z=G_R*y``.  Rational Schur complements give simultaneous exact
bounds at all three embeddings, and the two E8 blocks are combined with the
E6 block by their exact field-valued squares.  Equal-height Vinberg packets
are selected simultaneously.
"""

