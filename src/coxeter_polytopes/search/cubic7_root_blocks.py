DELTA7 = 2 - THETA7


def _e6_cartan_gram() -> list[list[int]]:
    gram = [[2 if i == j else 0 for j in range(6)] for i in range(6)]
    # Arms of lengths two, two and one at vertex 2.
    for i, j in ((0, 1), (1, 2), (2, 3), (3, 4), (2, 5)):
        gram[i][j] = gram[j][i] = -1
    return gram


@lru_cache(maxsize=1)
def h22_spatial_gram() -> tuple[tuple[int, ...], ...]:
    return tuple(
        tuple(row)
        for row in block_diagonal(
            e8_cartan_gram(), e8_cartan_gram(), _e6_cartan_gram()
        )
    )


