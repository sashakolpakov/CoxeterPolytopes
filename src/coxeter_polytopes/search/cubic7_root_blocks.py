@lru_cache(maxsize=None)
def h22_basis_gram(seed: Cubic7RootBlockSeed) -> Matrix:
    spatial = h22_spatial_gram()
    rank = 23
    rows = [[CUBIC7_ZERO for _ in range(rank)] for _ in range(rank)]
    rows[0][0] = -seed.timelike_coefficient
    for i in range(22):
        for j in range(22):
            rows[i + 1][j + 1] = Cubic7(spatial[i][j])
    return tuple(tuple(row) for row in rows)


def root_block_pair(
    seed: Cubic7RootBlockSeed,
    left: Sequence[Cubic7],
    right: Sequence[Cubic7],
) -> Cubic7:
    if len(left) != 23 or len(right) != 23:
        raise ValueError("an H22 root-block vector has rank 23")
    gram = h22_basis_gram(seed)
    return sum(
        (
            left[i] * gram[i][j] * right[j]
            for i in range(23)
            for j in range(23)
            if gram[i][j]
        ),
        start=CUBIC7_ZERO,
    )


def _quadratic(vector: Sequence[Cubic7], matrix: RationalMatrix) -> Cubic7:
    return sum(
        (
            vector[i] * Cubic7(matrix[i][j]) * vector[j]
            for i in range(len(vector))
            for j in range(len(vector))
            if matrix[i][j]
        ),
        start=CUBIC7_ZERO,
    )


def _mat_vec(matrix: RationalMatrix, vector: Sequence[Cubic7]) -> Vector:
    return tuple(
        sum(
            (
                Cubic7(matrix[i][j]) * vector[j]
                for j in range(len(vector))
                if matrix[i][j]
            ),
            start=CUBIC7_ZERO,
        )
        for i in range(len(matrix))
    )


@lru_cache(maxsize=None)
def _block_data(block: str) -> tuple[RationalMatrix, RationalMatrix, tuple[RationalMatrix, ...]]:
    if block == "E8":
        integral = e8_cartan_gram()
    elif block == "E6":
        integral = _e6_cartan_gram()
    else:
        raise ValueError("block must be E8 or E6")
    gram = tuple(tuple(Fraction(entry) for entry in row) for row in integral)
    inverse = _fraction_inverse(gram)
    return gram, inverse, _prefix_schur_complements(inverse)


def _embedding_integer_upper(value: Cubic7, embedding: int) -> int:
    if value.sign(embedding) < 0:
        raise ValueError("the selected embedding bound is negative")
    upper = 0 if not value else 1
    while (Cubic7(upper) - value).sign(embedding) < 0:
        upper *= 2
    return upper


@lru_cache(maxsize=None)
def _bounded_for_caps(caps: tuple[Cubic7, Cubic7, Cubic7]) -> tuple[Cubic7, ...]:
    return bounded_cubic7_integers(
        tuple(_embedding_integer_upper(cap, place) for place, cap in enumerate(caps))
    )


@dataclass(frozen=True, slots=True)
class DominantBlockWeight:
    square: Cubic7
    weights: Vector
    coordinates: Vector


@dataclass(frozen=True, slots=True)
class DominantBlockEnumeration:
    block: str
    target: Cubic7
    root_norm: Cubic7
    alphabet: tuple[Cubic7, ...]
    visited_by_depth: tuple[int, ...]
    schur_pruned_by_depth: tuple[int, ...]
    identity_pruned_by_depth: tuple[int, ...]
    nonintegral_leaf_count: int
    vectors: tuple[DominantBlockWeight, ...]


@lru_cache(maxsize=None)
def enumerate_dominant_block_weights(
    block: str, target: Cubic7, root_norm: Cubic7
) -> DominantBlockEnumeration:
    """Enumerate all integral dominant block vectors of square at most target."""

    _gram, inverse, schur = _block_data(block)
    rank = len(inverse)
    twice_target = 2 * target
    alphabet = tuple(
        value
        for value in _bounded_for_caps((twice_target, twice_target, twice_target))
        if value.sign(0) >= 0
        and all((twice_target - value * value).sign(place) >= 0 for place in range(3))
        and (2 * value / root_norm).is_integral
    )
    visited = [0] * (rank + 1)
    schur_pruned = [0] * (rank + 1)
    identity_pruned = [0] * (rank + 1)
    nonintegral = 0
    output: list[DominantBlockWeight] = []

    def extend(prefix: Vector) -> None:
        nonlocal nonintegral
        depth = len(prefix)
        visited[depth] += 1
        if depth:
            minimum = _quadratic(prefix, schur[depth - 1])
            if any((target - minimum).sign(place) < 0 for place in range(3)):
                schur_pruned[depth] += 1
                return
            # The inverse Cartan matrices are entrywise nonnegative.  Since
            # every dominant weight is nonnegative at place zero, the energy
            # of an identity-place prefix can only increase on extension.
            prefix_energy = _quadratic(
                prefix,
                tuple(tuple(inverse[i][j] for j in range(depth)) for i in range(depth)),
            )
            if (target - prefix_energy).sign(0) < 0:
                identity_pruned[depth] += 1
                return
        if depth == rank:
            square = _quadratic(prefix, inverse)
            coordinates = _mat_vec(inverse, prefix)
            if not all(entry.is_integral for entry in coordinates):
                nonintegral += 1
                return
            if any((target - square).sign(place) < 0 for place in range(3)):
                raise AssertionError("Schur pruning admitted a block above its target")
            output.append(DominantBlockWeight(square, prefix, coordinates))
            return
        for entry in alphabet:
            extend((*prefix, entry))

    extend(())
    vectors = tuple(sorted(output, key=lambda item: (item.square, item.weights)))
    return DominantBlockEnumeration(
        block=block,
        target=target,
        root_norm=root_norm,
        alphabet=alphabet,
        visited_by_depth=tuple(visited),
        schur_pruned_by_depth=tuple(schur_pruned),
        identity_pruned_by_depth=tuple(identity_pruned),
        nonintegral_leaf_count=nonintegral,
        vectors=vectors,
    )


@dataclass(frozen=True, slots=True)
class H22RootBlockCandidate:
    norm: Cubic7
    height: Cubic7
    control: Cubic7
    target: Cubic7
    vector: Vector


@dataclass(frozen=True, slots=True)
class H22ControlLevel:
    norm: Cubic7
    height: Cubic7
    control: Cubic7
    target: Cubic7


def _control_levels(
    seed: Cubic7RootBlockSeed, height_bound: int
) -> tuple[H22ControlLevel, ...]:
    if height_bound < 0:
        raise ValueError("height_bound must be nonnegative")
    a = seed.timelike_coefficient
    levels: set[H22ControlLevel] = set()
    for norm in seed.canonical_mirror_norms:
        caps = (norm * height_bound / a, norm / (-a), norm / (-a))
        for control in _bounded_for_caps(caps):
            if control.sign(0) <= 0 or not (2 * a * control / norm).is_integral:
                continue
            target = norm + a * control * control
            if any(target.sign(place) < 0 for place in (1, 2)):
                continue
            height = a * control * control / norm
            if (Cubic7(height_bound) - height).sign(0) < 0:
                continue
            levels.add(H22ControlLevel(norm, height, control, target))
    return tuple(sorted(levels, key=lambda item: (item.height, item.norm, item.control)))


@lru_cache(maxsize=None)
def enumerate_h22_control_level(
    seed: Cubic7RootBlockSeed, level: H22ControlLevel
) -> tuple[H22RootBlockCandidate, ...]:
    e8 = enumerate_dominant_block_weights("E8", level.target, level.norm)
    e6 = enumerate_dominant_block_weights("E6", level.target, level.norm)
    e6_buckets: dict[Cubic7, list[DominantBlockWeight]] = {}
    for vector in e6.vectors:
        e6_buckets.setdefault(vector.square, []).append(vector)
    candidates: list[H22RootBlockCandidate] = []
    for first in e8.vectors:
        for second in e8.vectors:
            remainder = level.target - first.square - second.square
            for third in e6_buckets.get(remainder, ()):
                vector = (
                    level.control,
                    *first.coordinates,
                    *second.coordinates,
                    *third.coordinates,
                )
                if root_block_pair(seed, vector, vector) != level.norm:
                    raise AssertionError("block reconstruction returned the wrong root norm")
                candidates.append(
                    H22RootBlockCandidate(
                        level.norm, level.height, level.control, level.target, vector
                    )
                )
    return tuple(sorted(candidates, key=lambda candidate: candidate.vector))


@lru_cache(maxsize=None)
def height_zero_dominant_roots(seed: Cubic7RootBlockSeed) -> tuple[H22RootBlockCandidate, ...]:
    roots: list[H22RootBlockCandidate] = []
    for norm in seed.canonical_mirror_norms:
        level = H22ControlLevel(norm, CUBIC7_ZERO, CUBIC7_ZERO, norm)
        roots.extend(enumerate_h22_control_level(seed, level))
    return tuple(sorted(roots, key=lambda root: (root.norm, root.vector)))


def height_zero_is_e8_e8_e6(seed: Cubic7RootBlockSeed) -> bool:
    roots = height_zero_dominant_roots(seed)
    return len(roots) == 3 and all(root.norm == 2 for root in roots)


@lru_cache(maxsize=1)
def h22_height_zero_simple_roots() -> tuple[Vector, ...]:
    roots: list[Vector] = []
    for index in range(22):
        root = [CUBIC7_ZERO] * 23
        root[index + 1] = -CUBIC7_ONE
        roots.append(tuple(root))
    return tuple(roots)


